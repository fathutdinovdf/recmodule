/* Замеры и суточная агрегация — ядро расчёта фактического эффекта.

   Фактический дебит приходит из ВМАП замерами (параметр 1, «Дебит жидкости
   Замерной»). Замер — это не суточное значение, а мгновенное: столько скважина
   давала в момент замера. Между замерами значение держится — до следующего
   замера ничего другого о скважине не известно.

   Отсюда два правила, оба взяты из того, как устроены сами данные.

   1. Внутри суток замеров может быть несколько. На дев-стенде: 1891 суток с
      одним замером, 991 с двумя, 196 с четырьмя. Среднее арифметическое здесь
      врёт: замер в 08:00 и замер в 22:00 описывают куски суток разной длины.
      Правильная величина — интеграл по времени, то есть площадь под ступенькой,
      делённая на длину суток.

   2. Между замерами бывают разрывы: медиана 11 часов, девяностый перцентиль
      24 часа, максимум — 50 суток. Поэтому последнее известное значение
      протягивается вперёд, пока не появится новое.

   Чего эти правила намеренно НЕ делают: не отличают остановленную скважину от
   скважины без замеров. Если скважина встала, а замеров нет, протяжка покажет
   прежний дебит и завысит факт. Состояние скважины лежит отдельным параметром
   (16 «Состояние по ТМ»), и когда оно появится в выгрузке, ноль состояния
   должен обрывать протяжку. До тех пор это известное ограничение, а не
   недосмотр. */

/* Время замера берётся из CreateDate, а не из FactDate: на выгрузке FactDate
   заполнен у 92 записей из 8994, а CreateDate — у всех и содержит осмысленные
   моменты (01.02 12:00, 01.02 22:06, 02.02 08:13 — интервалы по десять часов).
   UpdateDate для этого не годится вовсе: это момент ночной пакетной загрузки,
   у всей пачки он одинаковый. */

const СУТКИ_МС = 86400000;

/** Начало суток, к которым принадлежит момент. */
function dayStart(t) {
  const d = new Date(t);
  d.setHours(0, 0, 0, 0);
  return d;
}

/** Среднесуточное значение по ряду замеров — интеграл ступенчатой функции.

    Замеры: [{ at: Date|строка, value: число }], порядок любой.
    Возвращает null, если на начало суток значение неизвестно и внутри суток
    замеров не было: ноль здесь означал бы остановленную скважину, а мы про неё
    ничего не знаем. Пустое значение честнее выдуманного нуля.

    coverage — доля суток, покрытая протяжкой от замеров ВНУТРИ этих суток.
    По ней видно, насколько значение опирается на измерения, а насколько на
    предположение о неизменности: сутки с одним утренним замером и сутки с
    четырьмя — разного качества, и в спорном расчёте это должно быть видно. */
function dailyAverage(замеры, день) {
  const начало = dayStart(день).getTime();
  const конец = начало + СУТКИ_МС;

  const точки = замеры
    .map((з) => ({ t: (з.at instanceof Date ? з.at : new Date(з.at)).getTime(), v: з.value }))
    .filter((з) => Number.isFinite(з.v) && Number.isFinite(з.t))
    .sort((a, b) => a.t - b.t);

  /* Значение на начало суток — последний замер, сделанный до них. Именно оно
     держится до первого замера внутри суток, и без него сутки начинаются
     с неизвестности. */
  let текущее = null;
  for (const з of точки) {
    if (з.t <= начало) текущее = з.v; else break;
  }

  const внутри = точки.filter((з) => з.t > начало && з.t < конец);
  if (текущее === null && !внутри.length) return null;

  let площадь = 0;
  let курсор = начало;

  for (const з of внутри) {
    if (текущее !== null) площадь += текущее * (з.t - курсор);
    else площадь += з.v * (з.t - курсор);   // до первого замера суток тянем его назад
    курсор = з.t;
    текущее = з.v;
  }
  площадь += текущее * (конец - курсор);

  /* Покрытие считается от первого замера этих суток до их конца: именно этот
     кусок опирается на сегодняшние измерения, а всё до него — на протяжку из
     прошлых суток. Сутки с замером в 03:28 покрыты на 86 %, сутки без замеров
     вовсе — на ноль, и по этому числу видно, чему в расчёте верить. */
  return {
    value: площадь / СУТКИ_МС,
    coverage: внутри.length ? (конец - внутри[0].t) / СУТКИ_МС : 0,
    points: внутри.length,
  };
}

/** Ряд среднесуточных значений за период [от, до] включительно.
    Замеры за пределами периода нужны обязательно: первый день опирается на
    последний замер перед ним. */
function dailySeries(замеры, от, до) {
  const out = [];
  const конец = dayStart(до).getTime();
  for (let t = dayStart(от).getTime(); t <= конец; t += СУТКИ_МС) {
    const день = new Date(t);
    out.push({ date: день, ...(dailyAverage(замеры, день) || { value: null, coverage: 0, points: 0 }) });
  }
  return out;
}

/** Нефть из жидкости: Qн = Qж × (1 − обводнённость) × плотность.
    Обводнённость объёмная, в процентах; плотность нефти в стандартных
    условиях, кг/м³. Формула — из «Пояснений» Формы 5. */
function oilFromLiquid(qzh, watercutPct, density) {
  if (!Number.isFinite(qzh) || !Number.isFinite(watercutPct) || !Number.isFinite(density)) return null;
  return qzh * (1 - watercutPct / 100) * (density / 1000);
}
