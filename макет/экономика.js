/* Разворачиваем один раз при загрузке. Ключ — «индекс месторождения + номер»:
   номер скважины уникален внутри месторождения, но не между ними. */
const ECON_FIELD_INDEX = Object.fromEntries(ECON_FIELD_RATES.map((r, i) => [r.field, i]));

const ECON_WELL_INDEX = (() => {
  const m = new Map();
  for (const [f, n, i, p] of ECON_WELL_RATES) {
    m.set(f + '\u0000' + normWell(n), { rateIndex: i, plast: p });
  }
  return m;
})();

/** Экономика скважины: ставки, пласт и признак полноты данных.
    Возвращает null, если месторождения нет в модели Заказчика или скважина
    в неё не попала, — расчёт в этом случае не делается вовсе. Молча взять
    чужую или устаревшую ставку нельзя: ошибка в разы не видна на экране. */
function wellEconomy(field, well) {
  const fi = ECON_FIELD_INDEX[field];
  if (fi === undefined) return null;
  const поле = ECON_FIELD_RATES[fi];
  if (!поле.source) return null;
  const запись = ECON_WELL_INDEX.get(fi + '\u0000' + normWell(well));
  if (!запись) return null;
  const ндпи = ECON_NDPI_RATES[запись.rateIndex];
  return {
    field: поле.field,
    source: поле.source,
    plast: запись.plast,
    taxPlast: ндпи.plast,
    ndpi: ндпи.rate,
    eeLiquid: поле.eeLiquid,
    eeOil: поле.eeOil,
    chem: поле.chem,
    oilPrice: ECON_GLOBAL.oilPrice,
  };
}

/** Эффект за сутки, руб. Принимает приросты: жидкость м³/сут, нефть т/сут.
    Возвращает разложение по статьям — карточке нужна не только сумма, но и
    то, из чего она сложилась: спор с Заказчиком идёт по статьям. */
function dailyEffect(econ, dQzh, dQn) {
  if (!econ) return null;
  const выручка = dQn * econ.oilPrice;
  const ндпи = dQn * econ.ndpi;
  const ээЖидкость = dQzh * econ.eeLiquid;
  const ээНефть = dQn * econ.eeOil;
  const реагенты = dQn * econ.chem;
  return {
    revenue: выручка,
    ndpi: ндпи,
    eeLiquid: ээЖидкость,
    eeOil: ээНефть,
    chem: реагенты,
    total: выручка - ндпи - ээЖидкость - ээНефть - реагенты,
  };
}
