function addHours(d, h) { return new Date(d.getTime() + h * 3600 * 1000); }
function addDays(d, n) { return new Date(d.getTime() + n * 86400 * 1000); }

/* ---------- рабочее окно ----------
   Пн–пт, 09:00–24:00 по Когалыму. Рекомендация, зарегистрированная вне окна,
   не уходит Заказчику сразу: она ждёт открытия рабочего дня. Поэтому статусы
   «Зарегистрировано» и «Передано Заказчику» — разные состояния, а не одно
   мгновение, и у рекомендации две разные отметки времени.
   Норматив ответа тоже считается рабочими часами: иначе срок в 4 часа по
   рекомендации, переданной в 22:00, истекал бы в два часа ночи. */

const WORK_FROM = 9;   // час начала
const WORK_TO = 24;    // час окончания
const WORK_HOURS = WORK_TO - WORK_FROM;

/** Локальное время в формате YYYY-MM-DDTHH:MM. Через toISOString нельзя:
    он переводит в UTC, и сгенерированный вечер превращается в день. */
function local16(d) {
  const p = (n) => String(n).padStart(2, '0');
  return `${d.getFullYear()}-${p(d.getMonth() + 1)}-${p(d.getDate())}T${p(d.getHours())}:${p(d.getMinutes())}`;
}

/** Локальная дата YYYY-MM-DD. Через toISOString нельзя по той же причине. */
function day(d) {
  const p = (n) => String(n).padStart(2, '0');
  return `${d.getFullYear()}-${p(d.getMonth() + 1)}-${p(d.getDate())}`;
}

function isWorkday(d) { const w = d.getDay(); return w >= 1 && w <= 5; }

function inWindow(d) {
  return isWorkday(d) && d.getHours() >= WORK_FROM && d.getHours() < WORK_TO;
}

/** Ближайший момент внутри рабочего окна: сам момент либо начало ближайшего дня. */
function toWindow(d) {
  /* Дата без времени («2026-07-03») по стандарту разбирается как UTC и в
     местном поясе съезжает. Сюда такие строки сегодня не попадают, но защита
     дешевле, чем разбирательство, почему срок уехал на сутки. */
  const x = new Date(d instanceof Date ? d
    : (/^\d{4}-\d{2}-\d{2}$/.test(d) ? `${d}T00:00` : d));
  if (inWindow(x)) return x;
  if (isWorkday(x) && x.getHours() < WORK_FROM) {
    x.setHours(WORK_FROM, 0, 0, 0);
    return x;
  }
  do {
    x.setDate(x.getDate() + 1);
    x.setHours(WORK_FROM, 0, 0, 0);
  } while (!isWorkday(x));
  return x;
}

/** Прибавить рабочие часы, перешагивая через ночи и выходные. */
function addWorkHours(from, hours) {
  let cur = toWindow(from);
  let left = hours;
  while (left > 0) {
    const endOfDay = new Date(cur);
    endOfDay.setHours(WORK_TO, 0, 0, 0);
    const avail = (endOfDay - cur) / 3600000;
    if (left <= avail) return addHours(cur, left);
    left -= avail;
    cur = toWindow(endOfDay);
  }
  return cur;
}

/** Сколько рабочих часов между двумя моментами. */
function workHoursBetween(a, b) {
  if (b <= a) return 0;
  let cur = toWindow(a);
  let acc = 0;
  while (cur < b) {
    const endOfDay = new Date(cur);
    endOfDay.setHours(WORK_TO, 0, 0, 0);
    const stop = b < endOfDay ? b : endOfDay;
    acc += (stop - cur) / 3600000;
    if (b <= endOfDay) break;
    cur = toWindow(endOfDay);
  }
  return acc;
}

/* Ожидаемый эффект, выведенный из строки-семени, а не из общего генератора.
   Нужен там, где поле надо доиграть отдельной записи: у реальных строк Формы 2
   его нет в источнике, а у ночной восьмёрки розыгрыш мог выдать «черновик».
   Через общий rnd() так делать нельзя — лишний вызов сдвигает всю остальную
   синтетику, и номера рекомендаций в скриншотах и документах протухают. */
function seededExpect(seed) {
  const qzh = +(2 + (hash(seed) % 180) / 10).toFixed(1);
  return {
    expectQzh: qzh,
    /* Та же связь нефти с жидкостью, что и в генераторе: доля × плотность. */
    expectQn: +(qzh * (0.1 + (hash(seed + '·нефть') % 56) / 100) * 0.86).toFixed(2),
    expectEE: -400 + (hash(seed + '·ээ') % 900),
    forecast: (50 + (hash(seed + '·руб') % 900)) * 1000,
  };
}

