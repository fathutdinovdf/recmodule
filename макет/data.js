/** Видит ли пользователь рекомендацию: зона по объектам плюс именной отбор
    у эксперта. Общая для инбокса и реестра — иначе счётчики разойдутся. */
function inScope(user, rec) {
  if (user.executor && rec.executor !== user.executor) return false;
  return !user.zone.length || user.zone.includes(rec.field);
}

/* Месторождения, кусты и скважины приходят из вмап.js — он собран из выгрузки
   с дев-стенда ВМАП по ТПП «Когалымнефтегаз» и подключается к странице раньше
   этого файла. Оттуда же FIELDS, FIELD_CODE, FIELD_STATS и WELL_INDEX. */

function hash(s) {
  let h = 0;
  for (const ch of String(s)) h = (h * 31 + ch.codePointAt(0)) >>> 0;
  return h;
}

/** Месторождение и куст рекомендации.

    У синтетики они пришли вместе со скважиной из выгрузки — искать нечего.
    У записей Формы 2 есть только номер, и его приходится разрешать по ВМАП;
    номер не уникален даже внутри ТПП, поэтому куст из формы работает
    уточнением. Источником истины остаётся ВМАП: у скважины 184р в форме стоит
    куст 184, в базе 0 — берём 0.

    Скважина 129к в ТПП «Когалымнефтегаз» не нашлась вовсе: номера по компании
    повторяются, и она принадлежит другому ДО. Для таких месторождение
    проставляется детерминированно, чтобы запись не выпала из реестра. */
function resolveWell(rec) {
  if (rec.field) return { field: rec.field, kust: rec.kust };
  const w = findWell(rec.well, rec.kust);
  if (w) return { field: w.field, kust: w.kust };
  return { field: FIELDS[hash(rec.well) % FIELDS.length], kust: rec.kust || '—' };
}

