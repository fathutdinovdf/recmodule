'use strict';

/* Общий слой для всех проверок: загрузка макета и единый формат отчёта.

   Почему загрузка через `new Function`, а не через `require`: `макет/data.js` —
   не модуль, а обычный скрипт для тега <script>. Он ничего не экспортирует, и
   переписывать его ради проверок нельзя — макет должен остаться тем же файлом,
   который открывается двойным кликом без сборщика. Поэтому исходник читается
   как текст, к нему дописывается `return` со списком нужных имён, и всё это
   исполняется как тело функции: значения видны, файл не тронут. */

const fs = require('fs');
const path = require('path');

const КОРЕНЬ = path.resolve(__dirname, '..');
const МАКЕТ = path.join(КОРЕНЬ, 'макет');

/** Читает файл макета как текст. Отдельная функция, чтобы во всех проверках
    был один и тот же путь и одна и та же кодировка. */
function исходник(имя) {
  return fs.readFileSync(path.join(МАКЕТ, имя), 'utf8');
}

/** Загружает data.js и возвращает всё, что в нём объявлено верхним уровнем.
    Список имён приходится перечислять руками: у скрипта нет экспорта, а брать
    всё подряд через `eval` в текущей области — значит затянуть в проверку сотни
    посторонних имён и потерять контроль над тем, что именно проверяется. */
function загрузитьДанные() {
  /* вмап.js подключается к каждой странице раньше data.js и держит справочные
     данные ВМАП: месторождения, скважины и разрешение номера в объект.
     Порядок здесь тот же, иначе data.js не соберётся. */
  const код = `${исходник('вмап.js')}\n;${исходник('data.js')}`;
  const экспорт = `
    ; return {
      NOW, DATA, TILES, STATUSES, PRIORITIES, DECISIONS, DIRECTIONS,
      EXECUTORS, CUSTOMERS, COMPLETENESS, STATUS_TONE, SLA_VISIBLE_STATUSES,
      MODULE_PARAMS, REJECT_REASONS, CLARIFY_REASONS,
      FIELDS, FIELD_CODE, FIELD_STATS, WELLS, VMAP_FIELDS, VMAP_WELLS,
      WELL_INDEX, findWell, wellsOfField, resolveWell,
      OUTCOME_MIX, OUTCOME_DECISION, COMMENTS_EXEC, COMMENTS_CUST,
      WORK_FROM, WORK_TO, REAL,
      day, local16, hash, isWorkday, inWindow, toWindow,
      addWorkHours, workHoursBetween, addDays, addHours
    };`;
  return new Function(код + экспорт)();
}

/* Дата без времени («2026-07-03») по стандарту разбирается как UTC и в местном
   поясе съезжает. Проверки обязаны читать такие строки ровно так же, как их
   читает макет (функция toDate в card.js), иначе проверка ловила бы не ошибку
   макета, а собственное расхождение в разборе строк. */
function дата(v) {
  if (v === null || v === undefined || v === '') return null;
  if (v instanceof Date) return v;
  return new Date(/^\d{4}-\d{2}-\d{2}$/.test(v) ? `${v}T00:00` : v);
}

/** Локальная дата YYYY-MM-DD — тот же формат, что day() в data.js. */
function день(d) {
  const p = (n) => String(n).padStart(2, '0');
  return `${d.getFullYear()}-${p(d.getMonth() + 1)}-${p(d.getDate())}`;
}

/* ------------------------------ отчёт ------------------------------ */

/* Уровни разведены намеренно. «Нарушение» — расхождение с зафиксированным
   решением: набор данных или макет противоречат документу, прогон обязан упасть.
   «Предупреждение» — место, где решение допускает толкования или где дефект
   косметический: падать нельзя, иначе прогон перестанут запускать, но и молчать
   нельзя, иначе о нём забудут. */
class Отчёт {
  constructor(имя) {
    this.имя = имя;
    this.правила = [];        // список проверенных правил — видно, что вообще проверяется
    this.нарушения = [];
    this.предупреждения = [];
    this.разделы = [];        // произвольные сводки, печатаются до списка нарушений
  }

  /** Регистрирует правило. Возвращает функцию, которой правило докладывает
      о каждом найденном нарушении — так номер правила нельзя забыть указать. */
  правило(код, описание) {
    this.правила.push({ код, описание });
    return {
      сбой: (сообщение) => this.нарушения.push({ код, сообщение }),
      предупреждение: (сообщение) => this.предупреждения.push({ код, сообщение }),
    };
  }

  раздел(заголовок, строки) {
    this.разделы.push({ заголовок, строки });
  }

  /** Печатает отчёт и возвращает код возврата: 0 — чисто, 1 — есть нарушения. */
  печать({ подробно = true } = {}) {
    const п = (s) => process.stdout.write(s + '\n');
    п('');
    п(`=== ${this.имя} ===`);
    for (const р of this.разделы) {
      п('');
      п(р.заголовок);
      for (const с of р.строки) п('  ' + с);
    }
    п('');
    п(`Правил проверено: ${this.правила.length}`);

    if (this.предупреждения.length) {
      п('');
      п(`Предупреждений: ${this.предупреждения.length}`);
      if (подробно) for (const в of this.предупреждения) п(`  [${в.код}] ${в.сообщение}`);
    }

    if (!this.нарушения.length) {
      п('');
      п('Нарушений нет.');
      return 0;
    }

    п('');
    п(`НАРУШЕНИЙ: ${this.нарушения.length}`);
    const поКоду = new Map();
    for (const н of this.нарушения) {
      if (!поКоду.has(н.код)) поКоду.set(н.код, []);
      поКоду.get(н.код).push(н.сообщение);
    }
    for (const [код, список] of поКоду) {
      const правило = this.правила.find((р) => р.код === код);
      п('');
      п(`  [${код}] ${правило ? правило.описание : ''} — ${список.length} шт.`);
      const показать = подробно ? список : список.slice(0, 5);
      for (const с of показать) п(`      ${с}`);
      if (!подробно && список.length > показать.length) {
        п(`      … и ещё ${список.length - показать.length}`);
      }
    }
    return 1;
  }
}

module.exports = { КОРЕНЬ, МАКЕТ, исходник, загрузитьДанные, дата, день, Отчёт };
