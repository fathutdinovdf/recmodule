'use strict';

/* Дисциплина дизайн-системы: всё, что видно глазом, идёт через tokens.css.

   Правило принято ради одной операции — подмены палитры ВМАП без правки
   разметки. Любой цвет, вписанный в макет напрямую, эту операцию ломает
   молча: тема переключится, а одно место останется прежним, и заметят это
   не при подмене, а через месяц на демонстрации.

   Отдельно проверяется обратное направление — что каждая переменная, на
   которую макет ссылается, в tokens.css существует. Сборщика в проекте нет,
   опечатка в имени переменной не ломает ничего: `var(--text-secondry)` просто
   даёт пустое значение, свойство выпадает, элемент наследует цвет родителя.
   Такое находят только глазами и только если знают, куда смотреть. */

const fs = require('fs');
const path = require('path');
const { КОРЕНЬ, МАКЕТ, загрузитьДанные, Отчёт } = require('./общее.js');

const отчёт = new Отчёт('Дисциплина дизайн-системы');

const ФАЙЛЫ_CSS = fs.readdirSync(МАКЕТ).filter((f) => f.endsWith('.css')).sort();
const ТОКЕНЫ_ПУТЬ = path.join(КОРЕНЬ, 'tokens.css');
const ТОКЕНЫ_ТЕКСТ = fs.readFileSync(ТОКЕНЫ_ПУТЬ, 'utf8');

/* ------------------------------ разбор tokens.css ------------------------------ */

/** Имя переменной → её значение (последнее объявление в файле, тем по темам). */
const ТОКЕНЫ = new Map();
for (const m of ТОКЕНЫ_ТЕКСТ.matchAll(/^[^\S\n]*(--[a-z0-9-]+)\s*:\s*([^;]+);/gmi)) {
  ТОКЕНЫ.set(m[1], m[2].trim());
}

/* Значение в пикселях → имена переменных с этим значением, по категориям.
   Категория нужна, чтобы проверка не советовала --line-height-h3 вместо
   ширины кнопки только потому, что там тоже 28px: совет должен быть
   применимым, иначе его перестанут читать. */
const КАТЕГОРИИ = [
  { имя: 'отступ', свойства: /^(padding|margin)(-(top|right|bottom|left|inline|block))?$/, префикс: /^--(item|group|block|section|screen)-padding-/ },
  { имя: 'зазор', свойства: /^(gap|row-gap|column-gap)$/, префикс: /-gap-/ },
  { имя: 'радиус', свойства: /^border-radius$/, префикс: /^--corner-radius-/ },
  /* Сокращённая запись `font:` проверяется той же категорией: в макете кегль
     задаётся почти всегда через неё, и без этой строки хардкод вроде
     `font: 700 30px/1.2 …` проверка бы не увидела вовсе. */
  { имя: 'кегль', свойства: /^(font|font-size)$/, префикс: /^--font-size-/ },
  { имя: 'интерлиньяж', свойства: /^line-height$/, префикс: /^--line-height-/ },
  { имя: 'трекинг', свойства: /^letter-spacing$/, префикс: /^--letter-spacing-/ },
  { имя: 'размер', свойства: /^(width|height|min-width|min-height|max-width|max-height)$/, префикс: /^--(sizing|layout)-/ },
];

function токенДляЗначения(категория, значение) {
  for (const [имя, знач] of ТОКЕНЫ) {
    if (категория.префикс.test(имя) && знач === значение) return имя;
  }
  return null;
}

/* ------------------------------ комментарии и секции ------------------------------ */

/* Осознанное отступление от токенов отличается от небрежности ровно одним —
   рядом написано, почему так. Проверка ищет обосновывающий комментарий и
   считает, что он действует до следующего разделителя секции: именно так
   комментарии в макете и написаны — шапкой к разделу, а не к строке. */
const СЛОВА_ОБОСНОВАНИЯ = /осознанн|намеренно|единичн|выход(ят|ит) за|не распространяется|исключени/i;
const РАЗДЕЛИТЕЛЬ = /-{6,}/;

/* Комментарий описывает отступление словами, а не числом: «размер номера».
   Крошечный словарь связывает такое слово с фрагментом селектора и с тем
   свойством, о котором в комментарии речь. Без ограничения по свойству
   комментарий «пилюля… намеренно уходит назад» оправдывал бы у пилюли вообще
   всё, включая высоту, о которой там ни слова. */
const СЛОВО_К_СЕЛЕКТОРУ = [
  [/номер/i, /num/i, /^font(-size)?$/],
  [/пилюл/i, /(pill|chip)/i, /^border-radius$/],
];

function разобратьКомментарии(текст) {
  const список = [];
  for (const m of текст.matchAll(/\/\*[\s\S]*?\*\//g)) {
    список.push({
      начало: текст.slice(0, m.index).split('\n').length,
      конец: текст.slice(0, m.index + m[0].length).split('\n').length,
      текст: m[0],
      разделитель: РАЗДЕЛИТЕЛЬ.test(m[0]),
      обоснование: СЛОВА_ОБОСНОВАНИЯ.test(m[0]),
    });
  }
  return список;
}

/** Обосновывающий комментарий, в зоне действия которого лежит строка. */
function обоснование(комментарии, строка) {
  let найдено = null;
  for (const c of комментарии) {
    if (c.конец >= строка) break;
    if (c.разделитель) найдено = c.обоснование ? c : null;
    else if (c.обоснование) найдено = c;
  }
  return найдено;
}

/** Названо ли отступление в тексте обоснования — значением или словом.

    Значение ищется по границам числа, а не подстрокой: «999px» содержит в себе
    «9px», и без границы комментарий про радиус пилюли молча оправдывал бы
    девятипиксельный кружок статуса тремя правилами ниже. */
function названо(комментарий, значение, селектор, свойство) {
  if (!комментарий) return false;
  const граница = new RegExp(`(?<![\\d.])${значение.replace('.', '\\.')}(?![\\d])`);
  if (граница.test(комментарий.текст)) return true;
  return СЛОВО_К_СЕЛЕКТОРУ.some(([слово, фрагмент, свойства]) =>
    слово.test(комментарий.текст) && фрагмент.test(селектор) && свойства.test(свойство));
}

/* ------------------------------ разбор объявлений CSS ------------------------------ */

/** Плоский список объявлений: файл, строка, селектор, свойство, значение. */
function объявления(текст) {
  const без = текст.replace(/\/\*[\s\S]*?\*\//g, (m) => m.replace(/[^\n]/g, ' '));
  const результат = [];
  const блок = /([^{}]+)\{([^{}]*)\}/g;
  let m;
  while ((m = блок.exec(без))) {
    const селектор = m[1].trim().replace(/\s+/g, ' ');
    const телоНачало = m.index + m[1].length + 1;
    for (const d of m[2].matchAll(/([a-z-]+)\s*:\s*([^;]+)/gi)) {
      результат.push({
        селектор,
        свойство: d[1].trim().toLowerCase(),
        значение: d[2].trim(),
        строка: без.slice(0, телоНачало + d.index).split('\n').length,
      });
    }
  }
  return результат;
}

/* ------------------------------ 1. цвета ------------------------------ */

/* Именованные цвета CSS выглядят безобидно, но это такой же хардкод:
   `color: white` в тёмной теме останется белым. Служебные значения —
   transparent, currentColor, inherit — не цвета, а способ ничего не задавать
   или наследовать заданное, поэтому разрешены. */
const ИМЕНОВАННЫЕ = /\b(white|black|red|green|blue|gray|grey|silver|orange|yellow|purple|pink|brown|navy|teal|olive|maroon|lime|aqua|fuchsia|darkgray|lightgray|whitesmoke)\b/i;
const РАЗРЕШЕНО = /\b(transparent|currentcolor|inherit|initial|unset|none|auto)\b/i;

{
  const р = отчёт.правило('Т-01', 'Цвета задаются только переменными tokens.css');
  const исключения = [];
  for (const файл of ФАЙЛЫ_CSS) {
    const текст = fs.readFileSync(path.join(МАКЕТ, файл), 'utf8');
    const комментарии = разобратьКомментарии(текст);
    for (const о of объявления(текст)) {
      const хекс = о.значение.match(/#[0-9a-f]{3,8}\b/i);
      const функц = о.значение.match(/\b(rgba?|hsla?)\s*\(/i);
      const имя = !РАЗРЕШЕНО.test(о.значение) && о.значение.match(ИМЕНОВАННЫЕ);
      const найдено = хекс ? хекс[0] : функц ? функц[0] : имя ? имя[0] : null;
      if (!найдено) continue;
      const об = обоснование(комментарии, о.строка);
      const сообщение = `${файл}:${о.строка} — «${о.селектор} { ${о.свойство}: ${о.значение} }» цвет вписан напрямую`;
      if (названо(об, найдено, о.селектор, о.свойство)) исключения.push(`${сообщение}; обосновано комментарием на строке ${об.начало}`);
      else р.сбой(сообщение);
    }
  }
  if (исключения.length) отчёт.раздел('Цвета — исключения с обоснованием:', исключения);
}

/* ------------------------------ 2. существование переменных ------------------------------ */

{
  /* Класс ошибок, специфичный для проекта без сборщика: опечатка в имени
     переменной не ломает ничего заметного. Свойство просто не применяется —
     текст наследует цвет родителя, отступ схлопывается в ноль. */
  const р = отчёт.правило('Т-02', 'Каждая переменная var(--…) объявлена в tokens.css');
  for (const файл of ФАЙЛЫ_CSS) {
    const текст = fs.readFileSync(path.join(МАКЕТ, файл), 'utf8');
    const свои = new Set([...текст.matchAll(/^[^\S\n]*(--[a-z0-9-]+)\s*:/gmi)].map((m) => m[1]));
    for (const m of текст.matchAll(/var\(\s*(--[a-z0-9-]+)\s*(,\s*([^)]*))?\)/gi)) {
      const имя = m[1];
      if (ТОКЕНЫ.has(имя) || свои.has(имя)) continue;
      const строка = текст.slice(0, m.index).split('\n').length;
      const запасное = m[3] && m[3].trim();
      if (запасное) {
        /* Запасное значение спасает вёрстку, но прячет расхождение: значение
           живёт в макете, а не в дизайн-системе, и при подмене палитры ВМАП
           останется прежним. */
        р.сбой(`${файл}:${строка} — переменной ${имя} нет в tokens.css; работает запасное значение «${запасное}», `
          + 'то есть значение фактически захардкожено мимо дизайн-системы');
      } else {
        р.сбой(`${файл}:${строка} — переменной ${имя} нет в tokens.css и запасного значения нет: свойство молча выпадает`);
      }
    }
  }
}

{
  /* Обратная сторона: токен объявлен, но им никто не пользуется. Не ошибка,
     но повод при следующей выгрузке из Figma не тащить лишнее. */
  const р = отчёт.правило('Т-03', 'Объявленные токены используются макетом');
  const весьCSS = ФАЙЛЫ_CSS.map((f) => fs.readFileSync(path.join(МАКЕТ, f), 'utf8')).join('\n')
    + ТОКЕНЫ_ТЕКСТ
    + fs.readdirSync(МАКЕТ).filter((f) => /\.(js|html)$/.test(f))
      .map((f) => fs.readFileSync(path.join(МАКЕТ, f), 'utf8')).join('\n');
  const неиспользуемые = [...ТОКЕНЫ.keys()].filter((имя) => {
    const без = весьCSS.split(new RegExp(`${имя}\\s*:`)).join('');
    return !без.includes(имя);
  });
  if (неиспользуемые.length) {
    р.предупреждение(`макет не использует ${неиспользуемые.length} из ${ТОКЕНЫ.size} токенов: `
      + неиспользуемые.join(', '));
  }
}

/* ------------------------------ 3. магические значения ------------------------------ */

{
  const р = отчёт.правило('Т-04', 'Отступы, радиусы, кегли и размеры берутся из шкалы токенов');
  const исключения = [];
  const внеШкалы = [];
  for (const файл of ФАЙЛЫ_CSS) {
    const текст = fs.readFileSync(path.join(МАКЕТ, файл), 'utf8');
    const комментарии = разобратьКомментарии(текст);
    for (const о of объявления(текст)) {
      const кат = КАТЕГОРИИ.find((k) => k.свойства.test(о.свойство));
      if (!кат) continue;
      for (const m of о.значение.matchAll(/(?<![-\w.])(\d+(?:\.\d+)?)px/g)) {
        const значение = `${m[1]}px`;
        /* Волосяные линии и микросдвиги (1–2 px) шкалой токенов не покрыты и
           покрыты быть не могут: это не отступ, а граница пикселя. */
        if (Number(m[1]) <= 2) continue;
        /* Значение внутри var(…, запасное) уже разобрано правилом Т-02. */
        if (/var\(/.test(о.значение) && о.значение.indexOf('var(') < m.index) continue;

        const токен = токенДляЗначения(кат, значение);
        const об = обоснование(комментарии, о.строка);
        const где = `${файл}:${о.строка} — «${о.селектор} { ${о.свойство}: ${о.значение} }»`;

        /* Порядок веток важен. Комментарий оправдывает только то, чего в
           дизайн-системе нет: если переменная с таким значением существует,
           никакое обоснование не объясняет, почему её не поставили — это
           бесплатно. Иначе один комментарий в шапке секции постепенно
           накрывает собой всю секцию, и проверка перестаёт что-либо ловить. */
        if (токен) {
          р.сбой(`${где} — ${кат.имя} ${значение} есть в дизайн-системе как ${токен}`);
        } else if (названо(об, значение, о.селектор, о.свойство)) {
          исключения.push(`${где}; ${кат.имя} вне токенов, обосновано комментарием на строке ${об.начало}`);
        } else {
          внеШкалы.push(`${где} — ${кат.имя} ${значение} вне шкалы токенов, подходящей переменной нет`);
        }
      }
    }
  }
  if (исключения.length) отчёт.раздел('Размеры — исключения с обоснованием:', исключения);
  for (const с of внеШкалы) р.предупреждение(с);
}

/* ------------------------------ 4. защита атрибута hidden ------------------------------ */

{
  /* У правила браузера для атрибута hidden минимальная специфичность: любой
     наш класс с display: flex его молча перебивает, и элемент, помеченный
     hidden, остаётся на экране. В проекте это выстрелило дважды — на кнопке
     сброса фильтров и на поповере. Закрыто одним правилом в registry.css;
     проверка следит, что оно на месте и что ниже по каскаду его не отменили. */
  const р = отчёт.правило('Т-05', 'Атрибут hidden защищён от перебивания классами');
  const registry = fs.readFileSync(path.join(МАКЕТ, 'registry.css'), 'utf8');
  const защита = /\[hidden\]\s*\{[^}]*display\s*:\s*none\s*!important/i.exec(registry);
  if (!защита) {
    р.сбой('в registry.css нет правила [hidden] { display: none !important; } — '
      + 'любой класс с display перебьёт атрибут hidden, и скрытый элемент останется на экране');
  } else {
    const строкаЗащиты = registry.slice(0, защита.index).split('\n').length;
    if (строкаЗащиты > 40) {
      р.предупреждение(`защита [hidden] стоит на строке ${строкаЗащиты}; она должна идти в самом начале файла, `
        + 'иначе легко не заметить и продублировать');
    }
    /* Отмена возможна только другим правилом на тот же атрибут: перебить
       !important обычным классом нельзя. Ищем именно такие. */
    for (const файл of ФАЙЛЫ_CSS) {
      const текст = fs.readFileSync(path.join(МАКЕТ, файл), 'utf8');
      for (const о of объявления(текст)) {
        if (!/\[hidden\]/.test(о.селектор)) continue;
        if (о.свойство !== 'display') continue;
        if (/^none\b/.test(о.значение)) continue;
        р.сбой(`${файл}:${о.строка} — «${о.селектор} { display: ${о.значение} }» отменяет защиту атрибута hidden`);
      }
    }
  }
}

/* ------------------------------ 5. рассинхрон CSS и данных ------------------------------ */

{
  /* Сетка плиток задана числом колонок в CSS, а число плиток — массивом в
     data.js. Эти два числа связаны только человеческой памятью: когда плиток
     стало семь вместо восьми, сетка осталась repeat(8, …) и правый край
     реестра обрезался. Проверка связывает их обратно. */
  const р = отчёт.правило('Т-06', 'Число колонок сетки плиток совпадает с числом плиток в data.js');
  const { TILES } = загрузитьДанные();
  const registry = fs.readFileSync(path.join(МАКЕТ, 'registry.css'), 'utf8');
  const о = объявления(registry).find((x) => /\.tiles\b/.test(x.селектор) && x.свойство === 'grid-template-columns');
  if (!о) {
    р.сбой('в registry.css не найдено правило .tiles { grid-template-columns: … } — '
      + 'сетку плиток нельзя сверить с данными');
  } else {
    const m = о.значение.match(/repeat\(\s*(\d+)/);
    if (!m) {
      р.предупреждение(`.tiles задана как «${о.значение}» — число колонок не выражено repeat(N), сверить с данными нельзя`);
    } else if (Number(m[1]) !== TILES.length) {
      р.сбой(`registry.css:${о.строка} — сетка плиток на ${m[1]} колонок, а плиток в data.js ${TILES.length}: `
        + `${Number(m[1]) > TILES.length ? 'справа останется пустая колонка' : 'правые плитки обрежутся'}`);
    }
  }

  /* Прочие жёстко заданные repeat(N) показываем списком: их немного, и каждый
     стоит хоть раз сверить глазами с тем, что рисует скрипт. */
  const прочие = [];
  for (const файл of ФАЙЛЫ_CSS) {
    const текст = fs.readFileSync(path.join(МАКЕТ, файл), 'utf8');
    for (const x of объявления(текст)) {
      const m = /repeat\(\s*(\d+)/.exec(x.значение);
      if (m && !/\.tiles\b/.test(x.селектор)) прочие.push(`${файл}:${x.строка} — ${x.селектор} → repeat(${m[1]}, …)`);
    }
  }
  if (прочие.length) отчёт.раздел('Прочие жёстко заданные repeat(N) — сверить глазами:', прочие);
}

/* ------------------------------ 6. значения в разметке и скриптах ------------------------------ */

{
  /* Инлайновый style в шаблонном литерале — та же дыра в дизайн-системе, что
     и хардкод в CSS, только искать её приходится в JS. */
  const р = отчёт.правило('Т-07', 'В разметке и скриптах нет инлайновых стилей с числами и цветами');
  for (const файл of fs.readdirSync(МАКЕТ).filter((f) => /\.(js|html)$/.test(f))) {
    const текст = fs.readFileSync(path.join(МАКЕТ, файл), 'utf8');
    for (const m of текст.matchAll(/style\s*=\s*"([^"]+)"/g)) {
      const значение = m[1];
      const строка = текст.slice(0, m.index).split('\n').length;
      if (/#[0-9a-f]{3,8}\b|rgba?\(/i.test(значение)) {
        р.сбой(`${файл}:${строка} — инлайновый стиль с цветом: style="${значение}"`);
      } else if (/\d+px/.test(значение)) {
        р.предупреждение(`${файл}:${строка} — инлайновый стиль с размером мимо токенов: style="${значение}"`);
      }
    }
  }
}

