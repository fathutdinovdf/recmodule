/* Проверка исходников макета на классы ошибок, которые уже случались.

   Каждое правило здесь родилось из конкретного дефекта, который нашли глазами
   на скриншоте. Регрессия таких мест ничего не ломает громко: страница
   рисуется, скрипт не падает, а неверно оказываются одни сутки, один отступ
   или одно слово. Поэтому проверка статическая, по тексту исходника: заметить
   это в отрисованном виде можно, только если знаешь, куда смотреть. */

const fs = require('fs');
const path = require('path');
const { МАКЕТ, исходник, загрузитьДанные, Отчёт } = require('./общее.js');

const отчёт = new Отчёт('Исходники макета');

const ФАЙЛЫ_JS = ['app.js', 'card.js', 'data.js', 'wizard.js'];
const ФАЙЛЫ_HTML = ['index.html', 'card.html', 'wizard.html'];

/** Убирает комментарии, сохраняя переводы строк, чтобы номера строк не съехали. */
function безКомментариев(текст) {
  return текст
    .replace(/\/\*[\s\S]*?\*\//g, (m) => m.replace(/[^\n]/g, ' '))
    .replace(/(^|[^:])\/\/[^\n]*/g, (m, p) => p + ' '.repeat(m.length - p.length));
}

const строка = (текст, i) => текст.slice(0, i).split('\n').length;

/** Содержимое скобок начиная с позиции открывающей. */
function скобки(текст, начало, открывающая = '(', закрывающая = ')') {
  let глубина = 0;
  for (let i = начало; i < текст.length; i++) {
    if (текст[i] === открывающая) глубина++;
    else if (текст[i] === закрывающая) {
      глубина--;
      if (!глубина) return { тело: текст.slice(начало + 1, i), конец: i };
    }
  }
  return { тело: текст.slice(начало + 1), конец: текст.length };
}

/* ------------------------------ 1. даты без времени ------------------------------ */

/* Строка «2026-07-03» по стандарту ECMAScript разбирается как полночь UTC, а не
   как локальная полночь. В поясе Когалыма (UTC+5) такая дата превращается в
   05:00 того же дня — рядом со сравнением «не позже сегодняшнего» это даёт
   разное поведение в разных поясах, а восточнее UTC+8:40 форма фиксации
   реализации начинает отвергать собственное значение по умолчанию. В макете
   для этого есть toDate(), которая дописывает «T00:00»; проверка следит, что
   мимо неё ничего не осталось. */

/** Поля набора, где лежит дата без времени. */
const ПОЛЯ_ДАТ = ['factDate', 'windowOpenAt', 'windowCloseAt', 'proposedDate', 'planDate'];

/** Все вызовы `new Date(...)` файла с текстом аргумента. */
function вызовыNewDate(текст) {
  const результат = [];
  for (const m of текст.matchAll(/new Date\s*\(/g)) {
    const { тело, конец } = скобки(текст, m.index + m[0].length - 1);
    результат.push({ аргумент: тело.trim(), позиция: m.index, конец });
  }
  return результат;
}

/** Функции, которые зовут `new Date(параметр)` без проверки на дату без времени. */
function небезопасныеПомощники(текст) {
  const найдено = [];
  const шаблоны = [
    /const\s+(\w+)\s*=\s*\(([^)]*)\)\s*=>/g,          // const days = (a, b) => …
    /function\s+(\w+)\s*\(([^)]*)\)\s*\{/g,           // function fmt(d) { … }
  ];
  for (const шаблон of шаблоны) {
    for (const m of текст.matchAll(шаблон)) {
      /* Только простые имена параметров. Деструктуризация и значения по
         умолчанию из этого грубого разбора приходят обрывками вроде «(» —
         подставленные в регулярное выражение, они его ломают, а искать в них
         «голый» new Date всё равно нечего. */
      const параметры = m[2].split(',')
        .map((s) => s.trim().split('=')[0].trim())
        .filter((s) => /^[A-Za-zА-Яа-яЁё_$][\w$]*$/.test(s));
      if (!параметры.length) continue;
      /* Тело берём до конца строки для стрелки-однострочника и по скобкам для
         обычной функции — этого достаточно для помощников макета. */
      const хвост = текст.slice(m.index + m[0].length);
      const тело = m[0].endsWith('{')
        ? скобки(текст.slice(m.index + m[0].length - 1), 0, '{', '}').тело
        : хвост.slice(0, хвост.indexOf(';') + 1 || 200);
      /* Наличие шаблона YYYY-MM-DD в теле означает, что автор о поясе подумал. */
      if (/\\d\{4\}-\\d\{2\}-\\d\{2\}|T00:00/.test(тело)) continue;
      for (const p of параметры) {
        if (new RegExp(`new Date\\s*\\(\\s*${p}\\s*\\)`).test(тело)) {
          найдено.push({ имя: m[1], параметр: p, индекс: параметры.indexOf(p), строка: строка(текст, m.index) });
        }
      }
    }
  }
  return найдено;
}

{
  const р = отчёт.правило('К-01', 'Даты без времени не разбираются «голым» new Date (пояс съедет)');
  for (const файл of ФАЙЛЫ_JS) {
    const текст = безКомментариев(исходник(файл));

    /* Значения полей ввода <input type="date"> — тоже строки «ГГГГ-ММ-ДД».
       Находим переменные, в которые их читают, чтобы правило видело не только
       поля набора, но и то, что вводит человек. */
    const датныеПоля = new Set([...текст.matchAll(/<input[^>]*type="date"[^>]*id="(\w+)"/g)].map((m) => m[1]));
    const датныеПеременные = new Set();
    for (const m of текст.matchAll(/(?:const|let|var)\s+(\w+)\s*=\s*val\('#(\w+)'\)/g)) {
      if (датныеПоля.has(m[2])) датныеПеременные.add(m[1]);
    }

    const опасно = (выражение) => ПОЛЯ_ДАТ.some((f) => new RegExp(`\\.${f}\\b`).test(выражение))
      || [...датныеПеременные].some((v) => new RegExp(`^${v}$`).test(выражение.trim()))
      || /^['"]\d{4}-\d{2}-\d{2}['"]$/.test(выражение.trim());

    for (const в of вызовыNewDate(текст)) {
      if (!опасно(в.аргумент)) continue;
      /* Внешний new Date вокруг вложенного получает уже число миллисекунд и
         сам по себе безопасен: докладывать надо о внутреннем, иначе одно
         место считается двумя дефектами и цифры в отчёте врут. */
      if (/new Date\s*\(/.test(в.аргумент)) continue;
      р.сбой(`${файл}:${строка(текст, в.позиция)} — new Date(${в.аргумент}) разбирает дату без времени как UTC; `
        + 'нужно через toDate() либо с дописанным «T00:00»');
    }

    /* Помощник, зовущий new Date на своём параметре, безопасен ровно до тех
       пор, пока ему не передадут дату без времени. Ищем именно такие вызовы —
       без этого шага дефект прячется на один уровень вглубь. */
    for (const п of небезопасныеПомощники(текст)) {
      let опасныеВызовы = 0;
      for (const m of текст.matchAll(new RegExp(`(?<![.\\w])${п.имя}\\s*\\(`, 'g'))) {
        const { тело } = скобки(текст, m.index + m[0].length - 1);
        const аргументы = тело.split(',');
        const арг = аргументы[п.индекс];
        if (арг && опасно(арг)) {
          опасныеВызовы++;
          р.сбой(`${файл}:${строка(текст, m.index)} — ${п.имя}(${тело.trim()}) передаёт дату без времени в помощник `
            + `${п.имя} (строка ${п.строка}), который разбирает её «голым» new Date(${п.параметр})`);
        }
      }
      if (!опасныеВызовы) {
        р.предупреждение(`${файл}:${п.строка} — помощник ${п.имя} разбирает параметр ${п.параметр} через `
          + '«голый» new Date; сейчас дат без времени в него не передают, но защиты нет');
      }
    }
  }
}

{
  /* «Сейчас» в макете зафиксировано константой NOW: иначе макет расходится сам
     с собой день ото дня — вчерашнее «осталось 3 часа» сегодня становится
     «просрочено», и обсуждать по нему нечего. */
  const р = отчёт.правило('К-02', '«Сейчас» берётся только из константы NOW');
  for (const файл of ФАЙЛЫ_JS) {
    const текст = безКомментариев(исходник(файл));
    for (const m of текст.matchAll(/new Date\s*\(\s*\)|Date\.now\s*\(\s*\)/g)) {
      р.сбой(`${файл}:${строка(текст, m.index)} — «${m[0]}» берёт реальное время; в макете время зафиксировано в NOW`);
    }
  }
  const data = исходник('data.js');
  if (!/const NOW = new Date\('2026-08-05T08:40:00'\)/.test(data)) {
    р.сбой('в data.js изменилась или пропала константа NOW = new Date(\'2026-08-05T08:40:00\') — '
      + 'все проверки, зависящие от времени, отсчитывают от неё');
  }
}

/* ------------------------------ 2. pre-wrap и отступы кода ------------------------------ */

{
  /* Контейнер с white-space: pre-wrap нужен, чтобы сохранять переносы в тексте,
     который ввёл человек. Но вёрстка в макете собирается многострочными
     шаблонными литералами, и отступы исходного кода в таком контейнере
     становятся видимой частью текста: абзац уезжает вправо ступенькой. Для
     собственных пояснений интерфейса в card.js есть prose(), схлопывающая
     пробелы. Проверка ищет места, где в pre-wrap попал собственный текст мимо
     неё. */
  const р = отчёт.правило('К-03', 'Собственный текст интерфейса в pre-wrap-контейнерах прогнан через prose()');

  /* Список классов берём из CSS, а не из памяти: если pre-wrap появится ещё
     на одном классе, правило подхватит его само. */
  const классы = new Set();
  for (const файл of fs.readdirSync(МАКЕТ).filter((f) => f.endsWith('.css'))) {
    const css = fs.readFileSync(path.join(МАКЕТ, файл), 'utf8');
    for (const m of css.matchAll(/([^{}]+)\{([^{}]*white-space\s*:\s*pre-wrap[^{}]*)\}/gi)) {
      for (const c of m[1].matchAll(/\.([a-z0-9_-]+)/gi)) классы.add(c[1]);
    }
  }
  if (!классы.size) {
    р.предупреждение('в CSS макета не нашлось ни одного контейнера с white-space: pre-wrap — правило нечего проверять');
  }
  отчёт.раздел('Контейнеры с white-space: pre-wrap:', [[...классы].join(', ')]);

  for (const файл of ФАЙЛЫ_JS) {
    const текст = исходник(файл);
    for (const класс of классы) {
      /* Класс сопоставляется целым словом по пробелам, а не через \b: граница
         слова срабатывает и внутри «log__i--talk», и правило начинало искать
         pre-wrap там, где его нет. */
      const открытие = new RegExp(`<(\\w+)[^>]*\\bclass="([^"]*)"[^>]*>`, 'g');
      for (const m of текст.matchAll(открытие)) {
        if (!m[2].split(/\s+/).includes(класс)) continue;
        const тег = m[1];
        /* Ищем парный закрывающий тег с учётом вложенности. */
        let глубина = 1;
        let i = m.index + m[0].length;
        const начало = i;
        const шаг = new RegExp(`<${тег}\\b|</${тег}>`, 'g');
        шаг.lastIndex = i;
        let s;
        while ((s = шаг.exec(текст))) {
          глубина += s[0].startsWith('</') ? -1 : 1;
          if (!глубина) { i = s.index; break; }
        }
        const содержимое = текст.slice(начало, i);

        /* Вырезаем подстановки ${…} целиком — остаётся только литеральный
           текст, тот самый, который попадёт на экран как есть. Именно его
           отступы и становятся видимыми. */
        let литерал = '';
        for (let k = 0; k < содержимое.length; k++) {
          if (содержимое[k] === '$' && содержимое[k + 1] === '{') {
            k = скобки(содержимое, k + 1, '{', '}').конец;
            continue;
          }
          литерал += содержимое[k];
        }
        if (/\n[ \t]{2,}\S/.test(литерал)) {
          const образец = литерал.replace(/\s+/g, ' ').trim().slice(0, 60);
          р.сбой(`${файл}:${строка(текст, m.index)} — в pre-wrap-контейнер «${класс}» попал собственный текст `
            + `с отступами исходного кода: «${образец}…»; прогнать через prose()`);
        }
      }
    }
  }

  if (!/const prose\s*=/.test(исходник('card.js'))) {
    р.сбой('в card.js пропала функция prose() — без неё отступы шаблонных литералов попадут на экран');
  }
}

/* ------------------------------ 3. защита hidden в разметке ------------------------------ */

{
  /* Проверка Т-05 следит за самим правилом в CSS. Здесь — обратная сторона:
     атрибутом hidden в макете действительно пользуются, значит правило нужно,
     и удалить его как «лишнее» нельзя. */
  const р = отчёт.правило('К-04', 'Атрибут hidden используется макетом, значит защита в CSS обязательна');
  const места = [];
  for (const файл of [...ФАЙЛЫ_JS, ...ФАЙЛЫ_HTML]) {
    const текст = безКомментариев(исходник(файл));
    for (const m of текст.matchAll(/\bhidden\b(?!:)/g)) {
      места.push(`${файл}:${строка(текст, m.index)}`);
    }
  }
  const registry = fs.readFileSync(path.join(МАКЕТ, 'registry.css'), 'utf8');
  if (места.length && !/\[hidden\]\s*\{[^}]*display\s*:\s*none\s*!important/i.test(registry)) {
    р.сбой(`атрибут hidden используется в ${места.length} местах (${места.slice(0, 6).join(', ')}…), `
      + 'но правила [hidden] { display: none !important } в registry.css нет');
  }
  отчёт.раздел('Атрибут hidden используется:', [места.join(', ') || 'нигде']);
}

/* ------------------------------ 4. рассинхрон кода и данных ------------------------------ */

/** Выдёргивает литерал константы из исходника и вычисляет его. */
function константа(текст, имя, открывающая, закрывающая) {
  const m = new RegExp(`const ${имя}\\s*=\\s*\\${открывающая}`).exec(текст);
  if (!m) return null;
  const { тело } = скобки(текст, m.index + m[0].length - 1, открывающая, закрывающая);
  return new Function(`return ${открывающая}${тело}${закрывающая}`)();
}

{
  /* Набор действий шапки карточки перечисляет статусы руками, а справочник
     статусов живёт в data.js. Появится одиннадцатый статус — карточка с ним
     останется без единого действия, и ошибка будет молчаливой.

     Ленты статусов здесь больше нет: решением 69 она убрана, её место заняла
     полоса прогноза. Правило про пять групп ленты выброшено вместе с ней —
     проверять его стало нечего, а оставленное «правило» о несуществующем
     элементе только создаёт видимость покрытия. Что полоса прогноза
     отрисовалась и заполнена осмысленно, проверяет Р-13 на живом экране. */
  const р = отчёт.правило('К-05', 'Действия шапки карточки покрывают все статусы справочника');
  const { STATUSES } = загрузитьДанные();
  const ключи = STATUSES.map((s) => s.key);
  const card = безКомментариев(исходник('card.js'));

  const HEAD_ACTIONS = константа(card, 'HEAD_ACTIONS', '{', '}');
  if (!HEAD_ACTIONS) {
    р.сбой('в card.js не найдена константа HEAD_ACTIONS — действия шапки нельзя сверить со справочником');
  } else {
    const нет = ключи.filter((k) => !(k in HEAD_ACTIONS));
    const лишние = Object.keys(HEAD_ACTIONS).filter((k) => !ключи.includes(k));
    if (нет.length) р.сбой(`для статусов ${нет.join(', ')} не задан набор действий шапки карточки`);
    if (лишние.length) р.сбой(`действия шапки заданы для несуществующих статусов: ${лишние.join(', ')}`);
    /* Решения 33 и 35: кнопок решения в шапке нет — до «Принять» и «Отклонить»
       можно добраться, только прокрутив технологическое обоснование. */
    for (const [ключ, действия] of Object.entries(HEAD_ACTIONS || {})) {
      for (const [подпись] of действия) {
        if (/^(Принять|Отклонить|Требует уточнения)$/.test(подпись)) {
          р.сбой(`в шапке карточки на статусе «${ключ}» появилась кнопка решения «${подпись}» — `
            + 'решениями 33 и 35 кнопок решения в шапке нет');
        }
      }
    }
  }
}

