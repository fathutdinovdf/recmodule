/* ------------------------------ 6. упразднённые сущности ------------------------------ */

{
  /* Решение 72: поля «источник рекомендации» нет нигде — ни справочника, ни
     колонки, ни поля в карточке и мастере. Проверка статическая и грубая
     нарочно: остаток вроде `rec.source` не падает и на экране выглядит пустой
     ячейкой, а справочник, оставшийся в data.js, рано или поздно всплывёт в
     новой форме, потому что «он же есть». */
  const р = отчёт.правило('К-08', 'Поля и справочника «источник рекомендации» нет ни в данных, ни в разметке (решение 72)');
  const остатки = [
    [/\bconst SOURCES\b/, 'справочник SOURCES'],
    [/\.source\b/, 'обращение к полю source'],
    [/['"]source['"]\s*:/, 'ключ source в описании колонок или полей'],
    [/Источник рекомендации/i, 'подпись «Источник рекомендации»'],
  ];
  for (const файл of [...ФАЙЛЫ_JS, ...ФАЙЛЫ_HTML]) {
    const текст = безКомментариев(исходник(файл));
    for (const [шаблон, что] of остатки) {
      const m = шаблон.exec(текст);
      if (m) р.сбой(`${файл}:${строка(текст, m.index)} — остался ${что} («${m[0]}»), упразднён решением 72`);
    }
  }
}

{
  /* Решение 69: лента статусов убрана. Классы .ribbon и .step, оставшиеся в
     CSS, ничего не ломают — и именно поэтому доживают до момента, когда кто-то
     решит, что раз стили есть, значит лента предусмотрена, и вернёт её. */
  const р = отчёт.правило('К-09', 'От убранной ленты статусов не осталось ни разметки, ни стилей (решение 69)');
  /* Подстановки `${…}` внутри class="…" вырезаются: выражение вроде
     `class="wzstep ${i === step ? …}"` содержит слово step как переменную, а не
     как класс, и без этого правило показывало бы на него пальцем. */
  const безПодстановок = (текст) => текст.replace(/\$\{[^{}]*\}/g, (m) => ' '.repeat(m.length));
  const используется = (класс) => {
    const места = [];
    for (const файл of [...ФАЙЛЫ_JS, ...ФАЙЛЫ_HTML]) {
      const текст = безПодстановок(безКомментариев(исходник(файл)));
      for (const m of текст.matchAll(new RegExp(`class="[^"]*\\b${класс}\\b|id="${класс}"`, 'g'))) {
        места.push(`${файл}:${строка(текст, m.index)}`);
      }
    }
    return места;
  };
  for (const класс of ['ribbon', 'step']) {
    const места = используется(класс);
    if (места.length) {
      р.сбой(`класс «${класс}» от ленты статусов ещё используется в разметке: ${места.join(', ')}`);
    }
  }
  for (const файл of fs.readdirSync(МАКЕТ).filter((f) => f.endsWith('.css'))) {
    const css = fs.readFileSync(path.join(МАКЕТ, файл), 'utf8');
    for (const m of css.matchAll(/(^|[\s,{}])\.(ribbon|step)\b/g)) {
      р.предупреждение(`${файл}:${строка(css, m.index)} — остался стиль «.${m[2]}» от убранной решением 69 ленты статусов`);
    }
  }
}

{
  /* Мастер строит список месторождений не из справочника FIELDS, а из дерева,
     собранного по скважинам тестового набора: узел без единой скважины в
     список не попадает. Для макета это правильно — выбрать месторождение,
     под которым нет ни одной скважины, значит упереться в пустой второй
     список. Но при переносе в React дерево придёт из ВМАП целиком, и правило
     «показываем только то, что есть в данных» нужно будет пересмотреть
     осознанно, а не унаследовать молча. */
  const р = отчёт.правило('К-10', 'Мастер показывает месторождения из дерева скважин, а не весь справочник');
  const { FIELDS, DATA } = загрузитьДанные();
  const сСкважинами = new Set(DATA.map((r) => r.field));
  const пустые = FIELDS.filter((f) => !сСкважинами.has(f));
  if (!/FIELDS\.filter\(/.test(безКомментариев(исходник('wizard.js')))) {
    р.предупреждение('мастер перестал фильтровать список месторождений по дереву скважин — '
      + 'проверить, что выбор месторождения без скважин не заводит в пустой список');
  } else if (пустые.length) {
    р.предупреждение(`в мастере доступно ${FIELDS.length - пустые.length} месторождений из ${FIELDS.length}: `
      + `в наборе нет ни одной скважины на ${пустые.join(', ')}`);
  }
}

