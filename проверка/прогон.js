'use strict';

/* Один вход для всех проверок макета.

   Смысл единого входа не в экономии нажатий, а в том, что набор проверок
   имеет ценность только целиком: правки идут пачками и задевают сразу
   несколько слоёв — данные, стили, разметку. Прогон по одному файлу создаёт
   иллюзию, что «всё в порядке», потому что сломалось в другом.

   Запуск:
       node проверка/прогон.js              полный отчёт
       node проверка/прогон.js --кратко     только первые строки каждого нарушения
       node проверка/прогон.js --без-рендера   без Chrome, если его нет под рукой

   Код возврата — 0, если нарушений нет, иначе 1. */

const кратко = process.argv.includes('--кратко');
const безРендера = process.argv.includes('--без-рендера');

const п = (s) => process.stdout.write(s + '\n');

const модули = [
  ['данные.js', 'непротиворечивость набора данных'],
  ['токены.js', 'дисциплина дизайн-системы'],
  ['код.js', 'исходники макета'],
];
if (!безРендера) модули.push(['рендер.js', 'рендер экранов локальным Chrome']);

const начало = Date.now();
const отчёты = [];
const упавшие = [];

for (const [файл, что] of модули) {
  process.stdout.write(`\n… ${файл} — ${что}\n`);
  try {
    /* Каждый модуль выполняет проверки при загрузке и отдаёт готовый отчёт.
       Печать вынесена сюда, чтобы порядок и оформление были общими. */
    отчёты.push(require(`./${файл}`));
  } catch (e) {
    упавшие.push([файл, e]);
    п(`  ОШИБКА: сама проверка не отработала — ${e.message}`);
  }
}

let нарушений = 0;
let предупреждений = 0;
let правил = 0;

for (const отчёт of отчёты) {
  отчёт.печать({ подробно: !кратко });
  нарушений += отчёт.нарушения.length;
  предупреждений += отчёт.предупреждения.length;
  правил += отчёт.правила.length;
}

п('');
п('='.repeat(72));
п('ИТОГ');
п('='.repeat(72));
for (const отчёт of отчёты) {
  const метка = отчёт.нарушения.length ? `${отчёт.нарушения.length} нарушений` : 'чисто';
  const доп = отчёт.предупреждения.length ? `, предупреждений ${отчёт.предупреждения.length}` : '';
  п(`  ${отчёт.имя.padEnd(40, '.')} ${метка}${доп}`);
}
for (const [файл, e] of упавшие) п(`  ${файл.padEnd(40, '.')} ПРОВЕРКА УПАЛА: ${e.message}`);

п('');
п(`  правил проверено: ${правил}`);
п(`  нарушений: ${нарушений}, предупреждений: ${предупреждений}`);
п(`  время: ${((Date.now() - начало) / 1000).toFixed(1)} с`);
if (!безРендера) п('  снимки экранов: проверка/снимки — их надо посмотреть глазами');
п('');

process.exit(нарушений || упавшие.length ? 1 : 0);
