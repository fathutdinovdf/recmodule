const БАЗА = [
  '--headless', '--disable-gpu', '--no-sandbox', '--hide-scrollbars',
  `--user-data-dir=${ПРОФИЛЬ}`,
];

function chrome(аргументы) {
  const r = spawnSync(CHROME, [...БАЗА, ...аргументы], { encoding: 'utf8', maxBuffer: 128 * 1024 * 1024 });
  if (r.error) throw new Error(`не удалось запустить Chrome (${CHROME}): ${r.error.message}`);
  return r;
}

function разметка(url, { файлыДоступны = false } = {}) {
  const r = chrome([
    ...(файлыДоступны ? ['--allow-file-access-from-files'] : []),
    '--virtual-time-budget=4000', '--dump-dom', url,
  ]);
  return r.stdout || '';
}

/** Открывает страницу-стенд и возвращает разобранный JSON из #итог. */
function стенд(файл, хеш = '') {
  const url = pathToFileURL(path.join(__dirname, файл)).href + хеш;
  const html = разметка(url, { файлыДоступны: true });
  const m = /<pre id="итог">([\s\S]*?)<\/pre>/.exec(html);
  if (!m) return null;
  try { return JSON.parse(текстом(m[1])); } catch (e) { return null; }
}

/* Состояние по щелчку (шаг мастера, раскрытое меню) снимается временной копией
   страницы с дописанным вызовом click: скриншот сам ничего не нажимает, а
   мастер держит шаг в памяти и в адресе его не принимает. Копия кладётся рядом
   с оригиналом, иначе относительные ссылки на data.js и tokens.css не найдутся,
   и удаляется сразу после снимка. */
function копияСоЩелчком(файл, имя, селектор) {
  const путь = path.join(МАКЕТ, `_проба-${имя}.html`);
  const текст = fs.readFileSync(path.join(МАКЕТ, файл), 'utf8')
    .replace(/<\/body>/i, `<script>
      /* Временная копия для проверки. Удаляется прогоном сразу после снимка. */
      var э = document.querySelector(${JSON.stringify(селектор)});
      if (э) э.click();
    </script>\n</body>`);
  fs.writeFileSync(путь, текст);
  return путь;
}

