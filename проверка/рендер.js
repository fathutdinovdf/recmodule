'use strict';

/* Рендер ключевых экранов локальным headless Chrome и проверка результата.

   Почему именно локальный Chrome, а не встроенное превью среды: превью отдаёт
   статический снимок разметки и выполняет не все скрипты. В этом макете и
   реестр, и вся карточка рисуются скриптом — в HTML лежат пустые контейнеры
   #tbody и #cardhead. На статическом снимке они пустые всегда, и отличить
   «скрипт не запускали» от «скрипт упал» невозможно.

   Почему проверяется не только скриншот, но и --dump-dom: упавший скрипт даёт
   пустую разметку, а на скриншоте это выглядит как чистая страница — дефект
   виден, только если человек знает, что там должна быть таблица. Проверка
   «в отрисованном DOM есть непустой #tbody» ловит это без человека.

   Скриншоты всё равно снимаются: часть дефектов — обрезанный край сетки,
   съехавший отступ, невидимый текст — из разметки не читается никак. Их
   смотрят глазами, но уже прицельно и по готовому набору состояний. */

const fs = require('fs');
const path = require('path');
const { spawnSync } = require('child_process');
const os = require('os');
const { pathToFileURL } = require('url');
const { МАКЕТ, загрузитьДанные, Отчёт } = require('./общее.js');

const отчёт = new Отчёт('Рендер экранов');

const CHROME = process.env.CHROME || 'C:/Program Files/Google/Chrome/Application/chrome.exe';
const СНИМКИ = path.join(__dirname, 'снимки');
const ПРОФИЛЬ = path.join(os.tmpdir(), 'проверка-макета-chrome');

fs.mkdirSync(СНИМКИ, { recursive: true });

/* Пути проекта содержат кириллицу и пробел; file:// такой путь принимает
   только в процентной кодировке, поэтому URL собирается pathToFileURL,
   а не склейкой строк. */
const адрес = (файл, запрос = '') => pathToFileURL(path.join(МАКЕТ, файл)).href + запрос;

/* --allow-file-access-from-files нужен только стенду вычисленных стилей: без
   него доступ к правилам чужого file://-стиля закрыт как к чужому источнику,
   и проверка каскада становится невозможной. Сами страницы макета снимаются
   без этого флага — так же, как их открывает человек. */
const БАЗА = [
  '--headless', '--disable-gpu', '--no-sandbox', '--hide-scrollbars',
  `--user-data-dir=${ПРОФИЛЬ}`,
];

function chrome(аргументы) {
  const r = spawnSync(CHROME, [...БАЗА, ...аргументы], { encoding: 'utf8', maxBuffer: 128 * 1024 * 1024 });
  if (r.error) throw new Error(`не удалось запустить Chrome (${CHROME}): ${r.error.message}`);
  return r;
}

function разметка(url, { файлыДоступны = false } = {}) {
  const r = chrome([
    ...(файлыДоступны ? ['--allow-file-access-from-files'] : []),
    '--virtual-time-budget=4000', '--dump-dom', url,
  ]);
  return r.stdout || '';
}

/** Открывает страницу-стенд и возвращает разобранный JSON из #итог. */
function стенд(файл, хеш = '') {
  const url = pathToFileURL(path.join(__dirname, файл)).href + хеш;
  const html = разметка(url, { файлыДоступны: true });
  const m = /<pre id="итог">([\s\S]*?)<\/pre>/.exec(html);
  if (!m) return null;
  try { return JSON.parse(текстом(m[1])); } catch (e) { return null; }
}

function снимок(url, имя) {
  const файл = path.join(СНИМКИ, имя);
  chrome(['--virtual-time-budget=4000', '--window-size=1600,1100', `--screenshot=${файл}`, url]);
  return fs.existsSync(файл) ? файл : null;
}

/* ------------------------------ разбор отрисованной разметки ------------------------------ */

/** Содержимое элемента с указанным id из строки разметки. */
function поId(html, id) {
  const m = new RegExp(`<(\\w+)[^>]*\\bid="${id}"[^>]*>`).exec(html);
  if (!m) return null;
  const тег = m[1];
  let глубина = 1;
  const шаг = new RegExp(`<${тег}\\b|</${тег}>`, 'g');
  шаг.lastIndex = m.index + m[0].length;
  let s;
  while ((s = шаг.exec(html))) {
    глубина += s[0].startsWith('</') ? -1 : 1;
    if (!глубина) return html.slice(m.index + m[0].length, s.index);
  }
  return html.slice(m.index + m[0].length);
}

/** Все куски разметки внутри элементов с указанным классом. */
function поКлассу(html, класс) {
  const результат = [];
  const открытие = /<(\w+)[^>]*\bclass="([^"]*)"[^>]*>/g;
  let m;
  while ((m = открытие.exec(html))) {
    if (!m[2].split(/\s+/).includes(класс)) continue;
    const тег = m[1];
    let глубина = 1;
    const шаг = new RegExp(`<${тег}\\b|</${тег}>`, 'g');
    шаг.lastIndex = m.index + m[0].length;
    let s;
    let конец = html.length;
    while ((s = шаг.exec(html))) {
      глубина += s[0].startsWith('</') ? -1 : 1;
      if (!глубина) { конец = s.index; break; }
    }
    результат.push(html.slice(m.index + m[0].length, конец));
  }
  return результат;
}

const текстом = (html) => html.replace(/<[^>]*>/g, '')
  .replace(/&nbsp;/g, ' ').replace(/&amp;/g, '&').replace(/&quot;/g, '"')
  .replace(/&lt;/g, '<').replace(/&gt;/g, '>');

const счёт = (html, класс) => поКлассу(html, класс).length;

/* ------------------------------ набор состояний ------------------------------ */

const { DATA, TILES, STATUSES } = загрузитьДанные();

/** Первая запись, подходящая под условие, — с внятной ошибкой, если такой нет. */
function найти(описание, условие) {
  const r = DATA.find(условие);
  if (!r) отчёт.правило('Р-00', 'Состояние есть в наборе данных')
    .сбой(`в наборе нет записи для состояния «${описание}» — снять этот экран нечем`);
  return r;
}

const СОСТОЯНИЯ = [
  { имя: 'registry', подпись: 'Реестр рекомендаций', файл: 'index.html' },
];

/* Карточка снимается во всех десяти статусах: именно там сходятся статусная
   модель, лента, набор действий и формы, и почти каждый дефект макета
   проявляется ровно на одном из статусов, а не на всех сразу. */
const ПО_СТАТУСАМ = [
  ['draft', 'Черновик'],
  ['registered', 'Зарегистрировано, ждёт открытия рабочего дня'],
  ['sent', 'Передано Заказчику'],
  ['review', 'На рассмотрении'],
  ['clarify', 'На уточнении'],
  ['approved', 'Согласовано к реализации'],
  ['windowOpen', 'Открыто окно подтверждения эффекта'],
  ['windowClosed', 'Закрыто окно подтверждения эффекта'],
  ['rejected', 'Отклонено'],
  ['cancelled', 'Отменено'],
];

for (const [ключ, подпись] of ПО_СТАТУСАМ) {
  const r = найти(подпись, (x) => x.status === ключ);
  if (!r) continue;
  /* На статусах окна интереснее вкладка «Реализация»: там живут дата
     реализации, полнота, вложения и спор о дате. */
  const вкладка = ['windowOpen', 'windowClosed'].includes(ключ) ? '&tab=impl' : '';
  СОСТОЯНИЯ.push({
    имя: `card-${ключ.replace(/[A-Z]/g, (c) => '-' + c.toLowerCase())}`,
    подпись: `Карточка — ${подпись} (${r.number})`,
    файл: 'card.html', запрос: `?id=${r.id}${вкладка}`, карточка: true, статус: ключ,
  });
}

/* Отдельные состояния, которых нет среди «первых попавшихся» по статусу. */
const спор = найти('открытое окно со спором о дате', (x) => x.dispute && x.status === 'windowOpen');
if (спор) {
  СОСТОЯНИЯ.push({
    имя: 'card-window-open-dispute',
    подпись: `Карточка — окно со спором о дате реализации (${спор.number})`,
    файл: 'card.html', запрос: `?id=${спор.id}&tab=impl`, карточка: true, статус: спор.status,
  });
}
const разговор = найти('карточка с обсуждением', (x) => x.comments.length >= 3);
if (разговор) {
  СОСТОЯНИЯ.push({
    имя: 'card-log',
    подпись: `Карточка — история и обсуждение (${разговор.number})`,
    файл: 'card.html', запрос: `?id=${разговор.id}&tab=log`, карточка: true, статус: разговор.status,
  });
}

/* ------------------------------ проверки ------------------------------ */

const жив = отчёт.правило('Р-01', 'Скрипт отработал: контейнеры, которые рисуются скриптом, не пустые');
const мусор = отчёт.правило('Р-02', 'В отрисованном тексте нет следов сломанной подстановки');
const прewrap = отчёт.правило('Р-03', 'В pre-wrap-контейнерах нет отступов исходного кода');
const плитки = отчёт.правило('Р-04', 'Плиток на экране столько же, сколько в data.js');
const лента = отчёт.правило('Р-05', 'Лента статусов и вкладки карточки отрисованы полностью');
const снимки = отчёт.правило('Р-06', 'Скриншот каждого состояния снят');
const решение = отчёт.правило('Р-09', 'Кнопки решения Заказчика доступны только там, где решение возможно');
const склейка = отчёт.правило('Р-10', 'Подписи не склеиваются в бессмысленные фразы');

/* Решение Заказчика возможно, только пока рекомендация у него на руках и
   ответа ещё нет: «Передано Заказчику» и «На рассмотрении». На всех остальных
   статусах решение либо уже принято, либо приниматься не может — отменённую
   рекомендацию Заказчик вообще никогда не видел (отмена происходит до
   передачи). Кнопка, которая там появляется, обещает несуществующее действие. */
const РЕШЕНИЕ_ВОЗМОЖНО = ['sent', 'review'];

/* Подстановка, промахнувшаяся мимо значения, даёт на экране не пустоту, а
   слово «undefined» или «[object Object]». Это не падение — страница выглядит
   рабочей, поэтому такое доезжает до демонстрации. */
const СЛЕДЫ = [/\bundefined\b/, /\bNaN\b/, /\[object Object\]/, /\bnull\b/];

const снято = [];

for (const с of СОСТОЯНИЯ) {
  const url = адрес(с.файл, с.запрос || '');
  const html = разметка(url);

  if (!html || !/<\/html>/i.test(html)) {
    жив.сбой(`${с.подпись} — Chrome не вернул разметку по адресу ${с.файл}${с.запрос || ''}`);
    continue;
  }

  /* Контейнеры, которые в исходном HTML пустые и наполняются скриптом. Если
     скрипт упал, они останутся пустыми — на скриншоте это чистая страница. */
  const обязательные = с.карточка
    ? [['cardhead', 'шапка карточки'], ['ribbon', 'лента статусов'],
      ['tabs', 'вкладки'], ['tabpane', 'содержимое вкладки'], ['context', 'правая колонка']]
    : [['tiles', 'плитки-счётчики'], ['thead', 'заголовок таблицы'],
      ['tbody', 'тело таблицы'], ['pagerInfo', 'счётчик отобранного']];

  for (const [id, что] of обязательные) {
    const внутри = поId(html, id);
    if (внутри === null) жив.сбой(`${с.подпись} — в разметке нет элемента #${id} (${что})`);
    else if (!внутри.trim()) {
      жив.сбой(`${с.подпись} — #${id} (${что}) пуст: скрипт до него не дошёл, `
        + 'на скриншоте это выглядит как пустая страница');
    }
  }

  const текст = текстом(html);
  for (const след of СЛЕДЫ) {
    const m = след.exec(текст);
    if (!m) continue;
    const контекст = текст.slice(Math.max(0, m.index - 60), m.index + 60).replace(/\s+/g, ' ').trim();
    мусор.сбой(`${с.подпись} — на экране «${m[0]}»: …${контекст}…`);
  }

  /* Отступы исходного кода в pre-wrap-контейнере становятся видимой частью
     текста: абзац уезжает вправо ступенькой. В card.js для этого есть prose();
     здесь проверяется результат, а не наличие вызова. */
  for (const класс of ['block__b', 'talk']) {
    for (const кусок of поКлассу(html, класс)) {
      const т = текстом(кусок);
      if (/\n[ \t]{2,}\S/.test(т)) {
        прewrap.сбой(`${с.подпись} — в «.${класс}» видны отступы исходного кода: `
          + `«${т.replace(/\s+/g, ' ').trim().slice(0, 70)}…»`);
      }
    }
  }

  /* Формулировки контроля ответа (решение 23) собираются из подписи и
     величины отклонения. «Нет срока» величины не имеет, и приклеенные к нему
     минуты превращают фразу в бессмыслицу — но страница при этом выглядит
     совершенно рабочей. */
  /* Без \b на конце намеренно: в JavaScript граница слова считается по [A-Za-z0-9_],
     и после кириллического «мин» она никогда не срабатывает — правило молчало бы. */
  const склеено = /нет срока\s+\d+\s*(мин|ч|д)(?![а-яё])/i.exec(текст);
  if (склеено) {
    склейка.сбой(`${с.подпись} — на экране «${склеено[0]}»: у состояния «нет срока» нет величины отклонения, `
      + 'а она всё равно приписана');
  }

  if (с.карточка && с.статус && !РЕШЕНИЕ_ВОЗМОЖНО.includes(с.статус)) {
    const кнопки = [...html.matchAll(/data-act="open:(accept|reject|clarify)"/g)].map((m) => m[1]);
    if (кнопки.length) {
      решение.сбой(`${с.подпись} — на статусе «${с.статус}» показаны кнопки решения Заказчика `
        + `(${кнопки.join(', ')}), хотя решение на этом статусе невозможно`);
    }
  }

  if (!с.карточка) {
    const n = счёт(поId(html, 'tiles') || '', 'tile');
    if (n !== TILES.length) плитки.сбой(`на экране ${n} плиток, а в data.js ${TILES.length}`);
  } else {
    const шагов = счёт(поId(html, 'ribbon') || '', 'step');
    /* Пять групп ленты; на отклонении и отмене в конец добавляется красный шаг. */
    const ждём = /отклон|отмен/i.test(с.подпись) ? 6 : 5;
    if (шагов !== ждём) лента.сбой(`${с.подпись} — шагов в ленте ${шагов}, ожидалось ${ждём}`);
    const вкладок = счёт(поId(html, 'tabs') || '', 'tab');
    if (вкладок !== 6) лента.сбой(`${с.подпись} — вкладок ${вкладок}, а решением 35 их шесть`);
  }

  const файл = снимок(url, `${с.имя}.png`);
  if (!файл) снимки.сбой(`${с.подпись} — скриншот не снялся`);
  else снято.push(`${path.basename(файл)} — ${с.подпись}`);
}

отчёт.раздел(`Снимков сделано: ${снято.length} (папка проверка/снимки)`, снято);

/* ------------------------------ стенд вычисленного стиля ------------------------------ */

{
  /* Часть правил проверяется только браузером: результат каскада и раскрытие
     переменных из текста CSS не видны. Стенд подключает те же файлы стилей и
     докладывает, что получилось на самом деле. */
  const рhidden = отчёт.правило('Р-07', 'Атрибут hidden не перебивается ни одним классом с display');
  const рvar = отчёт.правило('Р-08', 'Каждая переменная макета раскрывается в непустое значение в обеих темах');

  const итог = стенд('стенд.html');
  if (!итог) {
    рhidden.сбой('стенд вычисленного стиля не отработал — проверить проверка/стенд.html');
  } else {
    if (!итог.доступ) {
      рhidden.предупреждение('браузер не отдал правила чужого file://-стиля; '
        + 'нужен флаг --allow-file-access-from-files');
    }
    отчёт.раздел('Стенд вычисленного стиля:', [
      `правил в подключённых стилях: ${итог.правил}`,
      `проверено сочетаний «класс с display + атрибут hidden»: ${итог.проверено}`,
      `переменных, на которые ссылается макет: ${итог.переменныхИспользовано}`,
    ]);
    for (const н of итог.hidden) {
      рhidden.сбой(`«${н.селектор}» задаёт display: ${н.объявлено}; с атрибутом hidden браузер всё равно `
        + `считает display: ${н.вычислено} — элемент останется на экране`);
    }
    for (const н of итог.переменные) {
      рvar.сбой(`в теме «${н.тема}» переменная ${н.имя} раскрывается в пустоту — свойство молча выпадает`);
    }
  }
}

/* ------------------------------ стенд геометрии ------------------------------ */

{
  /* Дефекты вёрстки, которых нет ни в разметке, ни в CSS по отдельности:
     значение переносится по строкам, потому что рядом оказался длинный сосед.
     Спрашиваем у браузера, сколько строк заняло значение, которое обязано
     читаться целиком. */
  const рперенос = отчёт.правило('Р-11', 'Номера и даты не разрываются переносом строки');
  const рширина = отчёт.правило('Р-12', 'Карточка не выезжает за ширину окна');

  const адреса = СОСТОЯНИЯ.filter((с) => с.карточка)
    .map((с) => `../макет/card.html${с.запрос}`).join('|');
  const итог = стенд('стенд-макет.html', '#' + encodeURIComponent(адреса));

  if (!итог) {
    рперенос.сбой('стенд геометрии не отработал — проверить проверка/стенд-макет.html');
  } else {
    отчёт.раздел('Стенд геометрии:', [`карточек измерено в кадре 1600×1100: ${итог.кадров}`,
      ...итог.ошибки]);
    /* Одно и то же место повторяется на каждой карточке — сворачиваем в один
       дефект по месту, иначе отчёт превращается в перечисление одинаковых строк. */
    const поМесту = new Map();
    for (const н of итог.переносы) {
      const ключ = `${н.класс || н.родитель}`;
      if (!поМесту.has(ключ)) поМесту.set(ключ, []);
      поМесту.get(ключ).push(н);
    }
    for (const [место, список] of поМесту) {
      const примеры = [...new Set(список.map((н) => н.значение))].slice(0, 4).join(', ');
      const карточек = new Set(список.map((н) => н.где)).size;
      рперенос.сбой(`«${место}» (внутри «${список[0].родитель}») — значение разрывается переносом на `
        + `${список[0].строк} строки; ${список.length} случаев на ${карточек} карточках из ${итог.кадров}; `
        + `например: ${примеры}`);
    }
    for (const н of итог.переполнение) {
      рширина.сбой(`${н.где} — содержимое шире окна: ${н.ширина} px при ${н.окно} px`);
    }
  }
}

module.exports = отчёт;

if (require.main === module) process.exit(отчёт.печать());
