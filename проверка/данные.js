'use strict';

/* Проверка непротиворечивости набора данных макета.

   Зачем это отдельной проверкой, а не глазами на экране: реестр показывает 50
   записей из 180, и любое из правил ниже нарушается ровно на тех записях, до
   которых при демонстрации не долистали. Ошибку в генераторе видно только при
   сплошном проходе по всему набору.

   Каждое правило подписано номером решения из «Дизайн модуля — принятые
   решения.md». Правило без ссылки на решение — это не правило, а вкус
   проверяющего, и через месяц его никто не сможет ни подтвердить, ни отменить. */

const { загрузитьДанные, дата, Отчёт } = require('./общее.js');

const М = загрузитьДанные();
const {
  DATA, NOW, TILES, STATUSES, PRIORITIES, DECISIONS, DIRECTIONS,
  COMPLETENESS, STATUS_TONE, SLA_VISIBLE_STATUSES, FIELDS, FIELD_CODE,
  inWindow, addWorkHours, workHoursBetween,
} = М;

const отчёт = new Отчёт('Непротиворечивость набора данных');

/* Подпись записи в сообщении: без номера и статуса нарушение невозможно найти
   в макете руками, а именно это и делают, получив отчёт. */
const п = (r) => `${r.number} (id ${r.id}, «${r.statusLabel}»)`;

const ОКНО = ['windowOpen', 'windowClosed'];
const КЛЮЧИ_СТАТУСОВ = STATUSES.map((s) => s.key);

/** Обходит все записи и докладывает о тех, где предикат сработал. */
function каждая(правило, предикат, сообщение) {
  for (const r of DATA) {
    let плохо = false;
    try { плохо = предикат(r); } catch (e) { плохо = `ошибка проверки: ${e.message}`; }
    if (плохо) правило.сбой(`${п(r)} — ${typeof плохо === 'string' ? плохо : сообщение}`);
  }
}

/* ------------------------------ справочники ------------------------------ */

{
  const р = отчёт.правило('Д-01', 'Статусов ровно десять (решение 40)');
  if (STATUSES.length !== 10) р.сбой(`в STATUSES ${STATUSES.length} статусов вместо десяти`);
  /* Слияние «Реализуется», «Реализовано» и «Частично реализовано» — суть
     решения 40. Если эти подписи вернутся, вернётся и плитка, которая всегда
     показывает ноль, и потерянная в отчётности полнота реализации. */
  for (const лишний of ['Реализуется', 'Реализовано', 'Частично реализовано']) {
    if (STATUSES.some((s) => s.label === лишний)) {
      р.сбой(`статус «${лишний}» отменён решением 40, но снова есть в справочнике`);
    }
  }
}

{
  const р = отчёт.правило('Д-02', 'Каждый статус записи есть в справочнике STATUSES');
  каждая(р, (r) => !КЛЮЧИ_СТАТУСОВ.includes(r.status), 'статуса нет в справочнике');
  каждая(р, (r) => {
    const s = STATUSES.find((x) => x.key === r.status);
    return s && r.statusLabel !== s.label && `подпись статуса «${r.statusLabel}» не совпадает со справочной «${s.label}»`;
  });
}

{
  const р = отчёт.правило('Д-03', 'Плиток семь, они взаимоисключающие и покрывают весь реестр (решения 55, 61)');
  if (TILES.length !== 7) р.сбой(`плиток ${TILES.length} вместо семи`);
  const все = TILES.flatMap((t) => t.statuses);
  const повтор = все.filter((s, i) => все.indexOf(s) !== i);
  if (повтор.length) р.сбой(`статусы попадают сразу в несколько плиток: ${[...new Set(повтор)].join(', ')}`);
  const непокрытые = КЛЮЧИ_СТАТУСОВ.filter((s) => !все.includes(s));
  if (непокрытые.length) р.сбой(`статусы не попадают ни в одну плитку: ${непокрытые.join(', ')}`);
  const чужие = все.filter((s) => !КЛЮЧИ_СТАТУСОВ.includes(s));
  if (чужие.length) р.сбой(`плитки ссылаются на несуществующие статусы: ${чужие.join(', ')}`);
  const сумма = TILES.reduce((s, t) => s + DATA.filter((r) => t.statuses.includes(r.status)).length, 0);
  if (сумма !== DATA.length) р.сбой(`сумма по плиткам ${сумма}, а записей ${DATA.length}`);
  /* Решение 61: последняя плитка — «Окно закрыто», а не «Подтверждено».
     Подтверждённым эффект становится после согласования расчёта, которого в
     модуле нет; переименование обратно означало бы обещание несуществующего. */
  if (TILES.some((t) => /Подтвержд/i.test(t.label))) {
    р.сбой('плитка названа «Подтверждено» — решением 61 она называется «Окно закрыто»');
  }
  /* Решение 8: до передачи Заказчик рекомендации не видел, значит
     «Зарегистрировано» относится к «У Исполнителя». */
  const у = TILES.find((t) => t.statuses.includes('registered'));
  if (!у || у.key !== 'executor') р.сбой('статус «Зарегистрировано» должен лежать в плитке «У Исполнителя» (решение 8)');
}

{
  const р = отчёт.правило('Д-04', 'Кружок статуса определён для всех статусов (решение 30)');
  const тона = ['neutral', 'wait', 'work', 'done', 'reject'];
  for (const s of STATUSES) {
    const t = STATUS_TONE[s.key];
    if (!t) { р.сбой(`для статуса «${s.label}» не задан кружок`); continue; }
    if (!тона.includes(t[0])) р.сбой(`у статуса «${s.label}» неизвестный цвет кружка «${t[0]}»`);
    if (typeof t[1] !== 'boolean') р.сбой(`у статуса «${s.label}» заливка кружка не булева`);
  }
  const лишние = Object.keys(STATUS_TONE).filter((k) => !КЛЮЧИ_СТАТУСОВ.includes(k));
  if (лишние.length) р.сбой(`кружок задан для несуществующих статусов: ${лишние.join(', ')}`);
}

{
  /* Решение 62: приоритет и контроль ответа видны только пока вопрос ответа
     Заказчика не закрыт. «На уточнении» сюда не входит сознательно — вопрос
     сброса норматива при повторном круге открыт. */
  const р = отчёт.правило('Д-05', 'Приоритет и контроль ответа видны ровно на трёх статусах (решение 62)');
  const ждём = ['registered', 'sent', 'review'];
  const есть = [...SLA_VISIBLE_STATUSES].sort().join(',');
  if (есть !== [...ждём].sort().join(',')) {
    р.сбой(`SLA_VISIBLE_STATUSES = [${SLA_VISIBLE_STATUSES}], а решение 62 задаёт [${ждём}]`);
  }
}

{
  const р = отчёт.правило('Д-06', 'Норматив ответа соответствует приоритету: I — 4 ч, II — 8 ч, III — 24 ч');
  const ждём = { I: 4, II: 8, III: 24 };
  for (const p of PRIORITIES) {
    if (p.sla !== ждём[p.code]) р.сбой(`у приоритета ${p.code} норматив ${p.sla} ч вместо ${ждём[p.code]}`);
  }
  каждая(р, (r) => {
    const p = PRIORITIES.find((x) => x.code === r.priority);
    if (!p) return `приоритет «${r.priority}» вне справочника`;
    return r.sla !== p.sla && `норматив ${r.sla} ч не совпадает с приоритетом ${r.priority}`;
  });
}

{
  const р = отчёт.правило('Д-07', 'Значения полей взяты из справочников');
  каждая(р, (r) => !DIRECTIONS.includes(r.direction) && `направление «${r.direction}» вне справочника`);
  каждая(р, (r) => !FIELDS.includes(r.field) && `месторождение «${r.field}» вне справочника`);
  каждая(р, (r) => !FIELD_CODE[r.field] && `у месторождения «${r.field}» нет кода для номера рекомендации`);
  каждая(р, (r) => r.decision && !DECISIONS.includes(r.decision) && `решение «${r.decision}» вне справочника`);
  каждая(р, (r) => r.completeness && !COMPLETENESS[r.completeness] && `полнота «${r.completeness}» вне справочника`);
  каждая(р, (r) => r.completeness && r.completenessLabel !== COMPLETENESS[r.completeness]
    && 'подпись полноты не совпадает со справочной');
}

/* ------------------------------ номер ------------------------------ */

{
  /* Решение 17: номер — код месторождения, год, счётчик внутри месторождения.
     Номер читается как адрес объекта, поэтому чужой префикс — не косметика. */
  const р = отчёт.правило('Д-08', 'Номер рекомендации собран из кода месторождения и года (решение 17)');
  каждая(р, (r) => r.status !== 'draft' && !/^[А-ЯЁA-Z]{2,3}\d?-26-\d{4}$/.test(r.number)
    && `номер «${r.number}» не соответствует формату КОД-26-NNNN`);
  каждая(р, (r) => r.status !== 'draft' && FIELD_CODE[r.field]
    && !r.number.startsWith(`${FIELD_CODE[r.field]}-26-`)
    && `номер «${r.number}» не соответствует коду месторождения «${FIELD_CODE[r.field]}»`);

  const счёт = new Map();
  for (const r of DATA) {
    if (r.status === 'draft') continue;
    счёт.set(r.number, (счёт.get(r.number) || 0) + 1);
  }
  for (const [номер, n] of счёт) if (n > 1) р.сбой(`номер ${номер} встречается ${n} раз`);
}

{
  /* Решение 1: у черновика нет ни номера, ни даты регистрации — дата
     регистрации юридически нагружена, и до регистрации её существовать
     не может. */
  const р = отчёт.правило('Д-09', 'У черновика нет номера (решение 1)');
  каждая(р, (r) => r.status === 'draft' && r.number !== '—' && `у черновика проставлен номер «${r.number}»`);
  каждая(р, (r) => r.status !== 'draft' && r.number === '—' && 'номер не проставлен, хотя рекомендация уже не черновик');
}

/* ------------------------------ передача и рабочее окно ------------------------------ */

{
  /* Решение 19: передача происходит только в рабочее окно Заказчика,
     пн–пт 09:00–24:00. Зарегистрированная ночью рекомендация ждёт утра. */
  const р = отчёт.правило('Д-10', 'Передача Заказчику попадает в рабочее окно пн–пт 09:00–24:00 (решение 19)');
  каждая(р, (r) => r.sentAt && !inWindow(r.sentAt) && `передача ${r.sentAt.toLocaleString('ru-RU')} вне рабочего окна`);
  каждая(р, (r) => r.sentAt && r.sentAt < r.regDate && 'передача раньше регистрации');
}

{
  /* Решение 20: норматив считается рабочими часами, иначе четырёхчасовой срок
     по рекомендации, переданной в 22:00, истекал бы в два часа ночи. */
  const р = отчёт.правило('Д-11', 'Срок обратной связи отсчитан рабочими часами от передачи (решение 20)');
  каждая(р, (r) => r.sentAt && !r.dueAt && 'передана, но срок обратной связи не рассчитан');
  каждая(р, (r) => !r.sentAt && r.dueAt && 'срок обратной связи есть, а передачи нет');
  каждая(р, (r) => r.sentAt && r.dueAt && +r.dueAt !== +addWorkHours(r.sentAt, r.sla)
    && 'срок обратной связи не совпадает с расчётом по рабочим часам');
}

{
  /* Решение 8: регистрация и передача — два разных состояния. До передачи
     статус «Зарегистрировано», после — «Передано Заказчику». */
  const р = отчёт.правило('Д-12', 'Статус согласован с моментом передачи относительно «сейчас» (решения 8, 19)');
  каждая(р, (r) => r.status === 'draft' && r.sentAt && 'у черновика проставлена передача');
  каждая(р, (r) => r.status === 'registered' && !(r.sentAt > NOW)
    && 'статус «Зарегистрировано», но момент передачи уже наступил');
  каждая(р, (r) => ['sent', 'review', 'clarify', 'approved', ...ОКНО, 'rejected'].includes(r.status)
    && !(r.sentAt && r.sentAt <= NOW)
    && 'статус наступает только после передачи, а передачи ещё не было');
}

/* ------------------------------ три отметки времени ------------------------------ */

{
  /* Решение 21: отметок три — передана, открыта Заказчиком, отвечена.
     Открытие карточки не есть ответ. */
  const р = отчёт.правило('Д-13', 'Три отметки времени идут в правильном порядке (решение 21)');
  каждая(р, (r) => r.openedAt && !r.sentAt && 'карточку открыли, хотя рекомендация не передана');
  каждая(р, (r) => r.repliedAt && !r.sentAt && 'есть ответ, хотя рекомендация не передана');
  каждая(р, (r) => r.openedAt && r.sentAt && r.openedAt < r.sentAt && 'карточку открыли раньше передачи');
  каждая(р, (r) => r.repliedAt && r.sentAt && r.repliedAt < r.sentAt && 'ответ раньше передачи');
  каждая(р, (r) => r.repliedAt && r.openedAt && r.repliedAt < r.openedAt && 'ответ раньше открытия карточки');
  каждая(р, (r) => r.openedAt && r.openedAt > NOW && 'карточку открыли в будущем');
  каждая(р, (r) => r.repliedAt && r.repliedAt > NOW && 'ответ из будущего');
  каждая(р, (r) => r.regDate > NOW && 'рекомендация зарегистрирована в будущем');
}

{
  /* Решение 4: открытие карточки пользователем Заказчика автоматически
     переводит «Передано» → «На рассмотрении». Значит «Передано» с отметкой
     открытия — состояние, которого в модуле не бывает. */
  const р = отчёт.правило('Д-14', 'Открытие карточки переводит «Передано» в «На рассмотрении» (решение 4)');
  каждая(р, (r) => r.status === 'sent' && r.openedAt && 'статус «Передано», хотя карточку уже открыли');
  каждая(р, (r) => r.status === 'review' && !r.openedAt && 'статус «На рассмотрении» без отметки открытия');
  каждая(р, (r) => r.status === 'review' && r.decision && 'статус «На рассмотрении», хотя решение уже принято');
}

/* ------------------------------ решение Заказчика ------------------------------ */

{
  /* Решение 22: решение — событие, двигающее статус, а не отдельное поле.
     Состояний вида «передано + отклонена», которые есть в Форме 2, быть не может. */
  const р = отчёт.правило('Д-15', 'Решение и дата ответа существуют только вместе (решение 22)');
  каждая(р, (r) => !!r.decision !== !!r.repliedAt
    && (r.decision ? 'решение есть, даты ответа нет' : 'дата ответа есть, решения нет'));
}

{
  const р = отчёт.правило('Д-16', 'Решение Заказчика соответствует статусу (решение 22)');
  const карта = {
    'Принята': ['approved', ...ОКНО],
    'Отклонена': ['rejected'],
    'Требует уточнения': ['clarify'],
  };
  каждая(р, (r) => r.decision && !карта[r.decision].includes(r.status)
    && `решение «${r.decision}» не сочетается со статусом`);
  каждая(р, (r) => ['approved', ...ОКНО].includes(r.status) && r.decision !== 'Принята'
    && 'статус после согласования, а решение не «Принята»');
  каждая(р, (r) => r.status === 'rejected' && r.decision !== 'Отклонена' && 'статус «Отклонено» без решения «Отклонена»');
  каждая(р, (r) => r.status === 'clarify' && r.decision !== 'Требует уточнения'
    && 'статус «На уточнении» без решения «Требует уточнения»');
  каждая(р, (r) => r.decision && !r.customer && 'решение принято, но ответственный Заказчика не указан');
}

{
  /* Решения 50 и 51: при отклонении и при запросе уточнения обоснование
     обязательно. Оно попадает в колонку реестра «Обоснование при отклонении»
     и в историю — без него Исполнитель не знает, что делать дальше, а в
     отчётности по договору отказ ничем не объяснён. */
  const р = отчёт.правило('Д-17', 'Отклонение и запрос уточнения снабжены обязательным обоснованием (решения 50, 51)');
  каждая(р, (r) => r.status === 'rejected' && !r.rejectReason && 'отклонено без обоснования');
  каждая(р, (r) => r.status === 'clarify' && !r.rejectReason && 'запрошено уточнение, но не сказано, что уточнить');
  каждая(р, (r) => r.rejectReason && !r.decision && 'обоснование есть, решения нет');
}

{
  /* Решение 7: три числовых поля ожидаемого результата обязательны при
     регистрации. Во второй итерации по ним считается точность прогноза
     эксперта, поэтому пустые значения ломают не карточку, а метрику. */
  const р = отчёт.правило('Д-18', 'У зарегистрированной рекомендации заполнен ожидаемый результат (решение 7)');
  const поля = [['expectQzh', 'Δ Qж'], ['expectQn', 'Δ Qн'], ['expectEE', 'Δ ЭЭ']];
  /* Одиннадцать записей перенесены из «Формы 2» один в один, а трёх числовых
     полей ожидаемого результата в самой Форме 2 нет — это зафиксировано в
     решениях (раздел «Колонки»: поля требует ТЗ, но в Excel-форме отсутствуют,
     вопрос вынесен на согласование форм с Заказчиком). Для таких записей это
     не ошибка набора, а известный пробел источника: докладываем
     предупреждением. Для синтетики, которую генератор придумывает сам,
     незаполненное обязательное поле — уже нарушение. */
  каждая(р, (r) => {
    if (r.status === 'draft') return false;
    const нет = поля.filter(([k]) => r[k] === undefined || r[k] === null).map(([, l]) => l);
    if (!нет.length) return false;
    if (!r.synthetic) {
      р.предупреждение(`${п(r)} — запись из Формы 2, полей ожидаемого результата в источнике нет: ${нет.join(', ')}`);
      return false;
    }
    return `не заполнены обязательные поля ожидаемого результата: ${нет.join(', ')}`;
  });
  каждая(р, (r) => r.status === 'draft' && поля.some(([k]) => r[k] !== undefined)
    && 'у черновика заполнен ожидаемый результат, хотя регистрации ещё не было');
  /* Записям Формы 2 значения досочинены генератором, иначе полоса прогноза в
     карточке показывала три прочерка. Пробел источника от этого никуда не делся,
     и он должен оставаться видимым: молчание проверки означало бы, что данные
     пришли от Заказчика. */
  const досочинено = DATA.filter((r) => r.expectSynthetic);
  if (досочинено.length) {
    р.предупреждение(`у ${досочинено.length} записей Формы 2 ожидаемый результат досочинён макетом `
      + '(признак expectSynthetic): в источнике этих полей нет, при переносе в React заменить настоящими');
  }
}

/* ------------------------------ контроль ответа ------------------------------ */

{
  /* Решение 23: разведены «ответ пришёл поздно» и «ответа нет вовсе».
     Формулировки: в срок, с опозданием, просрочено, осталось, ожидает передачи. */
  const р = отчёт.правило('Д-19', 'Контроль ответа выведен из отметок времени, а не задан отдельно (решение 23)');
  const виды = ['none', 'pending', 'ok', 'late', 'overdue', 'waiting'];
  каждая(р, (r) => !виды.includes(r.controlKind) && `неизвестный вид контроля «${r.controlKind}»`);
  каждая(р, (r) => {
    /* Отмена происходит до передачи, просрочивать нечего — отдельная ветка. */
    const ждём = (r.status === 'draft' || r.status === 'cancelled') ? 'none'
      : r.status === 'registered' ? 'pending'
        : r.repliedAt ? (r.repliedAt <= r.dueAt ? 'ok' : 'late')
          : (NOW > r.dueAt ? 'overdue' : 'waiting');
    return r.controlKind !== ждём && `контроль ответа «${r.controlKind}», а из отметок времени следует «${ждём}»`;
  });
  каждая(р, (r) => ['ok', 'late'].includes(r.controlKind) && !r.repliedAt
    && 'контроль ответа говорит об ответе, а ответа нет');
  каждая(р, (r) => r.controlKind === 'overdue' && r.repliedAt
    && 'ответ помечен просроченным, хотя он получен — это «с опозданием»');
}

{
  /* Отмена происходит на стороне Исполнителя, пока рекомендация ещё
     «Зарегистрировано», то есть до передачи: решения по ней никогда не было
     и не будет. Без этого правила отменённая строка красилась бы в реестре
     красной кромкой «просрочено», хотя просрочивать нечего. */
  const р = отчёт.правило('Д-20', 'У отменённой рекомендации нет контроля ответа');
  каждая(р, (r) => r.status === 'cancelled' && r.controlKind !== 'none'
    && `у отменённой рекомендации контроль ответа «${r.controlKind}»`);
  каждая(р, (r) => r.status === 'cancelled' && r.decision && 'отменённая рекомендация имеет решение Заказчика');
  каждая(р, (r) => r.status === 'cancelled' && r.repliedAt && 'у отменённой рекомендации есть дата ответа');
}

{
  const р = отчёт.правило('Д-21', 'Величина отклонения от норматива согласована с видом контроля (решение 23)');
  каждая(р, (r) => {
    if (!['ok', 'late', 'overdue', 'waiting'].includes(r.controlKind)) return false;
    const от = r.controlKind === 'waiting' ? NOW : r.dueAt;
    const до = r.controlKind === 'waiting' ? r.dueAt : (r.repliedAt || NOW);
    const ждём = Math.round(workHoursBetween(от, до) * 3600000);
    return Math.abs(Math.round(r.controlDelta) - ждём) > 60000
      && `отклонение ${Math.round(r.controlDelta / 60000)} мин, а по рабочим часам ${Math.round(ждём / 60000)} мин`;
  });
}

/* ------------------------------ реализация и окно эффекта ------------------------------ */

{
  /* Решения 39, 43: факт и дату реализации определяет Исполнитель по
     телеметрии, а окно в 90 суток отсчитывается от даты реализации, а не от
     момента фиксации: эксперт может увидеть смену режима через день-другой. */
  const р = отчёт.правило('Д-22', 'Окно подтверждения открыто датой реализации и длится ровно 90 суток (решения 42, 43)');
  каждая(р, (r) => ОКНО.includes(r.status) && !r.factDate && 'окно есть, а даты фактической реализации нет');
  каждая(р, (r) => r.factDate && r.windowOpenAt !== r.factDate
    && `окно открыто ${r.windowOpenAt}, а реализация ${r.factDate} — окно обязано открываться датой реализации`);
  каждая(р, (r) => {
    if (!r.factDate || !r.windowCloseAt) return false;
    const сут = Math.round((дата(r.windowCloseAt) - дата(r.factDate)) / 86400000);
    return сут !== 90 && `окно длится ${сут} суток вместо 90`;
  });
  каждая(р, (r) => ОКНО.includes(r.status) && !r.completeness && 'не указана полнота реализации');
  каждая(р, (r) => ОКНО.includes(r.status) && !Number.isInteger(r.factFiles)
    && 'не заполнено число вложений к фиксации реализации');
  каждая(р, (r) => ОКНО.includes(r.status) && !r.factBy && 'не указано, кто зафиксировал реализацию');
}

{
  const р = отчёт.правило('Д-23', 'Даты реализации и фиксации не из будущего, фиксация не раньше реализации (решение 43)');
  каждая(р, (r) => r.factDate && дата(r.factDate) > NOW && `дата реализации ${r.factDate} в будущем`);
  каждая(р, (r) => r.factFixedAt && дата(r.factFixedAt) > NOW && 'момент фиксации в будущем');
  каждая(р, (r) => r.factDate && r.factFixedAt && дата(r.factFixedAt) < дата(r.factDate)
    && 'реализация зафиксирована раньше, чем произошла');
  /* Копия обязательна: дата() возвращает тот же объект Date, если ей его и
     передали, и setHours на нём испортил бы саму запись — проверка молча
     переписала бы данные, которые проверяет, и следующие правила прошли бы
     по искажённому набору. */
  каждая(р, (r) => {
    if (!r.factDate || !r.repliedAt) return false;
    const деньОтвета = new Date(r.repliedAt);
    деньОтвета.setHours(0, 0, 0, 0);
    return дата(r.factDate) < деньОтвета
      && `реализация ${r.factDate} раньше дня согласования — работы не могли начаться до решения Заказчика`;
  });
}

{
  /* Решение 41: полнота — поле, а не статус, и при частичной реализации
     пояснение обязательно (решение 44). Без пояснения «частично» в отчётности
     по договору не значит ничего. */
  const р = отчёт.правило('Д-24', 'При частичной реализации есть пояснение (решения 41, 44)');
  каждая(р, (r) => r.completeness === 'partial' && !r.factNote
    && 'реализация частичная, но не сказано, что именно не выполнено');
  каждая(р, (r) => r.completeness === 'full' && r.factNote
    && 'реализация полная, но заполнено пояснение о невыполненном');
}

{
  /* Обратная сторона решения 40: реализация существует только внутри окна.
     Если дата реализации или полнота появились на «Согласовано» или на
     «Отклонено», значит где-то остался промежуточный статус реализации. */
  const р = отчёт.правило('Д-25', 'Следы реализации живут только на статусах окна (решение 40)');
  const поля = ['factDate', 'factFixedAt', 'completeness', 'factNote', 'factFiles', 'windowOpenAt', 'windowCloseAt', 'dispute'];
  каждая(р, (r) => {
    if (ОКНО.includes(r.status)) return false;
    const есть = поля.filter((k) => r[k] !== undefined && r[k] !== null && r[k] !== '');
    return есть.length && `вне статусов окна заполнены поля реализации: ${есть.join(', ')}`;
  });
}

{
  const р = отчёт.правило('Д-26', 'Закрытое окно закрылось в прошлом, открытое ещё идёт (решение 40)');
  каждая(р, (r) => r.status === 'windowClosed' && дата(r.windowCloseAt) > NOW
    && `окно закрыто, но срок закрытия ${r.windowCloseAt} ещё не наступил`);
  каждая(р, (r) => r.status === 'windowOpen' && дата(r.windowCloseAt) <= NOW
    && `окно значится открытым, хотя срок ${r.windowCloseAt} уже вышел`);
}

/* ------------------------------ спор о дате ------------------------------ */

{
  /* Решения 47–49: Заказчик вправе оспорить дату, пока окно не закрыто; после
     закрытия эффект финализирован. Спор — поле, а не статус: окно не
     останавливается, расчёт до снятия возражения помечается предварительным. */
  const р = отчёт.правило('Д-27', 'Спор о дате возможен только при открытом окне (решения 47, 49)');
  каждая(р, (r) => r.dispute && r.status !== 'windowOpen'
    && `возражение по дате при статусе «${r.statusLabel}» — оспаривать можно только открытое окно`);
  каждая(р, (r) => {
    if (!r.dispute) return false;
    const d = r.dispute;
    if (!['open', 'accepted', 'declined'].includes(d.state)) return `неизвестное состояние спора «${d.state}»`;
    if (!d.reason) return 'возражение без обязательного обоснования';
    if (!d.proposedDate) return 'возражение без собственной даты';
    if (дата(d.at) > NOW) return 'возражение подано в будущем';
    if (дата(d.at) < дата(r.factDate)) return 'возражение подано раньше оспариваемой даты реализации';
    if (дата(d.proposedDate) > NOW) return `предлагаемая дата ${d.proposedDate} в будущем`;
    if (d.state === 'accepted' && r.factDate !== d.proposedDate) {
      return 'дата Заказчика принята, но дата реализации не пересчитана';
    }
    if (d.state === 'declined' && !d.resolution) return 'возражение отклонено без обоснования';
    if (d.state !== 'open' && !d.resolvedAt) return 'спор разрешён, но момент разрешения не зафиксирован';
    return false;
  });
}

/* ------------------------------ обсуждение ------------------------------ */

{
  /* Решения 52–54: комментарии общие, живут в одной ленте с событиями и ничего
     не двигают. До передачи вести обсуждение не с кем — Заказчик рекомендации
     ещё не видел. */
  const р = отчёт.правило('Д-28', 'Комментарии появляются не раньше передачи и не из будущего (решения 52, 53)');
  каждая(р, (r) => r.comments.some((c) => !r.sentAt) && 'есть комментарии, хотя рекомендация не передана');
  каждая(р, (r) => r.sentAt && r.comments.some((c) => c.at < r.sentAt) && 'комментарий раньше передачи Заказчику');
  каждая(р, (r) => r.comments.some((c) => c.at > NOW) && 'комментарий из будущего');
  каждая(р, (r) => r.comments.some((c) => !['exec', 'cust'].includes(c.side)) && 'у комментария неизвестная сторона');
  каждая(р, (r) => r.comments.some((c) => !c.author || !c.text) && 'комментарий без автора или без текста');
  каждая(р, (r) => r.comments.some((c) => c.side === 'cust') && !r.customer
    && 'комментарий Заказчика есть, а ответственный Заказчика не назначен');
  каждая(р, (r) => r.commentsCount !== r.comments.length && 'счётчик комментариев расходится с лентой');
  каждая(р, (r) => {
    const t = r.comments.map((c) => +c.at);
    return t.some((v, i) => i && v < t[i - 1]) && 'комментарии идут не по хронологии';
  });
}

/* ------------------------------ прочая целостность ------------------------------ */

{
  const р = отчёт.правило('Д-29', 'Обязательное содержание рекомендации заполнено');
  каждая(р, (r) => !r.problem && 'не заполнена проблема / отклонение');
  каждая(р, (r) => !r.action && 'не заполнено рекомендуемое мероприятие');
  каждая(р, (r) => !r.rationale && 'не заполнено технологическое обоснование (обязательно, шаг 3 мастера)');
  каждая(р, (r) => !r.executor && 'не назначен ответственный Исполнителя');
  каждая(р, (r) => !r.well && 'не указана скважина');
  каждая(р, (r) => r.kust === undefined || r.kust === null ? 'не указан куст' : false);
  каждая(р, (r) => typeof r.isPrimary !== 'boolean' && 'признак первичности не заполнен');
  каждая(р, (r) => !Number.isInteger(r.attachments) && 'число вложений не заполнено');
  каждая(р, (r) => r.customer && !r.sentAt && 'ответственный Заказчика назначен до передачи');
}

{
  const р = отчёт.правило('Д-30', 'Идентификаторы уникальны и записи упорядочены по дате регистрации');
  const ид = new Set();
  for (const r of DATA) {
    if (ид.has(r.id)) р.сбой(`${п(r)} — идентификатор ${r.id} повторяется`);
    ид.add(r.id);
  }
  for (let i = 1; i < DATA.length; i++) {
    if (DATA[i].regDate < DATA[i - 1].regDate) {
      р.сбой(`${п(DATA[i])} — набор не отсортирован по дате регистрации`);
      break;
    }
  }
}

{
  /* Отмена — действие Исполнителя на статусе «Зарегистрировано», то есть до
     передачи Заказчику (статусная модель решения 40, строка «Зарегистрировано»).
     Это же объяснение записано в data.js рядом с обнулением контроля ответа:
     «просрочивать уже нечего». Но момент передачи у отменённых записей всё
     равно проставлен и лежит в прошлом — и вкладка «История и обсуждение»
     рисует событие «Передана Заказчику» с датой. Получается рекомендация,
     которую Заказчику передали, а потом отменили в обход статусной модели.
     Ленты статусов, где это бросалось в глаза первым делом, больше нет
     (решение 69), но расхождение никуда не делось: оно в данных, а не в
     вёрстке, и переехало из ленты в историю. */
  const р = отчёт.правило('Д-32', 'Отмена происходит до передачи Заказчику (статусная модель, решение 40)');
  каждая(р, (r) => r.status === 'cancelled' && r.sentAt && r.sentAt <= NOW
    && `отменена, но момент передачи Заказчику проставлен (${r.sentAt.toLocaleString('ru-RU')}) и уже наступил — `
      + 'во вкладке «История и обсуждение» стоит событие «Передана Заказчику»');
}

{
  /* Полоса прогноза (решения 69, 70) показывает четыре величины: три Δ и
     прогнозный эффект в рублях. Все четыре заполняются на одном шаге мастера,
     значит и появляться обязаны вместе: заполненные Δ при пустых рублях дают
     на самом видном месте карточки прочерк, а пустые Δ при заполненных рублях —
     сумму, взявшуюся ниоткуда. */
  const р = отчёт.правило('Д-33', 'Ожидаемый результат и прогнозный эффект заполняются вместе (решения 7, 69)');
  каждая(р, (r) => r.expectQzh !== undefined && r.forecast === undefined
    && 'ожидаемый результат заполнен, а прогнозного эффекта в рублях нет — в полосе прогноза будет прочерк');
  каждая(р, (r) => r.forecast !== undefined && r.expectQzh === undefined
    && 'прогнозный эффект есть, а ожидаемого результата нет — сумма взялась ниоткуда');
  каждая(р, (r) => r.status === 'draft' && r.forecast !== undefined
    && 'у черновика заполнен прогнозный эффект, хотя ожидаемый результат вносят при регистрации');
}

{
  /* Нефть — часть жидкости, и прирост нефти в тоннах не может быть больше
     прироста жидкости в кубометрах: плотность нефти меньше единицы, так что
     Δ Qн ≤ Δ Qж всегда, а обычно заметно меньше. Числа в наборе рисуются двумя
     независимыми случайными величинами, поэтому пары вида «Δ Qж +4,1 м³/сут,
     Δ Qн +4,95 т/сут» попадают в полосу прогноза — то есть на самое видное
     место карточки, рядом с суммой в рублях. Для эксперта, который эти числа
     и выдаёт, такая пара — сразу видимая нелепость. */
  const р = отчёт.правило('Д-34', 'Прирост нефти не превышает прироста жидкости (физика, не решение)');
  каждая(р, (r) => typeof r.expectQzh === 'number' && typeof r.expectQn === 'number'
    && r.expectQn > r.expectQzh
    && `ожидаемый Δ Qн ${r.expectQn} т/сут больше Δ Qж ${r.expectQzh} м³/сут — нефти прибавляется больше, чем жидкости`);
}

{
  /* Мягкая проверка. Решение 1 говорит, что у черновика нет даты регистрации,
     но в наборе она есть у всех записей — иначе черновики некуда поставить в
     сортировке по умолчанию и они выпадут из реестра. Расхождение осознанное,
     но должно быть видно: в React-версии дату черновика нельзя показывать
     как «дату регистрации». */
  const р = отчёт.правило('Д-31', 'Дата регистрации у черновика (решение 1) — расхождение макета с решением');
  const черновики = DATA.filter((r) => r.status === 'draft' && r.regDate);
  if (черновики.length) {
    р.предупреждение(`у ${черновики.length} черновиков есть дата регистрации, хотя по решению 1 её у черновика нет; `
      + 'в макете она нужна для сортировки — при переносе в React показывать её как «дату регистрации» нельзя');
  }
}

