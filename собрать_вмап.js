/* Собирает макет/вмап.js из выгрузки вмап.json.

   Зачем отдельный файл, а не запись прямо в data.js: справочные данные ВМАП —
   это четыре тысячи строк, они меняются только с новой выгрузкой и читать их
   человеку незачем. data.js остаётся тем, что правят руками.

   Запуск после каждой новой выгрузки:
       node собрать_вмап.js
*/

const fs = require('fs');
const path = require('path');

const КОРЕНЬ = __dirname;
const выгрузка = JSON.parse(fs.readFileSync(path.join(КОРЕНЬ, 'вмап.json'), 'utf8'));

/* Буквенные коды месторождений для номера рекомендации. В самой ВМАП код
   числовой и у четырёх Южно-Ягунских он общий — 305, потому что для базы это
   одно месторождение, разрезанное по цехам. Нам нужен код, различающий узлы
   (решения 17, 77), поэтому таблица своя и ведётся руками. */
const КОДЫ = {
  'Южно-Ягунское / ЦДНГ-1 (Я)': 'ЮЯ1',
  'Южно-Ягунское / ЦДНГ-2 (Я)': 'ЮЯ2',
  'Южно-Ягунское / ЦДНГ-3 (Я)': 'ЮЯ3',
  'Южно-Ягунское / ЦДНГ-4 (Я)': 'ЮЯ4',
  'Кустовое (Видное и Восточно-Ягунское) / ЦДНГ-2 (Я)': 'КВ2',
  'Кустовое (Видное и Восточно-Ягунское) / ЦДНГ-7 (Я)': 'КВ7',
  'Восточно-Икилорское': 'ВИ',
  'Западно-Икилорское-обнова': 'ЗИ',
  'Тевлинско-Русскинское': 'ТР',
  'Северо-Ягунское': 'СЯ',
  'Грибное': 'ГР',
  'Дружное (Кумалиягунское и Танеевское)': 'ДР',
  'Новоортьягунское': 'НО',
  'Свободное': 'СВ',
  'Яркое': 'ЯР',
  'Восточно-Придорожное': 'ВП',
  'Равенское': 'РВ',
  'Разведочные площади': 'РП',
};

const месторождения = [...выгрузка.fields].sort((a, b) => b.wells - a.wells);
const индексПоля = new Map(месторождения.map((f, i) => [f.name, i]));

const нет = месторождения.filter((f) => !КОДЫ[f.name]);
if (нет.length) {
  console.error('Нет буквенного кода у месторождений:', нет.map((f) => f.name).join(', '));
  console.error('Добавьте их в таблицу КОДЫ и запустите снова.');
  process.exit(1);
}

/* Номер скважины берём из Name: именно он стоит в реестре и в Форме 2.
   Code у части скважин отличается — на экране это сбивало бы. */
const скважины = выгрузка.wells
  .filter((w) => w.name && w.field && индексПоля.has(w.field))
  .map((w) => [String(w.name).trim(), String(w.kust ?? '').trim(), индексПоля.get(w.field)])
  .sort((a, b) => a[2] - b[2] || a[0].localeCompare(b[0], 'ru', { numeric: true }));

const строка = (s) => `'${String(s).replace(/\\/g, '\\\\').replace(/'/g, "\\'")}'`;

/* Сколько номеров встречается больше одного раза — число идёт в комментарий
   готового файла, чтобы неочевидное свойство данных было видно на месте. */
const счёт = new Map();
for (const [n] of скважины) счёт.set(n, (счёт.get(n) || 0) + 1);
const повторов = [...счёт.values()].filter((n) => n > 1).length;

const текст = `/* Справочные данные ВМАП по ТПП «Когалымнефтегаз».

   Файл собран автоматически из выгрузки с дев-стенда — правит его скрипт
   собрать_вмап.js, а не человек. Новая выгрузка кладётся в вмап.json рядом,
   после чего скрипт запускается заново.

   Выгрузка от ${new Date().toLocaleDateString('ru-RU')}: ${месторождения.length} месторождений, ${скважины.length} скважин.
   Всего скважин в базе — ${выгрузка.wells_total_in_db}, остальные в других ТПП.

   Месторождение здесь — узел дерева ВМАП. Там, где месторождение разрабатывают
   несколько цехов, каждая пара идёт отдельным месторождением со своим
   буквенным кодом: в самой базе код у четырёх Южно-Ягунских общий, и номера
   рекомендаций по разным объектам совпали бы. */

const VMAP_FIELDS = [
${месторождения.map((f) => `  { name: ${строка(f.name)}, code: ${строка(КОДЫ[f.name])}, kusts: ${f.kusts_in_tree}, wells: ${f.wells} },`).join('\n')}
];

/* Скважины: [номер, куст, индекс месторождения в VMAP_FIELDS].
   Массивом, а не объектами: четыре тысячи записей с именами полей — это лишние
   двести килобайт на каждое открытие страницы. */
const VMAP_WELLS = [
${скважины.map(([n, k, f]) => `[${строка(n)},${строка(k)},${f}]`).join(',\n')}
];

/* Разворачиваем один раз при загрузке — дальше все экраны берут готовое. */
const FIELDS = VMAP_FIELDS.map((f) => f.name);
const FIELD_CODE = Object.fromEntries(VMAP_FIELDS.map((f) => [f.name, f.code]));
const FIELD_STATS = Object.fromEntries(VMAP_FIELDS.map((f) => [f.name, { kusts: f.kusts, wells: f.wells }]));

/** Номер скважины к сравнимому виду: регистр, пробелы и латиница, похожая на
    кириллицу. В базе встречается и «3407Г», и «3407г» с латинской «g». */
function normWell(s) {
  let x = String(s ?? '').trim().toLowerCase().replace(/\\s/g, '');
  for (const [lat, cyr] of [['a', 'а'], ['c', 'с'], ['e', 'е'], ['o', 'о'], ['p', 'р'],
    ['x', 'х'], ['k', 'к'], ['m', 'м'], ['t', 'т'], ['b', 'в'], ['h', 'н'], ['g', 'г']]) {
    x = x.split(lat).join(cyr);
  }
  return x;
}

/* Номер скважины не уникален даже внутри одного ТПП: ${повторов} номеров
   встречаются на разных месторождениях. Поэтому индекс отдаёт список
   кандидатов, а не одну запись, — выбирать должен тот, кто знает куст. */
const WELL_INDEX = (() => {
  const m = new Map();
  for (const [n, k, f] of VMAP_WELLS) {
    const key = normWell(n);
    if (!m.has(key)) m.set(key, []);
    m.get(key).push({ well: n, kust: k, field: VMAP_FIELDS[f].name });
  }
  return m;
})();

/** Скважина по номеру. Куст, если известен, снимает неоднозначность. */
function findWell(номер, куст) {
  const список = WELL_INDEX.get(normWell(номер));
  if (!список || !список.length) return null;
  if (куст !== undefined && куст !== null && куст !== '') {
    const точное = список.find((w) => w.kust === String(куст));
    if (точное) return точное;
  }
  return список[0];
}

/** Скважины месторождения, по возрастанию номера. */
function wellsOfField(name) {
  const i = VMAP_FIELDS.findIndex((f) => f.name === name);
  return i < 0 ? [] : VMAP_WELLS.filter((w) => w[2] === i).map((w) => w[0]);
}
`;

const путь = path.join(КОРЕНЬ, 'макет', 'вмап.js');
fs.writeFileSync(путь, текст, 'utf8');

const кб = (fs.statSync(путь).size / 1024).toFixed(0);
console.log(`Записано: ${путь} (${кб} КБ)`);
console.log(`  месторождений: ${месторождения.length}`);
console.log(`  скважин: ${скважины.length}`);
console.log(`  крупнейшее: ${месторождения[0].name} — ${месторождения[0].wells} скважин`);
