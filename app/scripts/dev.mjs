/* Запуск дев-сервера с пересчётом эффекта сразу после подъёма.
 *
 * Зачем обёртка. Расчёт эффекта убран из рендера страницы: она читает готовое
 * из `rec.effect_daily`, а считает тот, кто поднят постоянно. В рабочем
 * контуре это бэкенд по расписанию, на демо расписания нет — его роль играет
 * подъём сервера. Каждый запуск = один проход планировщика.
 *
 * Почему не хук `instrumentation.ts`, куда это просится по смыслу: Next
 * собирает инструментацию для всех слоёв, включая клиентский, а туда через
 * `pg` тянется `fs`, которого там нет. Модуль не собирается — и вместе с ним
 * не собирается приложение: все страницы отдают 500. Проверено, откачено.
 *
 * Отсюда способ: дождаться, пока сервер начнёт отвечать, и дёрнуть его же
 * маршрут `POST /api/effect/recalc`. Расчёт при этом идёт внутри сервера, тем
 * же кодом домена, и второй реализации формулы не появляется.
 *
 * Запуск: node scripts/dev.mjs  (через npm run dev / dev:only)
 */

import { spawn } from 'node:child_process';
import { existsSync, mkdirSync, rmSync, writeFileSync, unlinkSync } from 'node:fs';

const PORT = 3100;
const АДРЕС = `http://localhost:${PORT}`;

/* Метка живого сервера. Пишется при подъёме, снимается при штатном выходе;
   уцелевшая метка значит, что прошлый процесс убили, а не закрыли.

   Лежит в node_modules, а НЕ в `.next`: тот при старте next dev вычищает сам,
   и метка исчезала вместе с ним — проверено, первая версия так и не срабатывала.
   node_modules заведомо вне гита и переживает снос `.next`. */
const КАТАЛОГ_МЕТКИ = 'node_modules/.cache';
const МАРКЕР = `${КАТАЛОГ_МЕТКИ}/dev-alive`;

/* Убитый на полуслове next dev оставляет `.next` недописанным: манифест
   ссылается на чанк, которого никто не дописал, и сервер поверх такого
   каталога отдаёт 500 «Cannot find module ./vendor-chunks/recharts.js» —
   ошибку, по которой не догадаешься, что дело в мусоре, а не в коде. Ловилось
   уже трижды, каждый раз лечилось руками. Поэтому чистим сами.

   Условие двойное: метка осталась И порт молчит. Без второй половины запуск
   на соседнем порту (см. recmodule-3101 в .claude/launch.json) снёс бы каталог
   из-под работающего сервера. */
if (existsSync(МАРКЕР)) {
  if (await отвечает()) {
    console.warn('[dev] метка прошлого запуска на месте, но порт занят —'
      + ' .next не трогаю: похоже, сервер уже поднят.');
  } else {
    console.warn('[dev] прошлый сервер не завершился штатно — сношу .next,'
      + ' первая сборка будет дольше обычного.');
    rmSync('.next', { recursive: true, force: true });
  }
}

mkdirSync(КАТАЛОГ_МЕТКИ, { recursive: true });
writeFileSync(МАРКЕР, String(process.pid));

/* Снимаем метку на любом выходе, в том числе по Ctrl+C: иначе следующий
   запуск примет штатное завершение за убийство и пересоберёт зря. */
function снятьМетку() {
  try { unlinkSync(МАРКЕР); } catch { /* уже снята или каталог снесли */ }
}
process.on('exit', снятьМетку);
for (const сигнал of ['SIGINT', 'SIGTERM', 'SIGHUP', 'SIGBREAK']) {
  process.on(сигнал, () => { снятьМетку(); process.exit(0); });
}

/* Сервер держим на своих stdio: вывод Next должен идти в терминал как обычно,
   иначе обёртка съест и ошибки компиляции, и адрес, на который заходить. */
const сервер = spawn('npx', ['next', 'dev', '-p', String(PORT)], {
  stdio: 'inherit',
  shell: process.platform === 'win32',
});

сервер.on('exit', (код) => { снятьМетку(); process.exit(код ?? 0); });

/* Пересчёт не должен мешать работе: сервер уже отвечает, человек уже открыл
   реестр, а расчёт идёт фоном и обновляет цифры к моменту, когда до карточки
   дойдёт очередь. */
пересчитатьКогдаПоднимется().catch((e) => {
  console.warn('[эффект] пересчёт при запуске не выполнен:', e.message ?? e);
});

async function пересчитатьКогдаПоднимется() {
  /* Первая компиляция маршрута в dev занимает секунды, поэтому ждём долго и
     редко: частый опрос ничего не ускорит, а лог засорит. */
  for (let i = 0; i < 60; i += 1) {
    if (await отвечает()) {
      const начало = Date.now();
      const ответ = await fetch(`${АДРЕС}/api/effect/recalc`, { method: 'POST' });
      if (!ответ.ok) throw new Error(`маршрут пересчёта ответил ${ответ.status}`);
      const { ok, total, failed } = await ответ.json();
      const сек = ((Date.now() - начало) / 1000).toFixed(1);
      console.log(`[эффект] пересчитано окон: ${ok} из ${total}`
        + `${failed ? `, сбоев: ${failed}` : ''}, ${сек} с`);
      return;
    }
    await пауза(1000);
  }
  throw new Error('сервер не поднялся за минуту');
}

async function отвечает() {
  try {
    /* HEAD по корню: он не рендерит страницу целиком и не мешает первой
       настоящей загрузке занять кэш компиляции. */
    const r = await fetch(АДРЕС, { method: 'HEAD' });
    return r.status > 0;
  } catch {
    return false;
  }
}

const пауза = (мс) => new Promise((r) => setTimeout(r, мс));
