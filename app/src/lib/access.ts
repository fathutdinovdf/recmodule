/* ---------------------------- граница видимости ----------------------------
 *
 * Зона ответственности — набор месторождений, пустой означает «все объекты
 * договора» (решение 87). Это именно граница, а не фильтр, который можно
 * снять: от неё считаются и строки реестра, и плитки, и счётчики в фильтрах
 * колонок. Поэтому фрагмент условия один на все запросы — вписывать его руками
 * в каждый значит однажды забыть в одном и показать Заказчику чужой цех.
 *
 * Идентификаторы подставляются числами, а не параметрами запроса: фрагмент
 * приклеивается к запросам, где нумерация параметров уже занята отбором
 * реестра, и сдвиг номеров ломал бы её. Числа приходят из нашей же базы и
 * проходят через Number() — строке сюда попасть неоткуда.
 */
export function границаВидимости(u: SessionUser | null, alias = 'r'): string {
  /* Не вошёл — не видит ничего. До запроса такое дойти не должно (оболочка
     уводит на форму входа), но условие «TRUE по умолчанию» — не та ошибка,
     которую хочется оставить на будущее. */
  if (!u) return 'false';

  const части: string[] = [];

  if (u.fields.length) {
    const ids = u.fields.map((f) => Number(f.id)).filter(Number.isInteger);
    части.push(`${alias}.field_id IN (${ids.join(', ') || 'NULL'})`);
  }

  /* Отбор по ответственному: у эксперта АКЭ рекомендация именная — он её
     выдал и он же ведёт её по телеметрии. Черновик виден автору: номера у
     него нет, и в реестре его больше не видит никто. */
  if (u.onlyOwn) {
    части.push(`(${alias}.executor_id = ${Number(u.id)} OR ${alias}.author_id = ${Number(u.id)})`);
  }

  return части.length ? части.join(' AND ') : 'true';
}
