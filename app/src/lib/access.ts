/* Что кому можно.
 *
 * Одно место на всё приложение. Раньше проверки стояли по месту: «Заказчик и
 * canDecide» в решении, «Исполнитель» в фиксации реализации — и каждая новая
 * страница переписывала условие заново. Расхождение в таком условии не падает
 * и не подсвечивается: оно просто однажды пускает не того.
 *
 * Проверки здесь возвращают признак, а не бросают исключение: серверные
 * действия отвечают формой с внятным текстом, и подменять его страницей ошибки
 * значило бы ухудшить работу ради единообразия.
 */

import type { SessionUser } from './session';

export const этоИсполнитель = (u: SessionUser | null): boolean => u?.side === 'executor';

/** Решение по рекомендации принимает Заказчик, и только с правом решения (решение 89). */
export const этоРешающий = (u: SessionUser | null): boolean =>
  u?.side === 'customer' && u.canDecide;

/** Ставки экономической модели правит не роль, а отдельное полномочие (решение 95). */
export const правитЭкономику = (u: SessionUser | null): boolean => !!u?.canEditEconomy;

