'use server';

/* Смена пользователя — подмена входа, а не функция модуля.
 *
 * В рабочем контуре пользователь приходит из ВМАП и не выбирается. Здесь он
 * выбирается, потому что показывать нечего иначе: у Заказчика есть решающие и
 * наблюдатели без права решения, а фиксация факта реализации — вообще действие
 * Исполнителя. Без переключателя половину экранов невозможно ни проверить, ни
 * показать.
 */

import { cookies } from 'next/headers';
import { revalidatePath } from 'next/cache';
import { КУКА_ПОЛЬЗОВАТЕЛЯ } from './session';

export async function switchUser(login: string): Promise<void> {
  (await cookies()).set(КУКА_ПОЛЬЗОВАТЕЛЯ, login, {
    path: '/',
    httpOnly: true,
    sameSite: 'lax',
    maxAge: 60 * 60 * 24 * 365,
  });
  /* Перерисовать нужно всё: от пользователя зависят и шапка, и состав кнопок
     на карточке. */
  revalidatePath('/', 'layout');
}
