/* Один список окон действий карточки: заголовок, тон, форма скелетона.
 *
 * Зачем отдельный файл. Окно теперь открывается ДО ответа сервера: кнопка
 * рисует заглушку сама, а настоящее окно приезжает следом и её заменяет. Чтобы
 * подмена не бросалась в глаза, заголовок у заглушки и у настоящего окна
 * обязан совпадать буквально — а значит, у него должен быть один источник, а
 * не два литерала в разных файлах, которые разъедутся при первой же правке.
 *
 * Отсюда же берётся ширина и тон: заглушка обязана совпасть с настоящим окном
 * и по геометрии, иначе при подмене окно дёрнется.
 *
 * Файл намеренно без 'use client': его читают и серверные страницы (настоящие
 * окна), и клиентские кнопки. Экспорт из клиентского модуля приехал бы на
 * сервер ссылкой, а не значением, — те же грабли, что с `tabs-def.ts`.
 */

export interface МетаОкна {
  title: string;
  /** Необратимое действие: значок и красный заголовок. */
  tone?: 'danger';
  /** Сколько полей рисует скелетон. 0 — окно-подтверждение, полей нет. */
  fields: number;
  /** Есть поля в строку — окну нужно 560 вместо 480. */
  wide?: boolean;
}

export const ОКНА = {
  /* Жизненный цикл — из меню в шапке. */
  register: { title: 'Зарегистрировать рекомендацию', fields: 0 },
  delete: { title: 'Удалить черновик', tone: 'danger', fields: 0 },
  cancel: { title: 'Отменить рекомендацию', tone: 'danger', fields: 1 },
  resend: { title: 'Внести уточнение и передать', fields: 1 },
  copy: { title: 'Создать новую на основе этой', fields: 0 },

  /* Решение Заказчика — вкладка «Сводка». */
  accept: { title: 'Принять рекомендацию', fields: 2, wide: true },
  reject: { title: 'Отклонить рекомендацию', tone: 'danger', fields: 2, wide: true },
  clarify: { title: 'Запросить уточнение', fields: 1, wide: true },

  /* Реализация и спор о дате. */
  fact: { title: 'Зафиксировать реализацию', fields: 2, wide: true },
  close: { title: 'Закрыть окно досрочно', tone: 'danger', fields: 1 },
  dispute: { title: 'Возражение по дате реализации', fields: 2 },
  acceptDispute: { title: 'Принять дату Заказчика', tone: 'danger', fields: 0 },
  declineDispute: { title: 'Отклонить возражение по дате', fields: 1 },

  /* Спор о базовых значениях — вкладка «Расчёт эффекта». */
  baseDispute: { title: 'Возражение по базовым значениям', fields: 2 },
  baseAccept: { title: 'Принять базу Заказчика', tone: 'danger', fields: 0 },
  baseDecline: { title: 'Отклонить возражение по базе', fields: 1 },
} as const satisfies Record<string, МетаОкна>;

export type КлючОкна = keyof typeof ОКНА;

/* `as const` выше сужает каждую запись до её литералов, и у окна без `tone`
   свойства `tone` в типе просто нет. Обе функции ниже возвращают общий тип
   `МетаОкна`, чтобы читающая сторона не разбирала объединение из 16 форм. */

/** Заголовок, тон и форма скелетона — для заглушки окна. */
export function мета(ключ: КлючОкна): МетаОкна {
  return ОКНА[ключ];
}

/** Свойства окна из его ключа: `<ActionDialog {...окно('reject')}>`. */
export function окно(ключ: КлючОкна) {
  const м: МетаОкна = ОКНА[ключ];
  return {
    title: м.title,
    tone: м.tone,
    className: м.wide ? 'max-w-[560px]' : undefined,
  };
}
