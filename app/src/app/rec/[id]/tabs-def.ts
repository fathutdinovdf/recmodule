/* Состав и порядок вкладок карточки.
 *
 * Лежит отдельно от компонента вкладок намеренно. Компонент помечен
 * 'use client' — активная вкладка определяется путём, — а любой экспорт из
 * клиентского модуля приезжает на сервер клиентской ссылкой, а не значением.
 * Серверная страница, которая берёт отсюда вкладку по умолчанию, получала бы
 * вместо строки прокси-объект и падала на подстановке его в адрес редиректа.
 *
 * Порядок не такой, как в макете: «Расчёт эффекта» стоит сразу за
 * «Реализацией», а не последним седьмым. Причина — процесс: реализация
 * открывает окно, окно даёт эффект, и две вкладки об одном и том же должны
 * лежать рядом. Аналоги, файлы, связи и история — справка вокруг, она и в
 * макете шла после сути.
 */

export interface TabDef {
  key: string;
  label: string;
  /** Вкладка, у которой ещё нет своей страницы, показывается приглушённой. */
  ready?: boolean;
}

export const ВКЛАДКИ: TabDef[] = [
  { key: 'summary', label: 'Сводка', ready: true },
  { key: 'impl', label: 'Реализация', ready: true },
  { key: 'effect', label: 'Расчёт эффекта', ready: true },
  { key: 'analogs', label: 'Аналоги', ready: true },
  { key: 'files', label: 'Файлы', ready: true },
  { key: 'links', label: 'Связи' },
  { key: 'log', label: 'История и обсуждение', ready: true },
];

/** Первая вкладка со своей страницей — на неё уходит адрес без сегмента. */
export const ВКЛАДКА_ПО_УМОЛЧАНИЮ = ВКЛАДКИ.find((t) => t.ready)!.key;
