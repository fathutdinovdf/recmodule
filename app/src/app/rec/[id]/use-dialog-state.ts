'use client';

/* Открытость окна действия: состояние плюс уборка `?form=` при закрытии руками.
 *
 * Общий хук для всех окон действий карточки (был впервые собран для спора о
 * базе, теперь используется всеми). Окно стоит в разметке закрытым, открывает
 * его состояние, а не переход по `?form=…`; адрес задаёт лишь НАЧАЛЬНУЮ
 * открытость — присланная ссылка и перезагрузка по-прежнему открывают окно.
 * Закрытие руками убирает параметр, иначе «назад» или обновление открывали бы
 * его снова.
 *
 * `готово` — признак успешного ответа действия (`'готово' in ответ` на
 * стороне вызывающего): закрываем окно сами, не дожидаясь клика по «Отмена»,
 * потому что revalidatePath уже перерисовал карточку под ним.
 *
 * `стартОткрыто` открывает окно и ПОЗЖЕ первого рендера, не только на старте.
 * Кнопка внутри самого окна (спор о базе, решение Заказчика) открывает его
 * прямым кликом — `useState` тут ни при чём, компонент реагирует на событие.
 * Но у пяти окон меню шапки (регистрация и т.д.) своей кнопки на вкладке нет:
 * их открывает пункт меню в ДРУГОМ поддереве компонентов через
 * `router.push(...?form=…)`, а окно к этому моменту уже смонтировано с
 * `открыто=false` — переход просто меняет входящий проп, а `useState` не
 * перечитывает initial value при каждом рендере. Без этого эффекта клик по
 * меню молча ничего не открывал. */

import { useEffect, useState } from 'react';
import { useRouter, usePathname } from 'next/navigation';

export function useОкноДействия(стартОткрыто: boolean, готово: boolean) {
  const [открыто, setОткрыто] = useState(стартОткрыто);
  const router = useRouter();
  const pathname = usePathname();

  useEffect(() => {
    if (готово) setОткрыто(false);
  }, [готово]);

  useEffect(() => {
    if (стартОткрыто) setОткрыто(true);
  }, [стартОткрыто]);

  const переключить = (значение: boolean) => {
    setОткрыто(значение);
    if (!значение && window.location.search.includes('form=')) router.replace(pathname);
  };

  return [открыто, переключить] as const;
}
