/* Живая лента обсуждения: поток новых реплик в открытую карточку.
 *
 * SSE, а не WebSocket. Поток нужен в одну сторону — сервер → браузер, —
 * отправка идёт обычным POST, и ради односторонней струи заводить второй
 * сервер незачем: SSE работает штатным маршрутом Next, а при встраивании в
 * SPA ВМАП переезжает как есть, потому что EventSource ничего не знает про
 * фреймворк.
 *
 * Что уходит в канал: готовая реплика целиком. Триггер в базе присылает
 * только её номер (предел полезной нагрузки NOTIFY — 8000 байт), поэтому
 * текст и вложения дочитываются здесь.
 */

import { getComment } from '@/db/log';
import { подписатьсяНаРеплики } from '@/db/notify';
import { currentUser } from '@/lib/session';

/* Поток живёт минутами и не должен ни кэшироваться, ни собираться заранее. */
export const dynamic = 'force-dynamic';
export const runtime = 'nodejs';

/* Пустой комментарий раз в 25 секунд. Прокси и балансировщики рвут
   молчащее соединение примерно через минуту, а браузер потом переподключается
   и на пустом месте показывает «связь потеряна». */
const ПУЛЬС_МС = 25_000;

/* Сколько живёт одно соединение до штатного закрытия. Пять минут — так, чтобы
   переподключений было немного, а зависших соединений не копилось. */
const ЖИЗНЬ_ПОТОКА_МС = 5 * 60_000;

export async function GET(req: Request, { params }: { params: Promise<{ id: string }> }) {
  const { id } = await params;
  const recId = Number(id);
  if (!Number.isFinite(recId)) return new Response('Bad id', { status: 400 });

  const user = await currentUser();
  const encoder = new TextEncoder();

  const stream = new ReadableStream({
    start(controller) {
      let жив = true;

      /* Любая запись в поток может застать его уже закрытым: браузер уходит со
         страницы в произвольный момент, а очередь на этой стороне про это ещё
         не знает. Исключение отсюда некому поймать — оно уронило бы процесс
         рендера целиком, — поэтому глушится здесь и закрывает поток. */
      const писать = (кусок: string) => {
        if (!жив) return;
        try {
          controller.enqueue(encoder.encode(кусок));
        } catch {
          закрыть();
        }
      };

      const послать = (событие: string, данные: unknown) =>
        писать(`event: ${событие}\ndata: ${JSON.stringify(данные)}\n\n`);

      const отписаться = подписатьсяНаРеплики(recId, async ({ commentId }) => {
        try {
          const реплика = await getComment(commentId, user?.id ?? null);
          /* Своя реплика уже нарисована оптимистично — но послать её всё равно
             надо: у автора может быть открыта вторая вкладка, а клиент отличит
             её по номеру и заменит временную запись, а не задвоит. */
          if (реплика) послать('comment', { ...реплика, at: реплика.at.toISOString() });
        } catch {
          /* Не смогли прочитать реплику — лента её не увидит до перезагрузки.
             Это лучше, чем упавший процесс. */
        }
      });

      const пульс = setInterval(() => писать(': пульс\n\n'), ПУЛЬС_МС);

      /* Поток не живёт вечно. В dev-режиме Next при перекомпиляции ждёт, пока
         запросы завершатся, и висящее часами соединение мешает ему собраться;
         в проде так же копятся соединения на перезапуске. Браузер восстановит
         связь сам — EventSource для того и придуман. */
      const срок = setTimeout(() => закрыть(), ЖИЗНЬ_ПОТОКА_МС);

      function закрыть() {
        if (!жив) return;
        жив = false;
        clearInterval(пульс);
        clearTimeout(срок);
        отписаться();
        try { controller.close(); } catch { /* уже закрыт браузером */ }
      }

      req.signal.addEventListener('abort', закрыть);
      послать('ready', { recId });
    },
  });

  return new Response(stream, {
    headers: {
      'Content-Type': 'text/event-stream; charset=utf-8',
      'Cache-Control': 'no-cache, no-transform',
      Connection: 'keep-alive',
      /* Nginx иначе буферизует поток и отдаёт его пачкой в конце — то есть
         никогда: живая лента превращается в мёртвую. */
      'X-Accel-Buffering': 'no',
    },
  });
}
