/* Инбокс инженера Заказчика — технолога ЦДНГ с правом решения.
 *
 * На какой вопрос отвечает экран: «по каким рекомендациям тикает МОЙ норматив
 * ответа». Поэтому первым стоит просроченное (hot), за ним идущий срок (warn) —
 * это два блока «ход за мной», и только они должны попадать в значок левой
 * навигации. Ниже — наблюдение: согласованное без работ (напоминание
 * организовать мероприятие) и открытые окна эффекта (последний шанс возразить
 * по дате реализации). Состав и тексты «why» — из макет/inbox.js,
 * buildEngineer.
 *
 * Порядок внутри блоков — «сначала горит»: просроченное — по величине
 * просрочки (дольше молчим — выше), идущее — по остатку (меньше времени —
 * выше), окна — по ближайшему закрытию. Величины считает control() из
 * domain/workhours — тот же расчёт, что у тега строки; принадлежность блоку
 * при этом решает control_kind из SQL: он общий с реестром, и числа блока
 * обязаны сходиться с реестром после перехода по ссылке.
 *
 * Отличия от макета — сознательные:
 *   – «зоны ЦДНГ» как отдельного понятия в приложении нет: граница видимости
 *     роли (границаВидимости, решение 87) и есть зона, причём та же граница
 *     режет и реестр. Поэтому макетные оговорки «ссылка ведёт в реестр без
 *     ограничения зоной» убраны — здесь блок и реестр видят одно и то же;
 *   – глубокие ссылки ведут на фильтр колонки «Контроль ответа»
 *     (/?control=overdue, /?control=waiting): отбор в точности совпадает с
 *     условием блока, макетного alert=soon (два рабочих часа) у реестра нет;
 *   – эксперт, выдавший рекомендацию, показан в строке дополнительной
 *     подписью (task__r4), а не в третьей строке, как в макете: состав
 *     третьей строки зашит в общий компонент Строка, и расширять его ради
 *     одной роли — трогать общий файл из параллельной ветки;
 *   – лимит окон — общий, 6 строк (в макете 3): у блока появился переход
 *     «остальные в реестре», которого в макете не было, и резать список
 *     вдвое ради экономии экрана больше незачем.
 */

import type { InboxRow } from '@/db/inbox';
import { строкиНаРешении, type СтрокаНаРешении } from '@/db/inbox-engineer';
import { дата, сутки } from '@/lib/format';
import { control, toWindow } from '@/domain/workhours';

/* Типы повторяют Блок/Плитка/Инбокс из ../page.tsx: они там не экспортированы,
   а экспортировать их — правка общего файла из параллельной ветки. Совпадение
   проверяет TypeScript структурно — в месте, где билдер вписан в БИЛДЕРЫ. */
interface Блок {
  id: string;
  tone: 'hot' | 'warn' | 'calm';
  act?: boolean;
  title: string;
  why?: string;
  rows: InboxRow[];
  empty?: string;
  href?: (r: InboxRow) => string;
  when: (r: InboxRow) => string;
  extra?: (r: InboxRow) => string;
  deep?: string;
  deepLabel?: string;
}

interface Плитка { n: number; l: string; href: string }

export interface Инбокс { плитки: Плитка[]; блоки: Блок[] }

const МС_СУТОК = 86_400_000;
const суткиНазад = (d: Date, now: Date) => Math.floor((now.getTime() - d.getTime()) / МС_СУТОК);
const суткиДо = (d: Date, now: Date) => Math.round((d.getTime() - now.getTime()) / МС_СУТОК);
/* «Меньше суток» вместо «0 суток» — то же правило, что у эксперта: ноль
   читается как «ничего не ждём», хотя ждём — просто меньше суток. */
const давность = (n: number) => (n <= 0 ? 'меньше суток' : сутки(n));

/* Эксперт, выдавший рекомендацию, — адресат вопросов инженера по существу.
   В реестре инженера колонки исполнителя по умолчанию нет, поэтому имя несёт
   строка инбокса (в макете — showExecutor). */
const эксперт = (r: InboxRow) => `эксперт ${r.executorName ?? '—'}`;

export async function инбоксИнженера(
  все: InboxRow[], _горизонт: number, now: Date,
): Promise<Инбокс> {
  /* sent/review дочитываются отдельно: строкиИнбокса() собраны под эксперта
     и статусы «у Заказчика» не возвращают, а у инженера это главные блоки. */
  const наРешении = await строкиНаРешении();
  const t = (d: Date | null) => (d ? d.getTime() : Number.MAX_SAFE_INTEGER);

  /* Рабочие часы до срока или сверх него — только для порядка и текстов;
     принадлежность блоку решает control_kind из SQL (см. шапку). */
  const часы = new Map(наРешении.map((r) => [
    r.id,
    control({ status: r.status, sentAt: r.sentAt, dueAt: r.dueAt, repliedAt: r.repliedAt }, now).hours,
  ]));

  const просрочено = наРешении.filter((r) => r.controlKind === 'overdue')
    .sort((a, b) => (часы.get(b.id) ?? 0) - (часы.get(a.id) ?? 0));
  const идётСрок = наРешении.filter((r) => r.controlKind === 'waiting')
    .sort((a, b) => (часы.get(a.id) ?? 0) - (часы.get(b.id) ?? 0));
  /* Подмножество «истекает в ближайшие два рабочих часа» — для текста блока:
     остаток в календарных сутках обманчив, в рабочих часах — нет. */
  const скороИстечёт = идётСрок.filter((r) => (часы.get(r.id) ?? 0) <= 2);

  const согласовано = все.filter((r) => r.status === 'approved')
    .sort((a, b) => t(a.repliedAt) - t(b.repliedAt));
  /* Сортировка по дате закрытия, а не по дате фиксации: единственное действие,
     которое здесь ещё возможно, — возразить по дате реализации, и возможно оно
     только пока окно открыто. Значит сверху то, что закроется раньше. */
  const окна = все.filter((r) => r.status === 'windowOpen' && r.windowCloseAt)
    .sort((a, b) => t(a.windowCloseAt) - t(b.windowCloseAt));

  /* Норматив идёт только внутри рабочего окна — вне его честно сказать, что
     сейчас он стоит. В макете это была константа («сейчас, до 09:00»), потому
     что NOW там заморожен; у приложения время настоящее. */
  const окноЗакрыто = toWindow(now).getTime() > now.getTime();

  const блоки: Блок[] = [
    {
      id: 'b-overdue', tone: 'hot', act: true, rows: просрочено,
      title: 'Просрочен ответ — разобрать в первую очередь',
      why: 'Норматив ответа истёк, время считается рабочими часами. Быстрых кнопок '
        + '«принять» и «отклонить» здесь нет намеренно: решение принимается в карточке, '
        + 'после технологического обоснования, — но дорога до неё в один клик.',
      deep: '/?control=overdue',
      deepLabel: 'просроченные в реестре',
      when: (r) => `передано ${дата(r.sentAt, true)}`,
      /* «Карточку открыли, решения нет» и «карточка ещё не открыта» — разные
         упрёки: во втором случае рекомендацию ещё никто не читал. */
      extra: (r) => `срок был ${дата(r.dueAt, true)} · ${r.status === 'review'
        ? `карточку открыли ${дата((r as СтрокаНаРешении).openedAt, true)}, решения нет`
        : 'карточка ещё не открыта'} · ${эксперт(r)}`,
      empty: 'Просроченных ответов нет.',
    },
    {
      id: 'b-soon', tone: 'warn', act: true, rows: идётСрок,
      title: 'Срок идёт — ответить сегодня',
      /* Текст собирается из данных: на другом наборе «истекает N» молча
         превратилось бы в ложь. */
      why: 'Норматив ещё не истёк. Остаток считается рабочими часами, пн–пт 09:00–24:00: '
        + 'календарные сутки и сутки норматива — разные величины'
        + (окноЗакрыто ? ', и сейчас, пока окно закрыто, он вообще не идёт. ' : '. ')
        + (скороИстечёт.length
          ? `${скороИстечёт.length} из них истекает в ближайшие два рабочих часа.`
          : 'В ближайшие два рабочих часа не истекает ни одна.'),
      deep: '/?control=waiting',
      deepLabel: 'все с идущим сроком, в реестре',
      when: (r) => `передано ${дата(r.sentAt, true)}`,
      extra: (r) => `ответить до ${дата(r.dueAt, true)} · ${эксперт(r)}`,
      empty: 'Сейчас никто не ждёт вашего ответа по нормативу.',
    },
    {
      id: 'b-approved', tone: 'calm', rows: согласовано,
      title: 'Согласовано — работы не начаты',
      why: 'Решение принято, но по телеметрии режим на скважине прежний. Исполнитель '
        + 'ждёт смены режима, чтобы зафиксировать реализацию: пока её нет, окно '
        + 'подтверждения эффекта не открывается и эффект не считается.',
      deep: '/?tile=approved',
      deepLabel: 'согласованные по вашей зоне, в реестре',
      when: (r) => `решение ${дата(r.repliedAt)}`,
      extra: (r) => (r.repliedAt
        ? `${давность(суткиНазад(r.repliedAt, now))} без изменения режима · ${эксперт(r)}`
        : эксперт(r)),
      empty: 'Всё согласованное уже в работе или реализовано.',
    },
    {
      id: 'b-window', tone: 'calm', rows: окна,
      title: 'Окна подтверждения эффекта в вашей зоне',
      why: 'Дату реализации определил Исполнитель по телеметрии. Не согласны — возразить '
        + 'можно, пока окно не закрыто: после закрытия эффект финализирован и дата '
        + 'не пересматривается.',
      /* Возражение живёт на вкладке реализации — туда и ведём. */
      href: (r) => `/rec/${r.id}/impl`,
      deep: '/?tile=window',
      deepLabel: 'все открытые окна, в реестре',
      when: (r) => `дата реализации ${дата(r.factDate)}`,
      extra: (r) => `окно до ${дата(r.windowCloseAt)}`
        + (r.windowCloseAt ? ` · осталось ${давность(суткиДо(r.windowCloseAt, now))}` : '')
        + ` · ${эксперт(r)}`,
      empty: 'Открытых окон в вашей зоне нет.',
    },
  ];

  const плитки: Плитка[] = [
    { n: просрочено.length, l: 'Просрочено', href: '#b-overdue' },
    { n: идётСрок.length, l: 'Срок идёт', href: '#b-soon' },
    { n: согласовано.length, l: 'Согласовано, работ нет', href: '#b-approved' },
    { n: окна.length, l: 'Окна эффекта открыты', href: '#b-window' },
  ];

  return { плитки, блоки };
}
