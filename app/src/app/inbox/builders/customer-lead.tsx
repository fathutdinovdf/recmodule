/* Инбокс руководителя Заказчика — перенос buildCustomerLead из макет/inbox.js.
 *
 * Наблюдательная роль. Право решения у него есть (canDecide, решение 89), но
 * экран собран не как очередь решений, а как надзор над своими объектами:
 * очередь разбирают инженеры ЦДНГ, руководителю нужны места, где процесс
 * встал. Отсюда два блока: «Просроченные ответы» — единственное, где ход за
 * стороной Заказчика лично, — и «Сводка по объектам».
 *
 * Свод по объектам, а не по людям: ответственный Заказчика в модуле
 * появляется только после открытия карточки, а до открытия рекомендация уже
 * висит на объекте и уже тратит норматив. Значит адресовать её можно только
 * зоной ответственности.
 *
 * Пояснений «why» у блоков нет намеренно (перенесено из макета): заголовки
 * говорят сами за себя, а пояснение сводки рассказывало Заказчику про
 * внутреннюю кухню устройства дерева ВМАП.
 *
 * Билдер асинхронный и читает базу сам: эксперту хватает общего среза
 * строкиИнбокса(), а руководителю нужны sent/review со всех объектов и
 * агрегат по месторождениям — тащить это в общий срез значило бы грузить
 * каждый инбокс данными всех остальных.
 */

import type { ReactNode } from 'react';
import { дата } from '@/lib/format';
import type { InboxRow } from '@/db/inbox';
import {
  данныеРуководителяЗаказчика, type СтрокаПросрочки, type СводкаОбъекта,
} from '@/db/inbox-customer-lead';

/* Зеркало типов Блок/Плитка/Инбокс из page.tsx: страница их не экспортирует
   (лишние экспорты из page-файла спорят с проверкой типов Next), а совместимость
   структурная. Сведение в общий модуль — за основной сессией при слиянии
   билдеров ролей. */
interface Блок {
  id: string;
  tone: 'hot' | 'warn' | 'calm';
  act?: boolean;
  title: string;
  why?: string;
  rows: InboxRow[];
  count?: number;
  html?: ReactNode;
  showExecutor?: boolean;
  empty?: string;
  href?: (r: InboxRow) => string;
  when: (r: InboxRow) => string;
  extra?: (r: InboxRow) => string;
  deep?: string;
  deepLabel?: string;
}

interface Плитка { n: number; l: string; href: string }

interface Инбокс { плитки: Плитка[]; блоки: Блок[] }

/* Сводная таблица — табличный паттерн реестра (.tbl из registry.css): тот же
   кегль, те же границы, второй визуальный язык здесь не нужен. Итоговая
   строка — часть tbody, её отделяет верхняя граница (см. inbox-customer-lead.css). */
function СводкаПоОбъектам({ сводка }: { сводка: СводкаОбъекта[] }) {
  const итог = (f: (s: СводкаОбъекта) => number) => сводка.reduce((n, s) => n + f(s), 0);
  const колонки: [string, (s: СводкаОбъекта) => number][] = [
    ['Ждут решения', (s) => s.ждутРешения],
    ['Просрочено', (s) => s.просрочено],
    ['из них приоритет I', (s) => s.просроченоI],
    ['Согласовано, работ нет', (s) => s.согласовано],
    ['Окна открыты', (s) => s.оконОткрыто],
  ];
  return (
    <table className="tbl sum">
      <thead>
        <tr>
          <th>Объект</th>
          {колонки.map(([з]) => <th key={з} className="sum__n">{з}</th>)}
        </tr>
      </thead>
      <tbody>
        {сводка.map((s) => (
          <tr key={s.объект}>
            <td>{s.объект}</td>
            {колонки.map(([з, f]) => <td key={з} className="sum__n">{f(s)}</td>)}
          </tr>
        ))}
        <tr>
          <td><b>Итого</b></td>
          {колонки.map(([з, f]) => <td key={з} className="sum__n"><b>{итог(f)}</b></td>)}
        </tr>
      </tbody>
    </table>
  );
}

export async function инбоксРуководителяЗаказчика(): Promise<Инбокс> {
  const { просроченные, сводка } = await данныеРуководителяЗаказчика();
  const итог = (f: (s: СводкаОбъекта) => number) => сводка.reduce((n, s) => n + f(s), 0);
  const просроченоI = просроченные.filter((r) => r.priority === 'I').length;

  const блоки: Блок[] = [
    {
      /* «Самые давние просрочки» звучало разговорно, а этот блок руководитель
         читает первым. Название — из терминологии самого модуля: колонка
         «Контроль ответа», значение «просрочено». Порядок «от самой давней»
         остаётся, но живёт в сортировке, а не в заголовке. */
      id: 'b-overdue', tone: 'hot', act: true, rows: просроченные,
      title: 'Просроченные ответы',
      /* Реестр умеет фильтр по колонке «Контроль ответа» — ссылка ведёт на тот
         же бакет overdue, что посчитан здесь, числа обязаны сойтись. */
      deep: '/?control=overdue',
      when: (r) => `передано ${дата(r.sentAt, true)}`,
      showExecutor: true,
      extra: (r) => `срок был ${дата(r.dueAt, true)} · ${r.status === 'review'
        ? `карточку открыли ${дата((r as СтрокаПросрочки).openedAt, true)}, решения нет`
        : 'карточка ещё не открыта'}`,
      empty: 'Просроченных ответов нет.',
    },
    {
      id: 'b-fields', tone: 'calm', rows: [], count: итог((s) => s.всего),
      title: 'Сводка по объектам',
      html: <СводкаПоОбъектам сводка={сводка} />,
      /* Строк у сводки нет — when обязателен по форме блока, но не зовётся. */
      when: () => '',
    },
  ];

  const плитки: Плитка[] = [
    { n: просроченные.length, l: 'Просрочен ответ', href: '/?control=overdue' },
    { n: просроченоI, l: 'Из них приоритет I', href: '#b-overdue' },
    { n: итог((s) => s.срокИдёт), l: 'Срок ещё идёт', href: '#b-fields' },
    { n: итог((s) => s.согласовано), l: 'Согласовано, работ нет', href: '#b-fields' },
    { n: итог((s) => s.оконОткрыто), l: 'Окна эффекта открыты', href: '#b-fields' },
  ];

  return { плитки, блоки };
}
