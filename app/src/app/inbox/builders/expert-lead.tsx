/* Инбокс руководителя экспертов Исполнителя (перенос buildExpertLead из
 * макет/inbox.js).
 *
 * У руководителя нет «своих» задач — его экран отвечает на вопрос «где по
 * команде работа встала». Отсюда состав и порядок блоков:
 *   1. Просроченные ответы Заказчика — наблюдение за SLA всей команды. Ход за
 *      Заказчиком, действия с нашей стороны нет, поэтому блок наблюдательный
 *      (calm) и в значок навигации не входит. В макете это была плитка со
 *      ссылкой в реестр; блоком она развёрнута затем, что реестр не покажет
 *      «карточку открыли, решения нет» — а именно это руководитель несёт на
 *      оперативку.
 *   2. Сводка по команде — таблица эксперт × статусы, карта всей работы.
 *   3. Возражения Заказчика по дате реализации (hot) и «согласовано дольше
 *      порога, реализации нет» (warn) — единственные места, где ход за
 *      Исполнителем: они и составляют значок «Мои задачи» руководителя.
 *
 * Билдер асинхронный и берёт данные сам (строкиИнбоксаРуководителя): выборка
 * эксперта — пять статусов, руководителю нужен весь реестр в границе видимости,
 * включая sent/review для колонки «У Заказчика». Порог «застрявших» — настройка
 * справочника «Параметры модуля», а не константа (решение 81).
 */

import type { ReactNode } from 'react';
import type { InboxRow } from '@/db/inbox';
import { параметрМодуля } from '@/db/inbox';
import {
  строкиИнбоксаРуководителя, type СтрокаИнбоксаРуководителя,
} from '@/db/inbox-expert-lead';
import { дата, сутки } from '@/lib/format';

/* Типы повторяют Блок/Плитка/Инбокс из inbox/page.tsx: страница их не
   экспортирует (общий файл параллельных веток), а TS сверит структурно при
   регистрации билдера в БИЛДЕРЫ — разъехаться молча они не смогут. */
interface Блок {
  id: string;
  tone: 'hot' | 'warn' | 'calm';
  act?: boolean;
  title: string;
  why?: string;
  rows: InboxRow[];
  empty?: string;
  href?: (r: InboxRow) => string;
  when: (r: InboxRow) => string;
  extra?: (r: InboxRow) => string;
  deep?: string;
  deepLabel?: string;
  showExecutor?: boolean;
  content?: ReactNode;
}

interface Плитка { n: number; l: string; href: string }

interface Инбокс { плитки: Плитка[]; блоки: Блок[] }

const МС_СУТОК = 86_400_000;
const суткиНазад = (d: Date, now: Date) => Math.floor((now.getTime() - d.getTime()) / МС_СУТОК);

/* «Меньше суток» вместо «0 суток» — та же причина, что в page.tsx: ноль
   читается как «ничего не ждём», хотя ждём — просто меньше суток. */
const давность = (n: number) => (n <= 0 ? 'меньше суток' : сутки(n));

const t = (d: Date | null) => (d ? d.getTime() : Number.MAX_SAFE_INTEGER);

/* ------------------------------ сводка по команде ------------------------------ */

/* Колонки идут по жизненному циклу рекомендации слева направо: черновик →
   передача → уточнение → у Заказчика → согласовано → окно. «Из них просрочено»
   стоит сразу за «У Заказчика», потому что считает подмножество именно этой
   колонки. */
const ШАПКА = ['Эксперт', 'Черновики', 'Ждут передачи', 'На уточнении', 'У Заказчика',
  'из них просрочено', 'Согласовано', 'Окна открыты', 'Оспорено'] as const;

function сводкаПоКоманде(все: InboxRow[]): ReactNode {
  /* Состав команды берётся из самих рекомендаций, а не из справочника
     пользователей: эксперт без единой рекомендации в сводке «где работа
     встала» не сообщает ничего. Безымянный исполнитель (черновик без
     назначения) собирается в строку «—», а не теряется. */
  const имена = [...new Set(все.map((r) => r.executorName ?? '—'))];
  const строки = имена.map((имя) => {
    const с = все.filter((r) => (r.executorName ?? '—') === имя);
    const n = (f: (r: InboxRow) => boolean) => с.filter(f).length;
    return {
      имя,
      числа: [
        n((r) => r.status === 'draft'),
        n((r) => r.status === 'registered'),
        n((r) => r.status === 'clarify'),
        n((r) => r.status === 'sent' || r.status === 'review'),
        n((r) => r.controlKind === 'overdue'),
        n((r) => r.status === 'approved'),
        n((r) => r.status === 'windowOpen'),
        n((r) => r.disputeOpenedAt !== null),
      ],
    };
  });
  /* Сверху тот, у кого больше просрочек Заказчика: сводка отвечает «где
     встало», а не сортирует людей по алфавиту. */
  строки.sort((a, b) => b.числа[4] - a.числа[4]);
  const итого = строки.reduce(
    (s, r) => s.map((x, i) => x + r.числа[i]),
    ШАПКА.slice(1).map(() => 0),
  );

  return (
    <table className="tbl sum">
      <thead>
        <tr>{ШАПКА.map((з, i) => <th key={з} className={i ? 'sum__n' : undefined}>{з}</th>)}</tr>
      </thead>
      <tbody>
        {строки.map((r) => (
          <tr key={r.имя}>
            <td>{r.имя}</td>
            {r.числа.map((n, i) => <td key={ШАПКА[i + 1]} className="sum__n">{n}</td>)}
          </tr>
        ))}
        <tr>
          <td><b>Итого</b></td>
          {итого.map((n, i) => <td key={ШАПКА[i + 1]} className="sum__n"><b>{n}</b></td>)}
        </tr>
      </tbody>
    </table>
  );
}

/* ------------------------------ билдер ------------------------------ */

export async function инбоксРуководителяЭкспертов(
  _все: InboxRow[], _горизонт: number, now: Date,
): Promise<Инбокс> {
  const [все, порог] = await Promise.all([
    строкиИнбоксаРуководителя(),
    параметрМодуля('stuckDays'),
  ]);

  /* Просрочка «сначала горит»: самый давний срок сверху — у overdue величина
     просрочки и есть давность due_at. */
  const просрочено = все.filter((r) => r.controlKind === 'overdue')
    .sort((a, b) => t(a.dueAt) - t(b.dueAt));
  const уточнения = все.filter((r) => r.status === 'clarify');
  const ждутПередачи = все.filter((r) => r.status === 'registered');
  const согласовано = все.filter((r) => r.status === 'approved');
  const окна = все.filter((r) => r.status === 'windowOpen');
  const споры = все.filter((r) => r.disputeOpenedAt !== null)
    .sort((a, b) => t(a.disputeOpenedAt) - t(b.disputeOpenedAt));

  /* «Согласовано, а режим не меняется» — единственное место, где у Исполнителя
     копится невидимая проблема: норматива на реализацию в договоре нет, срок
     ничем не подсвечивается, и рекомендация может стоять месяцами. */
  const застряли = согласовано
    .filter((r) => r.repliedAt && суткиНазад(r.repliedAt, now) > порог)
    .sort((a, b) => t(a.repliedAt) - t(b.repliedAt));

  /* Разница дат в возражении — по календарю между нашей датой и предложенной:
     от неё зависит, на сколько сдвинется окно и деньги по договору. */
  const разницаДат = (r: InboxRow) => (r.factDate && r.disputeProposedDate
    ? давность(Math.abs(Math.round(
      (r.disputeProposedDate.getTime() - r.factDate.getTime()) / МС_СУТОК,
    )))
    : null);

  const блоки: Блок[] = [
    {
      id: 'b-overdue', tone: 'calm', rows: просрочено, showExecutor: true,
      title: 'Просрочен ответ Заказчика',
      why: 'Норматив ответа истёк, время считается рабочими часами. Ход за Заказчиком — '
        + 'со стороны Исполнителя действия нет, но просрочки по всей команде поднимает '
        + 'на оперативке именно руководитель.',
      deep: '/?control=overdue',
      deepLabel: 'просроченные в реестре',
      when: (r) => `передано ${дата(r.sentAt, true)}`,
      extra: (r) => `срок был ${дата(r.dueAt, true)} · ${r.status === 'review'
        ? `карточку открыли ${дата((r as СтрокаИнбоксаРуководителя).openedAt, true)}, решения нет`
        : 'карточка ещё не открыта'}`,
      empty: 'Просроченных ответов нет.',
    },
    {
      id: 'b-team', tone: 'calm', rows: все,
      title: 'Сводка по команде',
      why: 'Руководителю нужны не свои задачи, а места, где работа встала. Колонка '
        + '«просрочено» считает ответы Заказчика: это не вина эксперта, но именно '
        + 'он поднимает вопрос на оперативке.',
      when: () => '',
      content: сводкаПоКоманде(все),
    },
    {
      id: 'b-dispute', tone: 'hot', act: true, rows: споры, showExecutor: true,
      title: 'Возражения Заказчика по дате реализации',
      why: 'От даты реализации считаются 90 суток окна и деньги по договору. Пока '
        + 'возражение не снято, расчёт эффекта предварительный, а разбирательство '
        + 'в случае отказа уходит из модуля в раздел 10 договора.',
      href: (r) => `/rec/${r.id}/impl`,
      when: (r) => `возражение ${дата(r.disputeOpenedAt, true)}`,
      extra: (r) => `наша дата ${дата(r.factDate)} · предлагают ${дата(r.disputeProposedDate)}`
        + (разницаДат(r) ? ` · разница ${разницаДат(r)}` : ''),
      empty: 'Возражений нет.',
    },
    {
      id: 'b-stuck', tone: 'warn', act: true, rows: застряли, showExecutor: true,
      title: `Согласовано больше ${сутки(порог)} назад, реализации нет`,
      why: 'Рекомендация принята, но режим на скважине не менялся — окно эффекта не '
        + 'открылось, в зачёт по договору она не идёт. Норматива на реализацию '
        + 'договор не устанавливает, поэтому это ручной контроль руководителя.',
      href: (r) => `/rec/${r.id}/impl`,
      when: (r) => `согласовано ${дата(r.repliedAt)}`,
      extra: (r) => (r.repliedAt ? `ждём смены режима ${давность(суткиНазад(r.repliedAt, now))}` : ''),
    },
  ];

  const плитки: Плитка[] = [
    { n: просрочено.length, l: 'Просрочен ответ Заказчика', href: '#b-overdue' },
    { n: уточнения.length, l: 'На уточнении у экспертов', href: '#b-team' },
    { n: ждутПередачи.length, l: 'Ждут передачи', href: '#b-team' },
    { n: согласовано.length, l: 'Согласовано, реализации нет', href: '#b-stuck' },
    { n: застряли.length, l: `Из них дольше ${сутки(порог)}`, href: '#b-stuck' },
    { n: окна.length, l: 'Окна эффекта открыты', href: '#b-team' },
  ];

  return { плитки, блоки };
}
