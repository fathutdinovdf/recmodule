/* Экран «Экономическая модель».
 *
 * Отвечает не на вопрос «какие у нас ставки», а на вопрос «посчитаются ли по
 * ним деньги». Ставка сама по себе — данные; ценность в том, полна ли модель,
 * и где именно она не полна. Поэтому первым делом на экране стоит готовность
 * с разбором пробелов, а таблица ставок идёт под ней.
 *
 * Ставки НДПИ не вынесены в отдельную вкладку, как было в макете. Пластовая
 * ставка — это подробность месторождения, а не параллельный список: человек
 * приходит с вопросом «что у меня по Южно-Ягунскому», а не «пойду посмотрю
 * вкладку НДПИ». Поэтому одна таблица объектов, а пласты раскрываются внутри
 * строки.
 *
 * Историю страница читает целиком и отдаёт клиенту: редакций единицы в год,
 * отдельный маршрут ради них — лишний круг по сети в момент, когда человек
 * уже спросил «а что менялось».
 */

import { currentUser } from '@/lib/session';
import { правитЭкономику } from '@/lib/access';
import { econModel, econHistory } from '@/db/economy';
import { Редактор } from './editor';
import './economy.css';

export const dynamic = 'force-dynamic';

export default async function EconomyPage() {
  const [я, модель, история] = await Promise.all([
    currentUser(), econModel(), econHistory(),
  ]);

  /* Даты через ISO: Date не переживает границу серверного и клиентского
     компонента как Date — приезжает строкой, но с типом Date, и первое же
     `.getTime()` падает уже в браузере. */
  const версии = история.map((v) => ({
    ...v,
    at: v.at.toISOString(),
    effectiveFrom: v.effectiveFrom.toISOString(),
  }));

  return <Редактор модель={модель} версии={версии} можноПравить={правитЭкономику(я)} />;
}
