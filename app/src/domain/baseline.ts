/* Базовые значения по замерам.
 *
 * Договор, Приложение № 2, раздел «Формирование базовых значений», описывает
 * четыре способа. Здесь реализован второй:
 *
 *   «...базовые значения дебита жидкости и дебита нефти определяются как
 *    средневзвешенные значения за три календарных дня, непосредственно
 *    предшествующих регистрации рекомендации. (по согласованию с Заказчиком)»
 *
 * И правило отбора суток оттуда же:
 *
 *   «При расчете используются только те календарные дни, в которых в
 *    информационной системе ОИС+ присутствуют кондиционные значения дебита
 *    жидкости, соответствующие фактическому режиму эксплуатации скважины.»
 *
 * Три вещи, которые из этих формулировок следуют не сразу.
 *
 * 1. Период отсчитывается от РЕГИСТРАЦИИ рекомендации, а не от даты
 *    реализации. База — это то, что было до того, как мероприятие вообще
 *    предложили; между регистрацией и работами проходят дни, и в них скважина
 *    уже могла измениться.
 *
 * 2. «Средневзвешенные» — по времени. Суточное значение и так интеграл по
 *    времени (см. measurements.ts), поэтому среднее по отобранным суткам и
 *    есть средневзвешенное за период. Сутки, не прошедшие отбор, из среднего
 *    выпадают целиком, а не размазываются протяжкой.
 *
 * 3. Кондиционность мы определяем беднее, чем договор: «соответствие
 *    фактическому режиму эксплуатации» требует состояния скважины (параметр 16
 *    «Состояние скважины по ТМ», на стенде пуст, либо 78 «Состояние (в работе,
 *    в накоплении, остановлена)»). Пока их нет в расчёте, кондиционными
 *    считаются сутки с собственным замером ДЕБИТА и ненулевым дебитом:
 *    протянутое значение — не замер этих суток, а ноль — это остановка, и
 *    усреднять её с рабочими сутками нельзя.
 *
 *    Требование «собственного замера» относится именно к дебиту жидкости, как
 *    и в договоре. Обводнённость может быть протянутой: её определяют
 *    лабораторно и заметно реже дебита — на фонде из трёх суток свой замер
 *    обводнённости есть у каждой десятой скважины. Требовать его значило бы
 *    оставить без базы девять рекомендаций из десяти, причём не по существу, а
 *    из-за регламента отбора проб.
 */

/* Расширение .ts в импорте — не описка. Этот файл вместе с measurements.ts
   подключает служебный скрипт scripts/rebase-demo.mjs напрямую голым node:
   тот снимает типы сам, но специфаер требует точного расширения. Сборщику
   Next это безразлично, а альтернатива — копия правил отбора суток в скрипте,
   которая разъедется с этой при первой же правке. */
import { liquidMass, oilFromLiquid, type DailyPoint } from './measurements.ts';

/** Сколько суток берётся по умолчанию. Три — по договору. */
export const BASELINE_DAYS = 3;

export interface BaselineDay {
  date: Date;
  qzh: number | null;
  watercut: number | null;
  qn: number | null;
  /** Прошли ли эти сутки отбор и почему нет. */
  used: boolean;
  reason: string | null;
}

export interface MeasuredBaseline {
  baseQzh: number | null;
  baseQn: number | null;
  /** Масса жидкости, т/сут — то, на что умножается ставка ЭЭ на жидкость. */
  baseQzhT: number | null;
  periodFrom: Date;
  periodTo: Date;
  days: BaselineDay[];
  usedDays: number;
}

/**
 * База по суточным рядам жидкости и обводнённости за выбранный период.
 *
 * Ряды приходят уже посчитанными (dailySeries), поэтому функция чистая и
 * ничего не знает ни про ВМАП, ни про базу модуля.
 */
export function baselineFromSeries(params: {
  qzh: DailyPoint[];
  watercut: DailyPoint[];
  oilDensity: number | null;
  waterDensity: number | null;
}): MeasuredBaseline {
  const { qzh, watercut, oilDensity, waterDensity } = params;
  const обводнённостьПоДню = new Map(watercut.map((d) => [d.date.getTime(), d]));

  const days: BaselineDay[] = qzh.map((d) => {
    const в = обводнённостьПоДню.get(d.date.getTime()) ?? null;
    const обводнённость = в?.value ?? null;
    const qn = oilFromLiquid(d.value, обводнённость, oilDensity);

    let reason: string | null = null;
    if (d.value === null) reason = 'нет данных о дебите';
    else if (d.points === 0) reason = 'нет собственного замера, значение протянуто';
    else if (d.value <= 0) reason = 'нулевой дебит — скважина не работала';
    else if (обводнённость === null) reason = 'нет обводнённости, нефть не посчитать';

    return { date: d.date, qzh: d.value, watercut: обводнённость, qn, used: reason === null, reason };
  });

  const отобранные = days.filter((d) => d.used);
  const среднее = (значения: number[]) => (значения.length
    ? значения.reduce((s, v) => s + v, 0) / значения.length : null);

  const baseQzh = среднее(отобранные.map((d) => d.qzh as number));
  const baseQn = среднее(отобранные.map((d) => d.qn as number));

  return {
    baseQzh,
    baseQn,
    baseQzhT: liquidMass(baseQzh, baseQn, oilDensity, waterDensity),
    periodFrom: qzh[0]?.date ?? new Date(NaN),
    periodTo: qzh[qzh.length - 1]?.date ?? new Date(NaN),
    days,
    usedDays: отобранные.length,
  };
}
