import { describe, it, expect } from 'vitest';
import { isTypoOf } from './textSimilarity';

describe('isTypoOf', () => {
  it('точное совпадение', () => {
    expect(isTypoOf('отклонение', 'отклонение')) .toBe(true);
  });

  it('одна опечатка в слове укладывается в бюджет', () => {
    expect(isTypoOf('отклоение', 'отклонение')).toBe(true);
  });

  it('совпадение с отдельным словом многословной фразы', () => {
    expect(isTypoOf('снижение', 'снижение дебита жидкости')).toBe(true);
    expect(isTypoOf('дебта', 'снижение дебита жидкости')).toBe(true);
  });

  it('совсем другое слово — не опечатка', () => {
    expect(isTypoOf('отклонение', 'снижение')).toBe(false);
  });

  it('короткие слова — маленький бюджет опечаток не путает разные термины', () => {
    // «КЭ» и «ЭЦ» — разные аббревиатуры, не должны считаться опечаткой друг друга.
    expect(isTypoOf('кэ', 'эц')).toBe(false);
  });

  it('регистр не влияет на сравнение', () => {
    expect(isTypoOf('Снижение', 'снижение')).toBe(true);
  });
});
