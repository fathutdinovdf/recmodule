/* Расчёт экономического эффекта мероприятия.
 *
 * Формула взята из рабочего шаблона Заказчика — «Шаблон оценки эффективности
 * АЛЬМА» от 05.08.2026, лист «Модель оценка добычи», строка 6 и ниже:
 *
 *     L: выручка       = J × цена нефти           J — добыча нефти, т
 *     M: НДПИ          = ставка(месторождение+пласт) × J
 *     N: ЭЭ жидкость   = ставка(месторождение) × K  K — добыча ЖИДКОСТИ, Т
 *     O: ЭЭ нефть      = ставка(месторождение) × J
 *     P: деэмульгаторы = ставка(месторождение) × J
 *     R: эффект        = L − M − N − O − P − Q
 *
 * Здесь всё то же самое, но применяется к ПРИРОСТУ, а не к добыче: мероприятие
 * приносит разницу между фактом и базой, и считать надо её.
 *
 * Четыре вещи, которые легко сделать неправильно.
 *
 * НДПИ берётся с нефти, а не с жидкости. Налог платится с товарной нефти, вода
 * в базу не входит; в шаблоне это столбец M, умножающий ставку на добычу нефти
 * (столбец J), — не на жидкость.
 *
 * Жидкость в формулу входит В ТОННАХ, а не в кубометрах. Столбец K шаблона так
 * и называется — «Добыча жидкости, т», и ставка ЭЭ на жидкость заведена в
 * руб/т. ВМАП же меряет дебит жидкости в м³/сут, поэтому прирост переводится в
 * массу (liquidMass в domain/measurements) до того, как попасть сюда. Разница
 * не косметическая: плотность смеси нефти с водой на фонде 0,86–1,20 т/м³.
 *
 * Столбца Q «Дополнительные затраты» у нас нет: в шаблоне это ручной ввод,
 * заполняемый по конкретному мероприятию, и подставлять туда ноль молча — то
 * же самое, что его не иметь. Появится — станет ещё одной статьёй.
 *
 * Прежний набор статей — подъём, ППД, транспорт, подготовка, обслуживание
 * ГНО — остался в более ранней модели Заказчика и здесь не воспроизводится.
 * В рабочем шаблоне их нет, а держать в модуле формулу, которой Заказчик не
 * пользуется, значит заранее разойтись с ним в цифрах при сверке.
 *
 * Коэффициента эксплуатации в формуле нет намеренно. Он нужен, когда суточный
 * дебит растягивают на календарный период и надо снять простои. Мы считаем по
 * фактическим суткам: день простоя приходит нулевым приростом сам, и поправка
 * на простой задвоилась бы.
 */

import { liquidMass } from './measurements';

export interface WellEconomy {
  fieldName: string;
  /** Как месторождение названо в модели Заказчика. */
  sourceName: string;
  /** Пласт по объекту разработки, из ВМАП. Справочный. */
  plast: string | null;
  /** Пласт в налоговом смысле — по нему выбрана ставка. */
  taxPlast: string;
  /** Ставка НДПИ+НДД, руб/т нефти. */
  ndpi: number;
  /** руб/т ЖИДКОСТИ — массы, не объёма (столбец K шаблона). */
  eeLiquid: number;
  /** руб/т нефти. */
  eeOil: number;
  /** Деэмульгаторы, руб/т нефти. */
  chem: number;
  /** Цена нефти (МСУ), руб/т. */
  oilPrice: number;
}

export interface EffectBreakdown {
  revenue: number;
  ndpi: number;
  eeLiquid: number;
  eeOil: number;
  chem: number;
  total: number;
}

/** Чего не хватает, чтобы посчитать. Пустой список — можно считать. */
export function missingRates(econ: Partial<WellEconomy> | null): string[] {
  if (!econ) return ['ставки по скважине не заведены'];
  const нет: string[] = [];
  const проверить: [keyof WellEconomy, string][] = [
    ['oilPrice', 'цена нефти'],
    ['ndpi', 'ставка НДПИ'],
    ['eeLiquid', 'электроэнергия на жидкость'],
    ['eeOil', 'электроэнергия на нефть'],
    ['chem', 'деэмульгаторы'],
  ];
  for (const [ключ, имя] of проверить) {
    const v = econ[ключ];
    /* Ноль — законное значение ставки («затрат нет»), а вот null или
       undefined означают, что ставку не завели, и расчёт с ней врал бы молча. */
    if (v === null || v === undefined || !Number.isFinite(v as number)) нет.push(имя);
  }
  return нет;
}

/**
 * Эффект за сутки, руб. На вход — приросты к базе: жидкость т/сут, нефть т/сут.
 * Обе величины в тоннах: ставки в модели Заказчика заведены на массу.
 *
 * Возвращает разложение по статьям, а не одно число: спор с Заказчиком идёт
 * по статьям, и в карточке нужно показать, из чего сложилась сумма.
 *
 * Отрицательный прирост — законный случай (мероприятие не дало эффекта или
 * дебит упал), и знак проходит через формулу насквозь.
 */
export function dailyEffect(
  econ: WellEconomy,
  deltaQzhT: number,
  deltaQn: number,
): EffectBreakdown {
  const revenue = deltaQn * econ.oilPrice;
  const ndpi = deltaQn * econ.ndpi;
  const eeLiquid = deltaQzhT * econ.eeLiquid;
  const eeOil = deltaQn * econ.eeOil;
  const chem = deltaQn * econ.chem;
  return {
    revenue,
    ndpi,
    eeLiquid,
    eeOil,
    chem,
    total: revenue - ndpi - eeLiquid - eeOil - chem,
  };
}

/**
 * Прогнозный эффект за всё окно, руб: ожидаемые приросты, прогнанные через ту
 * же формулу и умноженные на длину окна.
 *
 * Отдельного поля «прогнозный эффект в рублях» у рекомендации нет намеренно.
 * Эксперт вводит при регистрации приросты — Δ Qж и Δ Qн, — и деньги считаются
 * из них. Хранить рубли отдельно значило бы завести второй источник правды:
 * прогноз разошёлся бы с собственными приростами эксперта, а шкала прогресса
 * окна сравнивала бы факт с числом, посчитанным по другим правилам, чем факт.
 *
 * Ожидаемый прирост жидкости эксперт вводит в м³/сут, поэтому здесь он
 * переводится в тонны той же функцией, что и факт: прирост нефти известен,
 * остальной объём — вода.
 *
 * Возвращает null, когда считать не из чего: без ставок, без ожидаемых
 * приростов или без плотностей прогноза не существует, и рисовать вместо него
 * ноль нельзя.
 */
export function forecastTotal(
  econ: WellEconomy | null,
  expectQzh: number | null,
  expectQn: number | null,
  oilDensity: number | null,
  waterDensity: number | null,
  days: number,
): number | null {
  if (!econ || missingRates(econ).length) return null;
  if (expectQzh === null || expectQn === null) return null;
  const массаЖидкости = liquidMass(expectQzh, expectQn, oilDensity, waterDensity);
  if (массаЖидкости === null) return null;
  return dailyEffect(econ, массаЖидкости, expectQn).total * days;
}

/** Сумма разложений — для накопленного итога по окну. */
export function sumBreakdowns(items: EffectBreakdown[]): EffectBreakdown {
  return items.reduce<EffectBreakdown>((acc, b) => ({
    revenue: acc.revenue + b.revenue,
    ndpi: acc.ndpi + b.ndpi,
    eeLiquid: acc.eeLiquid + b.eeLiquid,
    eeOil: acc.eeOil + b.eeOil,
    chem: acc.chem + b.chem,
    total: acc.total + b.total,
  }), { revenue: 0, ndpi: 0, eeLiquid: 0, eeOil: 0, chem: 0, total: 0 });
}
