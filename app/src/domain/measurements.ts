/* Замеры и суточная агрегация — ядро расчёта фактического эффекта.
 *
 * Модуль намеренно не знает ни про Next, ни про базу: на вход массив замеров,
 * на выход числа. Так он одинаково работает на сервере при пересчёте окна, в
 * тесте и в браузере при показе разложения — и переживёт смену обвязки.
 *
 * Фактический дебит приходит из ВМАП замерами (параметр 1, «Дебит жидкости
 * Замерной»). Замер — не суточное значение, а мгновенное: столько скважина
 * давала в момент замера. Между замерами значение держится, потому что ничего
 * другого о скважине не известно.
 *
 * Отсюда два правила, оба взяты из того, как устроены сами данные дев-стенда.
 *
 * 1. Внутри суток замеров бывает несколько: 1891 суток с одним замером, 991 с
 *    двумя, 196 с четырьмя. Среднее арифметическое здесь врёт — замер в 08:00 и
 *    замер в 22:00 описывают куски суток разной длины. Правильная величина —
 *    интеграл по времени: площадь под ступенькой, делённая на длину суток.
 *
 * 2. Между замерами бывают разрывы: медиана 11 часов, девяностый перцентиль 24
 *    часа, максимум 50 суток. Поэтому последнее известное значение
 *    протягивается вперёд, пока не появится новое.
 *
 * Чего эти правила намеренно НЕ делают: не отличают остановленную скважину от
 * скважины без замеров. Если скважина встала, а замеров нет, протяжка покажет
 * прежний дебит и завысит факт. Состояние скважины лежит отдельным параметром
 * (16, «Состояние по ТМ»), и когда оно появится в выгрузке, ноль состояния
 * должен обрывать протяжку. До тех пор это известное ограничение, а не
 * недосмотр.
 */

export interface Measurement {
  /** Момент замера. Из ВМАП берётся как COALESCE(FactDate, LEAST(CreateDate,
   *  UpdateDate)): семантика пары Create/Update в разных пачках разная, но
   *  момент замера всегда раньше момента записи в базу. */
  at: Date;
  value: number;
}

export interface DailyValue {
  /** Среднее по времени за сутки. */
  value: number;
  /** Доля суток, опирающаяся на замеры ЭТИХ суток, а не на протянутое
   *  значение прошлых. По ней видно, чему в расчёте верить. */
  coverage: number;
  /** Сколько замеров пришлось на эти сутки. */
  points: number;
}

export interface DailyPoint {
  date: Date;
  /** null — про эти сутки ничего не известно: ни замеров, ни значения до них. */
  value: number | null;
  coverage: number;
  points: number;
}

const СУТКИ_МС = 86_400_000;

/** Начало суток, к которым принадлежит момент. */
export function dayStart(t: Date): Date {
  const d = new Date(t);
  d.setHours(0, 0, 0, 0);
  return d;
}

/**
 * Среднесуточное значение по ряду замеров — интеграл ступенчатой функции.
 *
 * Возвращает null, если на начало суток значение неизвестно и внутри суток
 * замеров не было: ноль здесь означал бы остановленную скважину, а мы про неё
 * ничего не знаем. Пустое значение честнее выдуманного нуля.
 */
export function dailyAverage(measurements: Measurement[], day: Date): DailyValue | null {
  const начало = dayStart(day).getTime();
  const конец = начало + СУТКИ_МС;

  const точки = measurements
    .map((з) => ({ t: з.at.getTime(), v: з.value }))
    .filter((з) => Number.isFinite(з.v) && Number.isFinite(з.t))
    .sort((a, b) => a.t - b.t);

  /* Значение на начало суток — последний замер, сделанный до них. Именно оно
     держится до первого замера внутри суток, и без него сутки начинаются
     с неизвестности. */
  let текущее: number | null = null;
  for (const з of точки) {
    if (з.t <= начало) текущее = з.v;
    else break;
  }

  const внутри = точки.filter((з) => з.t > начало && з.t < конец);
  if (текущее === null && внутри.length === 0) return null;

  let площадь = 0;
  let курсор = начало;

  for (const з of внутри) {
    /* До первого замера суток, если предыдущего значения нет вовсе, тянем
       первый замер назад: другого предположения о начале суток не из чего
       построить. */
    площадь += (текущее ?? з.v) * (з.t - курсор);
    курсор = з.t;
    текущее = з.v;
  }
  площадь += (текущее as number) * (конец - курсор);

  /* Покрытие считается от первого замера этих суток до их конца: именно этот
     кусок опирается на сегодняшние измерения, а всё до него — на протяжку из
     прошлых суток. Сутки с замером в 03:28 покрыты на 86 %. */
  return {
    value: площадь / СУТКИ_МС,
    coverage: внутри.length ? (конец - внутри[0].t) / СУТКИ_МС : 0,
    points: внутри.length,
  };
}

/**
 * Ряд среднесуточных значений за период включительно.
 *
 * Замеры за пределами периода нужны обязательно: первым суткам опереться не на
 * что, если не передать последний замер ДО них.
 */
export function dailySeries(measurements: Measurement[], from: Date, to: Date): DailyPoint[] {
  const out: DailyPoint[] = [];
  const конец = dayStart(to).getTime();
  for (let t = dayStart(from).getTime(); t <= конец; t += СУТКИ_МС) {
    const день = new Date(t);
    const знач = dailyAverage(measurements, день);
    out.push({
      date: день,
      value: знач?.value ?? null,
      coverage: знач?.coverage ?? 0,
      points: знач?.points ?? 0,
    });
  }
  return out;
}

/**
 * Нефть из жидкости: Qн = Qж × (1 − обводнённость) × плотность.
 *
 * Обводнённость объёмная, в процентах; плотность нефти в стандартных условиях,
 * кг/м³. Формула — из «Пояснений» Формы 5, приложения к договору.
 */
export function oilFromLiquid(
  qzh: number | null,
  watercutPct: number | null,
  densityKgM3: number | null,
): number | null {
  if (qzh === null || watercutPct === null || densityKgM3 === null) return null;
  if (!Number.isFinite(qzh) || !Number.isFinite(watercutPct) || !Number.isFinite(densityKgM3)) return null;
  return qzh * (1 - watercutPct / 100) * (densityKgM3 / 1000);
}
