-- Жидкость в тоннах.
--
-- В «Шаблоне оценки эффективности АЛЬМА» столбец K называется «Добыча жидкости,
-- т», и ставка электроэнергии на жидкость (столбец N) умножается именно на
-- него. ВМАП же меряет дебит жидкости в м³/сут. Пока расчёт умножал ставку на
-- кубометры, статья «электроэнергия на жидкость» врала на плотность смеси —
-- а она на фонде 0,86–1,20 т/м³.
--
-- Масса хранится рядом с объёмом, а не вместо него: объём — это то, что
-- измерено, масса — то, что посчитано. В споре нужны оба.

ALTER TABLE rec.effect_daily
    ADD COLUMN IF NOT EXISTS fact_qzh_t  numeric(10,3),
    ADD COLUMN IF NOT EXISTS delta_qzh_t numeric(10,3);

COMMENT ON COLUMN rec.effect_daily.fact_qzh  IS 'Дебит жидкости за сутки, м³/сут — как меряет ВМАП';
COMMENT ON COLUMN rec.effect_daily.fact_qzh_t IS 'Он же в т/сут: нефть плюс вода по плотностям скважины';
COMMENT ON COLUMN rec.effect_daily.delta_qzh_t IS 'Прирост жидкости в т/сут — на него умножается ставка ЭЭ на жидкость';

-- Кэш посчитан по старой формуле (ставка × м³), и оставлять его нельзя:
-- закрытые окна отдаются из кэша и не пересчитываются.
TRUNCATE rec.effect_daily;
