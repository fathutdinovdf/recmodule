-- История правок справочников (решение 109).
--
-- Одна таблица на все справочники, а не журнал в каждом: правок мало, смотрят
-- их одним списком «что менялось» с отбором по справочнику, и заводить четыре
-- одинаковые таблицы значит четыре раза чинить одно и то же.
--
-- Версий и обязательной причины здесь нет — в отличие от экономики
-- (rec.econ_versions). Разница по существу: правка справочника одиночная и
-- обратимая, а требовать обоснование за переименование направления значит
-- приучить людей писать «правка» в поле причины. В экономике причина
-- обязательна, потому что по её числам подписывают акты.
CREATE TABLE rec.ref_changes (
    id          bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    at          timestamptz NOT NULL DEFAULT now(),
    actor_id    bigint NOT NULL REFERENCES rec.users(id),
    actor_name  text NOT NULL,
    -- Ключ справочника — имя таблицы без схемы. Текстом, а не enum: состав
    -- справочников уже менялся (упразднение «Рекомендуемых мероприятий»,
    -- решение 108), и история должна переживать такие правки без миграции.
    ref         text NOT NULL,
    -- Название значения на момент записи. Денормализовано сознательно: строка
    -- истории обязана читаться и после переименования, и по архивному значению.
    object_name text NOT NULL,
    action      text NOT NULL
                CHECK (action IN ('add', 'rename', 'update', 'archive', 'restore')),
    -- Какое поле правили — только для action = 'update' (у приоритета правится
    -- и название, и норматив; каждое поле — своя строка, иначе old/new не
    -- разложить). Машинное имя колонки, подпись даёт интерфейс.
    field       text,
    old_value   text,
    new_value   text
);

CREATE INDEX ON rec.ref_changes (ref, at DESC);
