-- Удаление рекомендации не должно ломаться о журнал правок.
--
-- Номер 016, а не 015: пятнадцатый занят веткой ролей и входа. Она в master
-- ещё не слита, но её миграция уже применена к общей базе разработки.
--
-- Что было. `rec.daily_fact_events.rec_id` ссылался на рекомендацию без
-- указания, что делать при её удалении, то есть с NO ACTION. Пересев демо
-- (`npm run db:seed`) начинается с `DELETE FROM rec.recommendations WHERE
-- is_demo` и с появлением журнала перестал проходить вовсе: демонстрационные
-- события журнала заводятся отдельно (миграции 013 и 014), сам seed про них
-- не знает и удалить их первыми не может.
--
-- Почему SET NULL, а не CASCADE. Событие журнала принадлежит СКВАЖИНЕ, а не
-- рекомендации — это записано и в комментарии к самому полю: одни и те же
-- сутки видны всем рекомендациям, чьи окна их накрывают, а rec_id лишь
-- помечает, из какой карточки правили. CASCADE стирал бы историю правок
-- суточных данных вместе с карточкой, то есть терял бы данные скважины из-за
-- удаления чужой записи. NULL здесь и так допустим (правка могла прийти вне
-- карточки), и означает ровно то, что произошло: карточки больше нет,
-- значение правили тогда-то и вот с такого на такое.
ALTER TABLE rec.daily_fact_events
    DROP CONSTRAINT daily_fact_events_rec_id_fkey,
    ADD CONSTRAINT daily_fact_events_rec_id_fkey
        FOREIGN KEY (rec_id) REFERENCES rec.recommendations(id) ON DELETE SET NULL;
