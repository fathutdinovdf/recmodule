-- Дата перехода на данные ВМАП.
--
-- Модуль первого этапа живёт на облачном сервере, где стенда Заказчика нет, и
-- суточный факт вводится руками. Когда он переедет на ландшафт Заказчика,
-- источником станет телеметрия — но НЕ задним числом: сутки, посчитанные по
-- внесённым вручную значениям, обязаны остаться такими, какими их посчитали.
-- Иначе в день переезда накопленный эффект по идущим окнам сдвинулся бы сам
-- собой, без единого действия человека, а это деньги по договору.
--
-- Отсюда граница: сутки ДО vmap_from берутся из rec.daily_facts, начиная с
-- vmap_from — из замеров ВМАП. Ряд склеивается в src/db/wells-data.ts.
--
-- Почему по дате, а не «есть ручное значение — берём его». Ручные сутки
-- хранятся только там, где их вносили; промежутки заполняются протяжкой на
-- лету. Смешивание по наличию записи дало бы чересполосицу источников внутри
-- одного окна, и объяснить происхождение цифры конкретного дня стало бы
-- нечем. Одна дата — одна формулировка в протоколе с Заказчиком.
--
-- Отдельная таблица, а не строка в rec.module_params: там value имеет тип
-- numeric, и дату туда не положить.

CREATE TABLE rec.source_switch (
  -- Строка ровно одна: это свойство ландшафта, а не справочник.
  id         smallint PRIMARY KEY DEFAULT 1 CHECK (id = 1),

  -- NULL — перехода не было: источник целиком определяется DATA_SOURCE.
  vmap_from  date,

  -- Чем переход оформлен: протокол, письмо, дата акта. Граница разделяет
  -- деньги по договору, и основание у неё должно быть записано.
  note       text,

  updated_at timestamptz NOT NULL DEFAULT now(),
  updated_by text
);

