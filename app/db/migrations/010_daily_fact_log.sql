-- Журнал правок суточного факта.
--
-- Зачем отдельная таблица, а не пара столбцов «кто менял последним» в
-- rec.daily_facts. На введённых руками числах стоит весь расчёт эффекта, то
-- есть деньги по договору. Первый вопрос при разборе спора — не «кто трогал
-- последним», а «как эта цифра дошла до нынешнего значения»: кто внёс, кто
-- поправил, когда и на сколько. Последняя правка на этот вопрос не отвечает,
-- а восстановить цепочку из одного снимка нельзя.
--
-- Поэтому здесь лежит КАЖДОЕ изменение, а rec.daily_facts остаётся текущим
-- состоянием — быстрым ответом на «сколько сейчас».

CREATE TABLE rec.daily_fact_events (
  id           bigserial PRIMARY KEY,
  well_id      bigint   NOT NULL,
  parameter_id smallint NOT NULL,
  date         date     NOT NULL,

  -- NULL в old_value — значения не было (первый ввод),
  -- NULL в new_value — значение стёрли. Оба NULL не бывают: событие без
  -- изменения не пишется.
  old_value    numeric,
  new_value    numeric,

  actor_id     bigint NOT NULL REFERENCES rec.users(id),
  -- Имя денормализовано, как в rec.recommendation_events и rec.comments:
  -- журнал должен читаться и после того, как пользователя переименуют или
  -- отключат. Ссылка на id при этом остаётся — по ней сверяют, тот ли это
  -- человек, а не однофамилец.
  actor_name   text NOT NULL,

  -- Из какой карточки правили. Сам факт принадлежит СКВАЖИНЕ, а не
  -- рекомендации: одни и те же сутки видны всем рекомендациям по этой
  -- скважине, чьи окна их накрывают. Но правку всегда делают, глядя на
  -- конкретную карточку, и в разборе спора важно, на какую именно смотрели.
  -- NULL допустим: правка могла прийти и вне карточки.
  rec_id       bigint REFERENCES rec.recommendations(id),

  at           timestamptz NOT NULL DEFAULT now()
);

-- Основной запрос журнала — история одних суток по скважине, её показывают
-- прямо в окне ввода дня.
CREATE INDEX daily_fact_events_point_idx
  ON rec.daily_fact_events (well_id, date, parameter_id, at DESC);

-- Второй запрос — «что вообще правили в этой карточке».
CREATE INDEX daily_fact_events_rec_idx
  ON rec.daily_fact_events (rec_id, at DESC);
