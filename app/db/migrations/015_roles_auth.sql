-- Роли и вход в модуль.
--
-- Номер 015, а не 009: девятый по четырнадцатый заняты веткой суточных данных
-- (ручной ввод, журнал правок, переключение источника). Она в master ещё не
-- слита, но её миграции уже применены к общей базе разработки, и совпадение
-- номеров означало бы два разных файла с одним именем при слиянии.
--
-- До сих пор «кто за экраном» подменялось куком с логином: приложение почти
-- всё только читало, и вопрос личности всерьёз не стоял. Теперь стоит.
--
-- Договорённость, от которой пляшет вся таблица: личность («кто») и права
-- («что можно») — разные вещи. В рабочем контуре личность приедет из ВМАП,
-- права всегда останутся здесь: у ВМАП нет и не будет понятия «сторона
-- договора». Простой логин с паролем — временная реализация первой половины,
-- ко второй он отношения не имеет.

-- ============================ роли ============================

-- Роль — перечисление, а не набор галочек. За ролью стоят разрешённые
-- действия и переходы статусов, то есть логика модуля: настраиваемая матрица
-- «роль × действие» позволила бы собрать невозможное состояние — например,
-- Заказчика, фиксирующего факт реализации, — и чинить это было бы некому.
-- Поэтому справочник системный: правится вместе с модулем, из интерфейса
-- только читается (решение 84).
CREATE TABLE rec.roles (
    key         text PRIMARY KEY,
    label       text NOT NULL,
    side        text NOT NULL CHECK (side IN ('executor', 'customer')),
    -- Стартовая страница роли: технологу без права решения задач не приходит,
    -- и открывать ему пустой инбокс незачем, а у администратора рекомендаций
    -- нет вовсе (решение 82).
    home        text NOT NULL,
    -- Умолчания при заведении пользователя, а не жёсткие свойства роли:
    -- право решения — свойство человека и переключается отдельно (решение 89).
    can_decide  boolean NOT NULL DEFAULT false,
    only_own    boolean NOT NULL DEFAULT false,
    -- Есть ли у роли рекомендации вообще. У администратора нет — ни зоны, ни
    -- счётчика в списке пользователей ему не показывают.
    has_recs    boolean NOT NULL DEFAULT true,
    note        text NOT NULL,
    sort        int NOT NULL
);

