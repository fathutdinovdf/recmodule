-- Отдельной роли «наблюдатель Заказчика» здесь нет намеренно. Наблюдатель —
-- это инженер, которому не выдали право решения: карточку он видит целиком,
-- вместе с нормативом ответа, и не хватает ему только кнопок (решение 89).
-- Заводить под это роль значит держать два способа описать одно состояние и
-- однажды получить инженера без права решения рядом с наблюдателем, у
-- которого право есть.

-- ============================ пользователи ============================

ALTER TABLE rec.users
    ADD COLUMN role_key      text REFERENCES rec.roles(key),
    -- Отбор по ответственному: у эксперта АКЭ рекомендация именная — он её
    -- выдал, он же ведёт её по телеметрии. Умолчание берётся из роли, но
    -- хранится у человека: в команде бывает и эксперт, ведущий чужие записи.
    ADD COLUMN only_own      boolean NOT NULL DEFAULT false,
    -- NULL означает «войти паролем нельзя». Так заводится пользователь,
    -- который придёт из ВМАП, и так же отключается вход, не удаляя человека:
    -- is_active гасит его целиком, вместе со списками ответственных.
    ADD COLUMN password_hash text,
    ADD COLUMN last_login_at timestamptz;

-- Роль существующим выводится из того, чем их различали раньше. Точнее
-- некуда: руководителя от рядового исполнителя в старой схеме отличало
-- только право правки экономики.
UPDATE rec.users SET role_key = CASE
    WHEN side = 'executor' AND can_edit_economy THEN 'expertLead'
    WHEN side = 'executor'                      THEN 'expert'
    ELSE 'engineer'
END WHERE role_key IS NULL;

UPDATE rec.users u SET only_own = r.only_own FROM rec.roles r WHERE r.key = u.role_key;

ALTER TABLE rec.users ALTER COLUMN role_key SET NOT NULL;

-- Сторона договора хранится и в роли, и у пользователя. Дублирование
-- намеренное: side участвует в десятке запросов и в домене, а разыменовывать
-- ради него роль в каждом — лишний JOIN. Расхождение исключается тем, что
-- side выставляется по роли при заведении и при её смене (см. rec.users_side).
CREATE FUNCTION rec.users_side() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
    SELECT side INTO NEW.side FROM rec.roles WHERE key = NEW.role_key;
    RETURN NEW;
END $$;

CREATE TRIGGER users_side BEFORE INSERT OR UPDATE OF role_key ON rec.users
    FOR EACH ROW EXECUTE FUNCTION rec.users_side();

-- ============================ сессии ============================

-- Сессия хранится в базе, а не подписанным куком. Разница одна, но решающая:
-- серверную сессию можно погасить — уволенный человек перестаёт входить в тот
-- же момент, когда сняли доступ, а не когда истечёт подписанный токен.
-- Секрет для подписи при этом не нужен вовсе, и терять его негде.
CREATE TABLE rec.sessions (
    -- Случайные 32 байта в base64url. Идентификатор сессии — это и есть
    -- секрет, поэтому он не выводится ни из логина, ни из времени.
    id           text PRIMARY KEY,
    user_id      bigint NOT NULL REFERENCES rec.users(id) ON DELETE CASCADE,
    created_at   timestamptz NOT NULL DEFAULT now(),
    last_seen_at timestamptz NOT NULL DEFAULT now(),
    expires_at   timestamptz NOT NULL,
    user_agent   text
);

CREATE INDEX ON rec.sessions (user_id);
CREATE INDEX ON rec.sessions (expires_at);
