-- Базовые значения: договорный способ, согласование Заказчика, вложения.
--
-- Приложение № 2, раздел «Формирование базовых значений», требует, чтобы база
-- была не числом, а числом ПЛЮС основанием: каким из способов получена, из
-- какого документа, и — для двух способов из трёх — с согласованием
-- Заказчика. Без этого число невозможно защитить в споре по разделу 10:
-- Заказчик вправе предъявить другой технологический режим или другие сутки, и
-- возразить будет нечем.

ALTER TABLE rec.baselines
  -- Способ по договору для дебитов жидкости и нефти.
  --
  --   techregime   — основной: значения утверждённого технологического режима,
  --                  действующего в месяце выдачи рекомендации. Применим
  --                  только если с момента утверждения режима до регистрации
  --                  не было изменений режима эксплуатации (см.
  --                  no_regime_changes ниже);
  --   threeDays    — средневзвешенные за трое суток до регистрации. Договор
  --                  ставит его под условие и прямо помечает «(по согласованию
  --                  с Заказчиком)» — односторонне не применяется;
  --   agreedPeriod — иной репрезентативный период, «по взаимному письменному
  --                  соглашению Сторон», когда кондиционных данных за трое
  --                  суток не набралось.
  --
  -- NULL допустим: у строк, заведённых до этой миграции, способа не
  -- записывали. Для новых форма требует его обязательно.
  ADD COLUMN method text
    CHECK (method IN ('techregime', 'threeDays', 'agreedPeriod')),

  -- Способ для энергопотребления — ОТДЕЛЬНЫЙ, и это не дублирование.
  -- Договор: «Поскольку утверждённый технологический режим не содержит
  -- значения потребления электрической энергии, базовое значение определяется
  -- по фактическим данным информационных систем». То есть из техрежима базу ЭЭ
  -- взять нельзя никогда, даже когда дебиты взяты именно оттуда.
  --
  --   factual   — по фактическим данным информационных систем;
  --   threeDays — средневзвешенное фактического потребления за тот же
  --               расчётный период, что и дебиты (когда те по threeDays);
  --   design    — расчётом в КИС ВМАП, модуль Design: применяется, когда
  --               достоверных данных нет, в том числе когда на станции
  --               управления нет выносного прибора учёта.
  ADD COLUMN method_ee text
    CHECK (method_ee IN ('factual', 'threeDays', 'design')),

  -- Утверждение эксперта: с момента утверждения технологического режима до
  -- регистрации рекомендации изменений режима эксплуатации не было.
  -- Договор ставит основной способ под это условие и перечисляет изменения
  -- (частота вращения ЭД, режим периодической скважины, ухудшение ГНО,
  -- изменение притока, техоперации, иные). Условие хранится явно: иначе выбор
  -- основного способа нечем обосновать, а проверить его задним числом уже
  -- нельзя.
  ADD COLUMN no_regime_changes boolean NOT NULL DEFAULT false,

  -- Согласование Заказчика. Требуется для threeDays («по согласованию с
  -- Заказчиком») и agreedPeriod («по взаимному письменному соглашению»).
  -- Само соглашение живёт вне модуля — письмом или протоколом, — поэтому
  -- здесь хранится факт и реквизиты, а не подпись.
  ADD COLUMN customer_agreed_at timestamptz,
  ADD COLUMN customer_agreed_by bigint REFERENCES rec.users(id),
  ADD COLUMN agreement_ref text;

-- Файл-обоснование привязывается к КОНКРЕТНОЙ версии базы, а не к
-- рекомендации: версий бывает несколько (исправление ошибки, принятая в споре
-- версия Заказчика), и документ у каждой свой. Без этой связи после первого
-- же исправления стало бы непонятно, какой файл к какой версии относится.
ALTER TABLE rec.attachments
  ADD COLUMN baseline_id bigint REFERENCES rec.baselines(id) ON DELETE CASCADE;

CREATE INDEX attachments_baseline_idx ON rec.attachments (baseline_id)
  WHERE baseline_id IS NOT NULL;

-- Цена электроэнергии, руб./кВт·ч, по месторождениям — рядом с остальными
-- ставками месторождения.
--
-- В расчёт ПОКА НЕ ВХОДИТ. Реализованная модель (шаблон АЛЬМА) списывает
-- энергию удельными ставками ee_liquid/ee_oil, пропорционально добыче, а не по
-- замеренному потреблению. Форма 5 Заказчика считает иначе — отдельной статьёй
-- «Эффект ЭЭ × цена ЭЭ», — и какая из двух моделей верна, Заказчику ещё
-- предстоит подтвердить. Столбец заведён, чтобы ставку было куда положить,
-- когда ответ придёт; складывать её с удельными статьями нельзя — это двойной
-- счёт одной и той же энергии.
ALTER TABLE rec.econ_field_rates
  ADD COLUMN ee_price numeric(12,4);
